def test_balanced_richardson_formula_and_laziness():
    """R_ib equals the analytic N² f² / |∇_h b|² and stays dask-backed."""
    lat = 30.0
    n2_val = 1.0e-5      # s⁻², typical stratification
    gradb2_val = 1.0e-9  # s⁻⁴, non-zero buoyancy gradient

    ds_merge = _make_ds_merge(lat)
    n2 = _dask_const(n2_val)
    gradb2 = _dask_const(gradb2_val)

    r_ib = cfad.balanced_richardson_number_3d(
        ds_merge, grid=None, n2=n2, gradb2=gradb2,
    )

    # The result must remain lazy (dask graph) before any .compute().
    assert isinstance(r_ib.data, da.Array), "R_ib must stay dask-backed"

    # Metadata wired through.
    assert r_ib.name == "R_ib"
    assert r_ib.attrs["units"] == "1"

    # Value matches the closed-form balanced Richardson number.
    f = _coriolis(lat)
    expected = n2_val * f**2 / gradb2_val
    np.testing.assert_allclose(r_ib.values, expected, rtol=1e-12)


def test_balanced_richardson_nan_where_grad_zero():
    """Columns with |∇_h b|² = 0 yield NaN; non-zero columns stay finite."""
    lat = 45.0
    ds_merge = _make_ds_merge(lat)
    n2 = _dask_const(1.0e-5)

    # One cell has a zero buoyancy gradient (undefined ratio → NaN),
    # the rest are finite.
    gradb2_np = np.full((1, 3, 3), 1.0e-9, dtype=float)
    gradb2_np[0, 1, 1] = 0.0
    gradb2 = xr.DataArray(
        da.from_array(gradb2_np, chunks=gradb2_np.shape),
        dims=("face", "j", "i"),
    )

    r_ib = cfad.balanced_richardson_number_3d(
        ds_merge, grid=None, n2=n2, gradb2=gradb2,
    ).values

    assert np.isnan(r_ib[0, 1, 1]), "zero-gradient cell must be NaN"
    finite_mask = np.ones((1, 3, 3), dtype=bool)
    finite_mask[0, 1, 1] = False
    assert np.isfinite(r_ib[finite_mask]).all(), "other cells must be finite"


def test_balanced_richardson_zero_at_equator():
    """At the equator f → 0, so R_ib → 0 (finite, not NaN)."""
    ds_merge = _make_ds_merge(0.0)
    n2 = _dask_const(1.0e-5)
    gradb2 = _dask_const(1.0e-9)  # non-zero so the ratio is defined

    r_ib = cfad.balanced_richardson_number_3d(
        ds_merge, grid=None, n2=n2, gradb2=gradb2,
    ).values

    np.testing.assert_allclose(r_ib, 0.0, atol=0.0)
