def test_balanced_richardson_against_real_tile(tmp_path):
    """Compute R_ib on a real LLC4320 tile and check the metadata is written.

    Network-dependent integration test, mirroring the real-grid approach of
    ``test_generate_tile.test_rect_ij_to_tile_against_grid_zarr``:

    1. Resolve a single 720×720 tile (mid-grid pixel → an open-ocean tile on
       face 4) and load its *real* grid (XC, YC, Z, dxC, dyC, CS, SN, drF)
       plus Theta/Salt for one snapshot from the LLC4320 S3 store.
    2. Slice the staggered dims (i_g, j_g) to the tile extent — the tile
       loaders slice only the tracer dims (i, j) — so center/face dim
       lengths match and a single-face xgcm grid (no face connections) is
       well-formed.
    3. Run the production ``balanced_richardson_number_3d`` and reduce to
       the surface via ``apply_depth_strategies`` — the same path the
       ``mixing_parameters`` subset uses.
    4. Write the field + provenance to a NetCDF, reload, and assert the
       field/provenance **metadata round-trips correctly**, and that the
       tile interior (away from the fill-boundary edges) is finite.

    Parameters
    ----------
    tmp_path : pathlib.Path
        pytest-provided temporary directory for the NetCDF round-trip.

    Returns
    -------
    None
        Passes by assertion; raises AssertionError on mismatch.

    Notes
    -----
    Requires network access to the LLC4320 S3 store.  Deselect for offline
    runs (see the module docstring).

    Generated by JXP and Claude
    """
    # Lazy imports keep import-time cheap for the offline tests above.
    import dbof.tiles.tile_utils as tu
    from dbof.tiles.tile_mapping import rect_ij_to_tile
    from dbof.llc4320_ingestion.grid import set_xgcm_grid
    from dbof.preprocessing.depth_strategies import apply_depth_strategies

    s3 = tu._resolve_s3_source(None)
    timestamp = "2012-11-09 12:00:00"

    # Mid-grid pixel → an open-ocean tile with real stratification.
    tile = rect_ij_to_tile(5000, 5000)

    # Real grid for the tile (eagerly loaded; size-1 face dim).
    ds_grid = tu._load_grid_for_tile(s3, tile)
    # Real tracers (only what R_ib needs) for one snapshot, lazily.
    ds_tracers = tu._load_tracers_for_tile(
        s3, timestamp, tile, vars_needed=["Theta", "Salt"],
    )

    # Slice the staggered dims (i_g, j_g) to the same 720-wide extent as the
    # tracer dims so the single-face xgcm grid is well-formed.
    ds_grid = ds_grid.isel(i_g=tile.i_face_slice, j_g=tile.j_face_slice)
    ds_merge = xr.merge([ds_grid, ds_tracers])

    # Single-face tile → no face connections.  Drop the vertical coords
    # xgcm doesn't need (they stay in ds_merge for the N² derivative).
    vvars = [v for v in ("Z", "Zl", "Zu", "Zp1", "drF") if v in ds_grid]
    grid = set_xgcm_grid(ds_grid.drop_vars(vvars), use_connections=False)

    # Production field function + surface depth reduction (mixing_parameters
    # path), then a single materialisation of the 2D result.
    rib_3d = cfad.balanced_richardson_number_3d(ds_merge, grid)
    rib_sfc = apply_depth_strategies(
        rib_3d, "R_ib", ds_merge, mld=None, requested={"R_ib_sfc"},
    )["R_ib_sfc"].compute()

    # Drop the size-1 face dim for a clean (j, i) output.
    if "face" in rib_sfc.dims:
        rib_sfc = rib_sfc.isel(face=0)

    # The tile interior (away from the fill-boundary edges) must be finite.
    interior = rib_sfc.values[5:-5, 5:-5]
    assert np.isfinite(interior).mean() > 0.95, (
        "R_ib interior should be predominantly finite over open ocean"
    )

    # --- Assemble field + provenance metadata and write to NetCDF. ---
    grid2d = ds_grid.isel(face=0)
    ds_out = rib_sfc.to_dataset(name="R_ib").assign_coords(
        XC=grid2d["XC"], YC=grid2d["YC"],
    )
    ds_out.attrs.update({
        "timestamp":  timestamp,
        "tile_index": tile.tile_idx,
        "face_index": tile.face_idx,
        "property":   "R_ib",
    })
    out_path = tmp_path / "R_ib_tile.nc"
    ds_out.to_netcdf(out_path, engine="h5netcdf")

    # --- Reload and confirm the metadata was written correctly. ---
    ds_re = xr.open_dataset(out_path, engine="h5netcdf")
    try:
        # Field-level metadata (set by balanced_richardson_number_3d).
        assert "R_ib" in ds_re
        assert ds_re["R_ib"].attrs["long_name"] == \
            "Balanced Richardson number"
        assert ds_re["R_ib"].attrs["units"] == "1"
        # Provenance metadata.
        assert ds_re.attrs["timestamp"] == timestamp
        assert int(ds_re.attrs["tile_index"]) == tile.tile_idx
        assert int(ds_re.attrs["face_index"]) == tile.face_idx
        assert ds_re.attrs["property"] == "R_ib"
        # Coordinates written alongside the field.
        assert ds_re["R_ib"].sizes == {"j": 720, "i": 720}
    finally:
        ds_re.close()
