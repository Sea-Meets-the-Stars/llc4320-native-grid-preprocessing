def _make_ds_merge(lat_value, shape=(1, 3, 3)):
    """Synthetic ds_merge carrying only latitude ``YC`` (dims face, j, i).

    Parameters
    ----------
    lat_value : float
        Constant latitude [deg N] to populate ``YC`` with.
    shape : tuple of int, optional
        (face, j, i) shape of the synthetic field (default (1, 3, 3)).

    Returns
    -------
    xr.Dataset
        Dataset whose only variable is ``YC`` — all that
        ``coriolis_parameter`` needs.
    """
    yc = np.full(shape, lat_value, dtype=float)
    return xr.Dataset(
        data_vars={"YC": (("face", "j", "i"), yc)},
    )


def _dask_const(value, shape=(1, 3, 3)):
    """Dask-backed constant DataArray on (face, j, i).

    Parameters
    ----------
    value : float
        Constant fill value.
    shape : tuple of int, optional
        (face, j, i) shape (default (1, 3, 3)).

    Returns
    -------
    xr.DataArray
        Lazy (dask-backed) DataArray filled with *value*.
    """
    arr = da.full(shape, value, dtype=float, chunks=shape)
    return xr.DataArray(arr, dims=("face", "j", "i"))


def _coriolis(lat_value):
    """Analytic Coriolis parameter f = 2 Ω sin(lat) for the test.

    Parameters
    ----------
    lat_value : float
        Latitude [deg N].

    Returns
    -------
    float
        Coriolis parameter f [s⁻¹].
    """
    return 2.0 * OMEGA_EARTH * np.sin(np.deg2rad(lat_value))


