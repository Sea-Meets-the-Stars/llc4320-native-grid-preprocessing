"""
Tests for the balanced Richardson number field in
``dbof.preprocessing.calculated_fields_at_depth``.

Follows the synthetic-data philosophy of ``tests/test_generate_tile.py``:
build tiny in-memory, dask-backed arrays so the tests run in milliseconds
with no network or model I/O.  The genuinely unit-testable core of
``balanced_richardson_number_3d`` is its composition formula
R_ib = N² f² / |∇_h b|² and its edge cases (NaN where |∇_h b|² = 0; R_ib → 0
at the equator).  Both N² and |∇_h b|² are injected via the function's
``n2`` / ``gradb2`` keywords so the test exercises the production formula
without standing up an xgcm grid (the heavy N² and gradient internals are
covered by their own field functions and the integration pipeline).

Generated by JXP and Claude
"""

# third-party
import numpy as np
import dask.array as da
import xarray as xr

# code under test
import dbof.preprocessing.calculated_fields_at_depth as cfad
from dbof.preprocessing.physical_constants import OMEGA_EARTH


# ---------------------------------------------------------------------------
# Helpers (private to the tests)
# ---------------------------------------------------------------------------

def _make_ds_merge(lat_value, shape=(1, 3, 3)):
    """Synthetic ds_merge carrying only latitude ``YC`` (dims face, j, i).

    Parameters
    ----------
    lat_value : float
        Constant latitude [deg N] to populate ``YC`` with.
    shape : tuple of int, optional
        (face, j, i) shape of the synthetic field (default (1, 3, 3)).

    Returns
    -------
    xr.Dataset
        Dataset whose only variable is ``YC`` — all that
        ``coriolis_parameter`` needs.
    """
    yc = np.full(shape, lat_value, dtype=float)
    return xr.Dataset(
        data_vars={"YC": (("face", "j", "i"), yc)},
    )


def _dask_const(value, shape=(1, 3, 3)):
    """Dask-backed constant DataArray on (face, j, i).

    Parameters
    ----------
    value : float
        Constant fill value.
    shape : tuple of int, optional
        (face, j, i) shape (default (1, 3, 3)).

    Returns
    -------
    xr.DataArray
        Lazy (dask-backed) DataArray filled with *value*.
    """
    arr = da.full(shape, value, dtype=float, chunks=shape)
    return xr.DataArray(arr, dims=("face", "j", "i"))


def _coriolis(lat_value):
    """Analytic Coriolis parameter f = 2 Ω sin(lat) for the test.

    Parameters
    ----------
    lat_value : float
        Latitude [deg N].

    Returns
    -------
    float
        Coriolis parameter f [s⁻¹].
    """
    return 2.0 * OMEGA_EARTH * np.sin(np.deg2rad(lat_value))


