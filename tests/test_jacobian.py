@pytest.mark.slow
@pytest.mark.network
@pytest.mark.skipif(not RUN_NETWORK,
                    reason="needs network/S3; set RUN_LLC_NETWORK_TESTS=1")
def test_jacobian_real_grid_constant_field_zero_gradient():
    """Test Case F: a constant field has ~zero gradient on the real grid.

    Feeds a spatially constant model velocity field through
    ``calculate_jacobian`` on the *real* curvilinear LLC4320 grid (with its
    true ``CS``/``SN``, metrics and 13-face ``face_connections``) and checks
    that the returned gradient tensor is essentially zero over the ocean
    interior.

    Why a robust statistic, not the global max: the ECCO routine rotates the
    velocity into geographic axes *before* differencing, so it differentiates
    ``u_lambda = U0*CS - V0*SN``.  Where the grid rotation ``CS``/``SN`` is
    locally smooth (the overwhelming majority of ocean points) this is
    constant and its gradient is zero to machine precision.  Near grid
    singularities (the Arctic-cap face and cube-sphere face corners) the real
    term ``grad(CS)`` is large, so a constant field there legitimately
    acquires an apparent gradient.  That is physics of the grid, not a bug,
    so we assert on the median and a high percentile rather than the max:

    - median over ocean interior is at machine precision (empirically
      ~3e-17), proving the diff / interp / metric machinery introduces no
      spurious gradient for constant fields;
    - the 99th percentile is tiny (empirically ~5e-7), proving the bulk of
      the grid is unaffected by curvature.

    Returns
    -------
    None
        Passes by assertion; raises AssertionError on mismatch.

    Generated by JXP and Claude
    """
    ds = load_real_llc_grid()
    grid = set_xgcm_grid(ds.drop_vars("hFacC"), use_connections=True)

    # Arbitrary non-zero constant model velocities; values must not matter.
    u_x, v_y = add_constant_velocity(ds, u0=0.5, v0=-0.3)

    outputs = ng.calculate_jacobian(u_x, v_y, ds, grid)

    # Ocean mask (hFacC > 0), with the face-edge ring trimmed as elsewhere.
    ocean = interior(ds["hFacC"]).values > 0
    assert ocean.any()

    # Pool all four components over the ocean interior.
    pooled = np.concatenate(
        [np.abs(interior(out).values[ocean]) for out in outputs])

    assert np.all(np.isfinite(pooled))           # no NaN/inf leaked in
    # Median is machine-precision zero (huge margin over the ~3e-17 seen).
    assert np.median(pooled) < 1e-12
    # The bulk of the grid is unaffected by curvature (~5e-7 observed).
    assert np.percentile(pooled, 99.0) < 1e-5

    # Outputs honour the tracer-point coordinate contract.
    for out in outputs:
        assert "i_g" not in out.dims and "j_g" not in out.dims
        assert set(("face", "j", "i")).issubset(out.dims)


def load_real_llc_surface_velocity(cache_path=REAL_UV_CACHE):
    """Load real LLC4320 surface ``U``/``V``, caching locally.

    Reads the surface (k=0) model-frame velocity components from the
    LLC_SURF OSN kerchunk store via
    :func:`get_raw_data.get_remote_llc_data` and caches them to a local
    NetCDF.  The OSN store holds only the surface level, so this is a true
    surface-only read (~2 GB) -- unlike the LLC_DEPTH timestep stores, which
    chunk all 51 vertical levels together.

    Parameters
    ----------
    cache_path : str
        Path to the local NetCDF cache.  Defaults to ``REAL_UV_CACHE``
        (overridable via the ``LLC_TEST_UV_CACHE`` env var).

    Returns
    -------
    u_x : xarray.DataArray
        Zonal model-frame velocity on U points ``(face, j, i_g)``.
    v_y : xarray.DataArray
        Meridional model-frame velocity on V points ``(face, j_g, i)``.

    Generated by JXP and Claude
    """
    if os.path.exists(cache_path):
        uv = xr.open_dataset(cache_path)
        return uv["U"], uv["V"]

    # Import here so a default (no-network) test run never imports the OSN
    # ingestion stack.
    from dbof.llc4320_ingestion import get_raw_data
    from dbof.global_dataset_creation.data_sources import OSN_ENDPOINT
    from dbof.global_dataset_creation.iterations import osn_date_to_iteration

    it = osn_date_to_iteration(REAL_UV_DATE)
    ds = get_raw_data.get_remote_llc_data(OSN_ENDPOINT, it, range(N_FACES))
    u_x = ds["U"].astype("float32").compute()
    v_y = ds["V"].astype("float32").compute()

    try:
        xr.Dataset({"U": u_x, "V": v_y}).to_netcdf(cache_path)
    except OSError:
        pass
    return u_x, v_y


def model_frame_jacobian(u_x, v_y, ds, grid):
    """Return the Jacobian with the grid rotation forced to the identity.

    Re-runs ``calculate_jacobian`` on a copy of ``ds`` whose rotation
    coefficients are ``CS=1, SN=0`` (identity), so the four outputs are the
    *model-frame* velocity gradients -- the rotation step is a no-op.  This
    is the reference against which the geographic (real-``CS``/``SN``)
    Jacobian's trace and antisymmetric part are compared in Case G.

    Parameters
    ----------
    u_x, v_y : xarray.DataArray
        Model-frame velocity components on U / V points.
    ds : xarray.Dataset
        Real grid dataset (provides ``dxC``, ``dyC``; its ``CS``/``SN`` are
        overridden).
    grid : xgcm.Grid
        Grid object with the LLC ``face_connections``.

    Returns
    -------
    tuple of xarray.DataArray
        ``(du_dx, du_dy, dv_dx, dv_dy)`` in the model frame.

    Generated by JXP and Claude
    """
    ds_id = ds.copy()
    ds_id["CS"] = xr.ones_like(ds["CS"])
    ds_id["SN"] = xr.zeros_like(ds["SN"])
    return ng.calculate_jacobian(u_x, v_y, ds_id, grid)


@pytest.mark.slow
@pytest.mark.network
@pytest.mark.skipif(not RUN_NETWORK,
                    reason="needs network/S3; set RUN_LLC_NETWORK_TESTS=1")
def test_jacobian_real_grid_rotation_invariance_trace_curl():
    """Test Case G: trace and curl are rotation-invariant on the real grid.

    Divergence (the trace ``du_lambda_dlambda + dv_phi_dphi``) and vorticity
    (the antisymmetric part ``dv_phi_dlambda - du_lambda_dphi``) are
    invariants of the velocity-gradient tensor under an orthogonal rotation
    of the frame.  So the geographic-frame divergence/vorticity from
    ``calculate_jacobian`` (using the real ``CS``/``SN``) must match the
    model-frame divergence/vorticity (identity rotation) computed from the
    *same* real velocities -- a strong, truth-free correctness check of the
    rotation logic.

    The match is not bit-exact everywhere: because the routine differences
    the *rotated* field, spatially-varying ``CS``/``SN`` inject ``grad(CS)``
    terms near grid singularities (Arctic cap, cube-sphere corners).  These
    are real and tiny, so we assert robust statistics:

    - the signal is genuinely non-zero (model-frame divergence RMS is
      O(1e-5)), so this is not a trivial 0 == 0 comparison;
    - the median absolute difference is ~0 (bit-identical where the rotation
      is locally smooth -- the bulk of the ocean);
    - the difference RMS is < 2% of the signal RMS (empirically ~0.3%);
    - the 99th-percentile absolute difference is tiny (empirically ~2e-7).

    Returns
    -------
    None
        Passes by assertion; raises AssertionError on mismatch.

    Generated by JXP and Claude
    """
    ds = load_real_llc_grid()
    grid = set_xgcm_grid(ds.drop_vars("hFacC"), use_connections=True)

    u_x, v_y = load_real_llc_surface_velocity()
    # Align coords to the grid so xgcm pairs the staggered axes correctly.
    u_x = u_x.assign_coords(
        {c: ds.coords[c] for c in u_x.dims if c in ds.coords})
    v_y = v_y.assign_coords(
        {c: ds.coords[c] for c in v_y.dims if c in ds.coords})

    geo = ng.calculate_jacobian(u_x, v_y, ds, grid)        # real CS/SN
    mod = model_frame_jacobian(u_x, v_y, ds, grid)         # identity

    # Divergence (trace) and vorticity (antisymmetric part) in each frame.
    geo_div, mod_div = geo[0] + geo[3], mod[0] + mod[3]
    geo_vort, mod_vort = geo[2] - geo[1], mod[2] - mod[1]

    ocean = interior(ds["hFacC"]).values > 0
    for geo_inv, mod_inv in ((geo_div, mod_div), (geo_vort, mod_vort)):
        g_vals = interior(geo_inv).values[ocean]
        m_vals = interior(mod_inv).values[ocean]
        finite = np.isfinite(g_vals) & np.isfinite(m_vals)
        g_vals, m_vals = g_vals[finite], m_vals[finite]

        signal_rms = np.sqrt(np.mean(m_vals ** 2))
        diff = np.abs(g_vals - m_vals)
        diff_rms = np.sqrt(np.mean(diff ** 2))

        # Real, non-trivial signal -- not a 0 == 0 comparison.
        assert signal_rms > 1e-6
        # Bit-identical where the rotation is locally smooth.
        assert np.median(diff) < 1e-10
        # Invariant to < 2% RMS (the grad(rotation) residual is ~0.3%).
        assert diff_rms / signal_rms < 2e-2
        # The bulk of points agree to ~machine precision.
        assert np.percentile(diff, 99.0) < 1e-6
