# LLC4320 has 13 faces; the synthetic grid reproduces all of them so the
# xgcm ``face_connections`` machinery is exercised by the tests.
N_FACES = 13

# Number of cells trimmed from every face edge before comparing to the
# analytic answer.  The X/Y chains each apply interp -> diff -> interp, so
# boundary fill / cross-face halo values can leak up to ~3 cells inward.
EDGE_MARGIN = 3


def make_synthetic_grid(n=16, d=2500.0, cs=1.0, sn=0.0, dy=None):
    """Build a 13-face synthetic LLC-like grid with uniform metrics.

    Parameters
    ----------
    n : int
        Number of cells per face along each horizontal dimension.  Must be
        comfortably larger than ``2 * EDGE_MARGIN`` so an interior remains.
    d : float
        Uniform grid spacing in metres for ``dxC`` (and for ``dyC`` when
        *dy* is None).
    cs, sn : float
        Spatially constant grid-rotation coefficients ``CS = cos(alpha)``
        and ``SN = sin(alpha)`` stored on tracer points.
    dy : float or None
        Uniform ``dyC`` spacing in metres.  When given and different from
        *d* the grid is **anisotropic** (dxC != dyC), which catches any
        accidental swap of the two metrics -- on an isotropic grid such a
        swap is invisible.  None (default) keeps ``dyC = d``.

    Returns
    -------
    ds : xarray.Dataset
        Grid dataset holding ``CS``, ``SN`` (tracer points ``(face, j, i)``),
        ``dxC`` (U points ``(face, j, i_g)``) and ``dyC`` (V points
        ``(face, j_g, i)``), with the comodo ``axis`` /
        ``c_grid_axis_shift`` attributes xgcm needs.
    grid : xgcm.Grid
        Grid built with the production LLC ``face_connections``.

    Generated by JXP and Claude
    """
    # 1-D index coordinates.  i_g/j_g are the staggered (cell-edge) axes;
    # the comodo attributes tell xgcm how each axis relates to the centre.
    idx = np.arange(n)
    coords = {
        "face": ("face", np.arange(N_FACES)),
        "i": ("i", idx, {"axis": "X"}),
        "i_g": ("i_g", idx, {"axis": "X", "c_grid_axis_shift": 0.5}),
        "j": ("j", idx, {"axis": "Y"}),
        "j_g": ("j_g", idx, {"axis": "Y", "c_grid_axis_shift": 0.5}),
    }

    # Rotation coefficients live on tracer points (face, j, i).
    cs_da = xr.DataArray(np.full((N_FACES, n, n), cs),
                         dims=("face", "j", "i"))
    sn_da = xr.DataArray(np.full((N_FACES, n, n), sn),
                         dims=("face", "j", "i"))

    # Cell-spacing metrics: dxC on U points, dyC on V points.  dy defaults
    # to d (isotropic); pass dy != d for an anisotropic grid.
    if dy is None:
        dy = d
    dxc = xr.DataArray(np.full((N_FACES, n, n), d),
                       dims=("face", "j", "i_g"))
    dyc = xr.DataArray(np.full((N_FACES, n, n), dy),
                       dims=("face", "j_g", "i"))

    ds = xr.Dataset(
        {"CS": cs_da, "SN": sn_da, "dxC": dxc, "dyC": dyc},
        coords=coords,
    )

    # Reuse the production grid constructor (with LLC face connections).
    grid = set_xgcm_grid(ds, use_connections=True)
    return ds, grid


def add_linear_velocity(ds, d, a, b, e, f, dy=None):
    """Add linear ``U`` and ``V`` velocity fields to the synthetic grid.

    The fields are ``u = a*x + b*y`` on U points and ``v = e*x + f*y`` on
    V points, where ``x`` / ``y`` are position in metres (index times the
    uniform spacing along each axis).  Linear fields are chosen because
    finite differences and linear interpolation reproduce them exactly, so
    the computed gradient tensor equals the analytic ``J_model = [[a, b],
    [e, f]]`` (before rotation) to machine precision.  Only slopes matter
    for the result, so any constant position offset is irrelevant.

    Parameters
    ----------
    ds : xarray.Dataset
        Synthetic grid from :func:`make_synthetic_grid`; modified in place
        to carry ``U`` and ``V``.
    d : float
        Uniform x grid spacing in metres (must match the grid's ``dxC``).
    a, b : float
        Zonal-velocity slopes du/dx and du/dy (model basis).
    e, f : float
        Meridional-velocity slopes dv/dx and dv/dy (model basis).
    dy : float or None
        Uniform y grid spacing in metres (must match the grid's ``dyC``).
        None (default) uses *d* (isotropic grid).

    Returns
    -------
    u_x : xarray.DataArray
        Zonal velocity on U points ``(face, j, i_g)``.
    v_y : xarray.DataArray
        Meridional velocity on V points ``(face, j_g, i)``.

    Generated by JXP and Claude
    """
    n = ds.sizes["i"]
    if dy is None:
        dy = d
    pos_x = np.arange(n) * d   # positions along the model-x axis
    pos_y = np.arange(n) * dy  # positions along the model-y axis

    # U on (face, j, i_g): varies as a*x along i_g and b*y along j.
    u2d = a * pos_x[None, :] + b * pos_y[:, None]      # (j, i_g)
    u3d = np.broadcast_to(u2d, (N_FACES, n, n)).copy()
    u_x = xr.DataArray(u3d, dims=("face", "j", "i_g"),
                       coords={c: ds.coords[c]
                               for c in ("face", "j", "i_g")},
                       name="U")

    # V on (face, j_g, i): varies as e*x along i and f*y along j_g.
    v2d = e * pos_x[None, :] + f * pos_y[:, None]      # (j_g, i)
    v3d = np.broadcast_to(v2d, (N_FACES, n, n)).copy()
    v_y = xr.DataArray(v3d, dims=("face", "j_g", "i"),
                       coords={c: ds.coords[c]
                               for c in ("face", "j_g", "i")},
                       name="V")

    ds["U"] = u_x
    ds["V"] = v_y
    return u_x, v_y


def interior(da, margin=EDGE_MARGIN):
    """Return the face interior, trimming ``margin`` cells from each edge.

    Edge cells are excluded because boundary fill and cross-face halo
    exchange (through ``face_connections``) inject values from inconsistent
    neighbouring linear fields, which are not part of the analytic answer.

    Parameters
    ----------
    da : xarray.DataArray
        Field on tracer points with ``i`` and ``j`` dimensions.
    margin : int
        Number of cells to drop from each edge along ``i`` and ``j``.

    Returns
    -------
    xarray.DataArray
        The trimmed interior region.

    Generated by JXP and Claude
    """
    return da.isel(i=slice(margin, -margin), j=slice(margin, -margin))


def analytic_rotated_jacobian(a, b, e, f, cs, sn):
    """Return the analytic geographic Jacobian ``R . J_model . R^T``.

    The two rotations inside ``calculate_jacobian`` compose to a single
    similarity transform of the model-basis gradient tensor
    ``J_model = [[a, b], [e, f]]`` by the orthogonal rotation
    ``R = [[CS, -SN], [SN, CS]]``.  For spatially constant ``CS, SN`` and
    linear velocity fields this transform is the exact expected interior
    result, component by component.

    Parameters
    ----------
    a, b : float
        Zonal-velocity slopes du/dx and du/dy (model basis).
    e, f : float
        Meridional-velocity slopes dv/dx and dv/dy (model basis).
    cs, sn : float
        Rotation coefficients ``CS = cos(alpha)`` and ``SN = sin(alpha)``.

    Returns
    -------
    du_lambda_dlambda, du_lambda_dphi, dv_phi_dlambda, dv_phi_dphi : float
        The four entries of ``R . J_model . R^T`` in the order returned by
        :func:`dbof.utils.native_gradient.calculate_jacobian`.

    Generated by JXP and Claude
    """
    # M = R . J_model.
    m00 = cs * a - sn * e
    m01 = cs * b - sn * f
    m10 = sn * a + cs * e
    m11 = sn * b + cs * f
    # (M . R^T) with R^T = [[CS, SN], [-SN, CS]].
    dudl = m00 * cs - m01 * sn
    dudp = m00 * sn + m01 * cs
    dvdl = m10 * cs - m11 * sn
    dvdp = m10 * sn + m11 * cs
    return dudl, dudp, dvdl, dvdp


def add_constant_velocity(ds, u0, v0):
    """Add spatially constant ``U`` and ``V`` fields to the synthetic grid.

    A constant field has zero gradient everywhere, so after any rotation
    ``calculate_jacobian`` must return zeros on every face interior.  This
    isolates the rotation machinery: any non-zero interior gradient would
    be a spurious gradient introduced by the rotation, not by the data.

    Parameters
    ----------
    ds : xarray.Dataset
        Synthetic grid from :func:`make_synthetic_grid`; modified in place.
    u0 : float
        Constant zonal-velocity value placed on U points.
    v0 : float
        Constant meridional-velocity value placed on V points.

    Returns
    -------
    u_x : xarray.DataArray
        Constant zonal velocity on U points ``(face, j, i_g)``.
    v_y : xarray.DataArray
        Constant meridional velocity on V points ``(face, j_g, i)``.

    Generated by JXP and Claude
    """
    n = ds.sizes["i"]
    # Build constant fields directly on the staggered velocity points.
    u_x = xr.DataArray(np.full((N_FACES, n, n), u0),
                       dims=("face", "j", "i_g"),
                       coords={c: ds.coords[c]
                               for c in ("face", "j", "i_g")},
                       name="U")
    v_y = xr.DataArray(np.full((N_FACES, n, n), v0),
                       dims=("face", "j_g", "i"),
                       coords={c: ds.coords[c]
                               for c in ("face", "j_g", "i")},
                       name="V")
    ds["U"] = u_x
    ds["V"] = v_y
    return u_x, v_y


def test_jacobian_no_rotation_recovers_model_gradients():
    """Test Case A: with CS=1, SN=0 the Jacobian equals the model gradients.

    When the grid rotation is the identity (``CS=1, SN=0``) the geographic
    axes coincide with the model axes, so ``R . J_model . R^T = J_model``.
    For the linear velocity fields ``u = a*x + b*y`` and ``v = e*x + f*y``
    the four returned components must therefore equal the constant slopes:

        du_lambda_dlambda = a,   du_lambda_dphi = b,
        dv_phi_dlambda    = e,   dv_phi_dphi    = f,

    everywhere in each face interior, to machine precision.  This validates
    the derivative values and the ``/dxC``, ``/dyC`` metric scaling.

    Returns
    -------
    None
        Passes by assertion; raises AssertionError on mismatch.

    Generated by JXP and Claude
    """
    # Uniform spacing and realistic O(1e-5 s^-1) velocity-gradient slopes.
    d = 2500.0
    a, b, e, f = 1.0e-5, 2.0e-5, -3.0e-5, 4.0e-5

    # Identity rotation: CS=1, SN=0.
    ds, grid = make_synthetic_grid(n=16, d=d, cs=1.0, sn=0.0)
    u_x, v_y = add_linear_velocity(ds, d, a, b, e, f)

    dudl, dudp, dvdl, dvdp = ng.calculate_jacobian(u_x, v_y, ds, grid)

    # Compare the trimmed interior of every face to the analytic constants.
    # rtol handles the ~1e-15 rounding from the multiply/divide chain.
    tol = dict(rtol=1e-9, atol=0.0)
    np.testing.assert_allclose(interior(dudl).values, a, **tol)
    np.testing.assert_allclose(interior(dudp).values, b, **tol)
    np.testing.assert_allclose(interior(dvdl).values, e, **tol)
    np.testing.assert_allclose(interior(dvdp).values, f, **tol)

    # Sanity: outputs are on tracer points (no staggered dims survive).
    for out in (dudl, dudp, dvdl, dvdp):
        assert "i_g" not in out.dims
        assert "j_g" not in out.dims
        assert set(("face", "j", "i")).issubset(out.dims)


def test_jacobian_90deg_rotation_sign_conventions():
    """Test Case B: a 90-degree grid rotation checks the sign conventions.

    With ``CS=0, SN=1`` the rotation is a quarter turn and
    ``R . J_model . R^T = [[f, -e], [-b, a]]``.  For the linear fields the
    four returned components must therefore equal, on each face interior:

        du_lambda_dlambda =  f,   du_lambda_dphi = -e,
        dv_phi_dlambda    = -b,   dv_phi_dphi    =  a.

    The flipped signs and swapped roles exercise exactly the part of the
    code most prone to a sign error in either rotation.

    Returns
    -------
    None
        Passes by assertion; raises AssertionError on mismatch.

    Generated by JXP and Claude
    """
    d = 2500.0
    a, b, e, f = 1.0e-5, 2.0e-5, -3.0e-5, 4.0e-5

    # Quarter-turn rotation: CS=0, SN=1.
    ds, grid = make_synthetic_grid(n=16, d=d, cs=0.0, sn=1.0)
    u_x, v_y = add_linear_velocity(ds, d, a, b, e, f)

    dudl, dudp, dvdl, dvdp = ng.calculate_jacobian(u_x, v_y, ds, grid)

    # Analytic targets for a 90-degree rotation: [[f, -e], [-b, a]].
    t_dudl, t_dudp, t_dvdl, t_dvdp = analytic_rotated_jacobian(
        a, b, e, f, cs=0.0, sn=1.0)

    tol = dict(rtol=1e-7, atol=1e-12)
    np.testing.assert_allclose(interior(dudl).values, t_dudl, **tol)
    np.testing.assert_allclose(interior(dudp).values, t_dudp, **tol)
    np.testing.assert_allclose(interior(dvdl).values, t_dvdl, **tol)
    np.testing.assert_allclose(interior(dvdp).values, t_dvdp, **tol)


def test_jacobian_rotation_only_constant_field_zero_gradient():
    """Test Case C: a rotated constant field has zero gradient everywhere.

    With a non-trivial rotation (45 degrees here) but a spatially constant
    velocity field, the true gradient is identically zero.  The rotation
    mixes the (constant) components but cannot manufacture spatial
    structure, so every interior component must be zero to machine
    precision.  Any non-zero interior value would reveal the rotation
    machinery injecting spurious gradients.

    Returns
    -------
    None
        Passes by assertion; raises AssertionError on mismatch.

    Generated by JXP and Claude
    """
    d = 2500.0
    alpha = np.radians(45.0)
    cs, sn = np.cos(alpha), np.sin(alpha)

    # Arbitrary non-zero constant velocities; their values must not matter.
    u0, v0 = 0.37, -0.12

    ds, grid = make_synthetic_grid(n=16, d=d, cs=cs, sn=sn)
    u_x, v_y = add_constant_velocity(ds, u0, v0)

    dudl, dudp, dvdl, dvdp = ng.calculate_jacobian(u_x, v_y, ds, grid)

    # Gradient of a constant is exactly zero on the interior.
    for out in (dudl, dudp, dvdl, dvdp):
        np.testing.assert_allclose(interior(out).values, 0.0, atol=1e-15)


