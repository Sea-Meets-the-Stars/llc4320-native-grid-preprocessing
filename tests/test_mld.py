"""
Tests for the mixed-layer-depth estimators in
``dbof.preprocessing.calculate_fields_at_depth``:

- ``mixed_layer_depth``     — threshold (Bodner et al.) MLD, the project default
- ``mixed_layer_depth_DI``  — Depth Integration Method (N²-weighted mean depth)

Follows the synthetic-data philosophy of
``tests/test_calculate_fields_at_depth.py``: build tiny in-memory,
dask-backed arrays so the unit tests run in milliseconds with no network or
model I/O.

The Depth Integration estimator is exercised through its ``n2`` keyword so the
production reduction formula

    MLD_DI = Σ_{z≤H} z N² dz / Σ_{z≤H} N² dz

is tested directly (weighting, the integration-depth cutoff, and the
N² < 0 → 0 floor) without standing up an xgcm grid. The threshold estimator is
exercised on a synthetic two-layer profile: a well-mixed upper layer over a
sharp cold (denser) layer, where the answer is the deepest uniform level
regardless of the exact JMD95 density values.

One file-dependent test (``test_mld_di_on_real_density_tile``) loads the local
LLC4320 density tile (``sigma0`` only) named in ``prompts/mld.md``, builds N²
from σ₀, and confirms ``mixed_layer_depth_DI`` produces a sensible interior
field. It is skipped automatically when the tile (or ``OS_OGCM``) is absent.

Generated by JXP and Claude
"""

# stdlib
import os

# third-party
import numpy as np
import dask.array as da
import xarray as xr
import pytest

# code under test
import dbof.preprocessing.calculate_fields_at_depth as cfad
from dbof.preprocessing.physical_constants import (
    G,
    RHO0_REFERENCE,
    MLD_INTEGRATION_DEPTH_M,
)
from dbof.preprocessing.vertical_helpers import _vertical_derivative


# ---------------------------------------------------------------------------
# Helpers (private to the tests)
# ---------------------------------------------------------------------------

# Synthetic, evenly spaced vertical grid: 8 tracer levels, 10 m thick,
# centres at 5, 15, ..., 75 m (positive downward).
_Z_POS = np.arange(5.0, 80.0, 10.0)          # [5, 15, ..., 75]
_DRF = np.full(_Z_POS.shape, 10.0)           # uniform 10 m layer thickness


def _grid_ds():
    """Synthetic ``ds_merge`` carrying only the vertical grid.

    Provides ``Z`` (MITgcm convention: negative-upward, dim ``Z``) and
    ``drF`` (dim ``k``) — all that ``_get_depth_coord`` and
    ``_get_vertical_spacing`` need for the depth-integration reductions.

    Returns
    -------
    xr.Dataset
        Dataset with coordinate ``Z`` and variable ``drF``.

    Generated by JXP and Claude
    """
    return xr.Dataset(
        data_vars={"drF": (("k",), _DRF)},
        coords={"Z": (("Z",), -_Z_POS)},     # negative-upward, like the model
    )


def _n2_profile(values, shape_spatial=(1, 2, 2)):
    """Dask-backed N² with a 1D profile broadcast over (face, j, i).

    Parameters
    ----------
    values : sequence of float
        Per-level N² values [s⁻²], one per model level (length == n levels).
    shape_spatial : tuple of int, optional
        (face, j, i) spatial shape to broadcast the profile over
        (default (1, 2, 2)).

    Returns
    -------
    xr.DataArray
        Lazy 4D N² on dims ``("k", "face", "j", "i")``.

    Generated by JXP and Claude
    """
    prof = np.asarray(values, dtype=float)
    nk = prof.size
    arr = np.broadcast_to(
        prof[:, None, None, None], (nk,) + shape_spatial,
    ).copy()
    return xr.DataArray(
        da.from_array(arr, chunks=arr.shape),
        dims=("k", "face", "j", "i"),
    )


def _two_layer_tracers(n_mixed=5, shape_spatial=(1, 2, 2)):
    """Synthetic Theta/Salt: well-mixed upper layer over a cold dense layer.

    The upper ``n_mixed`` levels are uniform (Theta=18 °C, Salt=35 PSU); the
    levels below are sharply colder (Theta=4 °C) and therefore denser. The
    threshold MLD must therefore fall at the deepest uniform level.

    Parameters
    ----------
    n_mixed : int, optional
        Number of uniform (well-mixed) surface levels (default 5).
    shape_spatial : tuple of int, optional
        (face, j, i) spatial shape (default (1, 2, 2)).

    Returns
    -------
    xr.Dataset
        Dataset with dask-backed ``Theta`` and ``Salt`` (dims
        ``k, face, j, i``) plus the vertical grid from :func:`_grid_ds`.

    Generated by JXP and Claude
    """
    nk = _Z_POS.size
    theta_prof = np.full(nk, 18.0)
    theta_prof[n_mixed:] = 4.0               # cold (denser) deep layer
    salt_prof = np.full(nk, 35.0)            # uniform salinity

    def _da(prof):
        arr = np.broadcast_to(
            prof[:, None, None, None], (nk,) + shape_spatial,
        ).copy()
        return xr.DataArray(
            da.from_array(arr, chunks=arr.shape),
            dims=("k", "face", "j", "i"),
        )

    ds = _grid_ds()
    ds["Theta"] = _da(theta_prof)
    ds["Salt"] = _da(salt_prof)
    return ds


# ---------------------------------------------------------------------------
# Depth Integration Method (MLD_DI)
# ---------------------------------------------------------------------------

def test_mld_di_formula_and_laziness():
    """MLD_DI equals the analytic N²-weighted mean depth and stays lazy."""
    # N² weights only the three deepest levels (z = 55, 65, 75 m).
    n2 = _n2_profile([0, 0, 0, 0, 0, 1.0, 1.0, 1.0])
    ds = _grid_ds()

    mld = cfad.mixed_layer_depth_DI(ds, n2=n2)

    # Must remain a lazy dask graph until .compute().
    assert isinstance(mld.data, da.Array), "MLD_DI must stay dask-backed"

    # Metadata wired through per the prompt spec.
    assert mld.name == "MLD_DI"
    assert mld.attrs["long_name"] == \
        "Mixed layer depth (Depth Integration Method)"
    assert mld.attrs["units"] == "m"
    assert mld.attrs["description"] == (
        "The depth to the bottom of the mixed layer calculated using the "
        "Depth Integration Method"
    )

    # Equal weights on z = 55, 65, 75 → weighted mean = 65 m everywhere.
    np.testing.assert_allclose(mld.values, 65.0, rtol=1e-12)


def test_mld_di_default_integration_depth():
    """Default H is ``MLD_INTEGRATION_DEPTH_M`` (300 m) — all levels enter."""
    # Uniform N² → MLD_DI is the thickness-weighted mean depth of all levels
    # (every level lies within the 300 m default window).
    n2 = _n2_profile(np.ones(_Z_POS.size))
    ds = _grid_ds()

    mld = cfad.mixed_layer_depth_DI(ds, n2=n2)

    assert MLD_INTEGRATION_DEPTH_M == 300.0
    np.testing.assert_allclose(mld.values, _Z_POS.mean(), rtol=1e-12)


def test_mld_di_integration_depth_cutoff():
    """Levels deeper than ``integration_depth_m`` are excluded from the integrals."""
    # All N² weight sits below 50 m; with H=50 m the weight integral is 0 and
    # the estimator is undefined (NaN). With the full window it is finite.
    n2 = _n2_profile([0, 0, 0, 0, 0, 1.0, 1.0, 1.0])
    ds = _grid_ds()

    mld_shallow = cfad.mixed_layer_depth_DI(
        ds, integration_depth_m=50.0, n2=n2,
    ).values
    assert np.isnan(mld_shallow).all(), "no weight within 50 m → NaN"

    mld_full = cfad.mixed_layer_depth_DI(ds, n2=n2).values
    assert np.isfinite(mld_full).all()


def test_mld_di_floors_negative_n2():
    """Statically unstable layers (N² < 0) are floored to 0 before weighting."""
    # k=5 carries a negative (unstable) N²; it must contribute zero weight, so
    # the estimator reduces to the mean of z = 65 and 75 m → 70 m.
    n2 = _n2_profile([0, 0, 0, 0, 0, -5.0, 1.0, 1.0])
    ds = _grid_ds()

    mld = cfad.mixed_layer_depth_DI(ds, n2=n2).values
    np.testing.assert_allclose(mld, 70.0, rtol=1e-12)


# ---------------------------------------------------------------------------
# Threshold MLD (default estimator)
# ---------------------------------------------------------------------------

def test_mixed_layer_depth_threshold_two_layer():
    """Threshold MLD sits at the deepest well-mixed level above the pycnocline."""
    n_mixed = 5                              # uniform levels k=0..4 (z≤45 m)
    ds = _two_layer_tracers(n_mixed=n_mixed)

    mld = cfad.mixed_layer_depth(ds)

    assert isinstance(mld.data, da.Array), "MLD must stay dask-backed"
    assert mld.name == "MLD"
    assert mld.attrs["units"] == "m"

    # Δσ = 0 through the uniform layer, then a large jump at the cold layer,
    # so MLD = deepest uniform depth = _Z_POS[n_mixed - 1] = 45 m.
    expected = _Z_POS[n_mixed - 1]
    np.testing.assert_allclose(mld.values, expected, rtol=1e-12)


def test_mixed_layer_depth_deepens_with_thicker_mixed_layer():
    """A thicker uniform layer yields a deeper threshold MLD (monotonic)."""
    shallow = cfad.mixed_layer_depth(_two_layer_tracers(n_mixed=3)).values
    deep = cfad.mixed_layer_depth(_two_layer_tracers(n_mixed=6)).values
    assert (deep > shallow).all(), "deeper mixed layer must give larger MLD"


# ---------------------------------------------------------------------------
# File-dependent integration: MLD_DI on the local LLC4320 density tile
# ---------------------------------------------------------------------------

def test_mld_di_on_real_density_tile():
    """MLD_DI on the real σ₀ density tile yields a sensible interior field.

    Loads the local tile named in ``prompts/mld.md``
    (``density_tile359_20121109T12.nc``), which stores only ``sigma0``. N² is
    rebuilt from σ₀ (ρ = σ₀ + 1000) via the production vertical derivative and
    fed to ``mixed_layer_depth_DI`` through its ``n2`` keyword. The tile has no
    ``drF``; ``_get_vertical_spacing`` falls back to differencing ``Z``.

    Skipped when ``OS_OGCM`` or the tile file is unavailable (offline runs).

    Generated by JXP and Claude
    """
    os_ogcm = os.environ.get("OS_OGCM")
    if not os_ogcm:
        pytest.skip("OS_OGCM not set")
    tile_path = os.path.join(
        os_ogcm, "LLC", "Fronts", "V4", "20121109_120000", "tiles",
        "density_tile359_20121109T12.nc",
    )
    if not os.path.exists(tile_path):
        pytest.skip(f"density tile not found: {tile_path}")

    ds = xr.open_dataset(tile_path, chunks={"k": -1, "j": 360, "i": 360})
    try:
        # The density tile stores only σ₀ (no ``drF``); supply a layer
        # thickness on the integer-k axis so ``_get_vertical_spacing`` does
        # not fall back to a depth-valued coordinate (which would misalign
        # with the integer-k N²).  In production ``ds_merge`` carries ``drF``.
        z_pos = np.abs(ds["Z"].values).astype(float)
        ds["drF"] = (("k",), np.gradient(z_pos))

        # ρ from σ₀, then N² = (g/ρ₀) dρ/dz on the model levels.
        rho = ds["sigma0"] + 1000.0
        drho_dz = _vertical_derivative(rho, ds)
        n2 = (G / RHO0_REFERENCE) * drho_dz

        mld = cfad.mixed_layer_depth_DI(ds, n2=n2).compute()

        assert mld.name == "MLD_DI"
        # Interior away from tile edges should be finite and within the
        # physical (0, 300] m integration window.
        interior = mld.values[5:-5, 5:-5]
        finite = interior[np.isfinite(interior)]
        assert finite.size > 0.5 * interior.size, "interior mostly finite"
        assert (finite > 0).all() and (finite <= MLD_INTEGRATION_DEPTH_M).all()
    finally:
        ds.close()
