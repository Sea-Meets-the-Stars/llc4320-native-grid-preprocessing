def test_legacy_aliases_resolve():
    assert resolve_property("temperature") is TILE_PROPERTIES["Theta"]
    assert resolve_property("salinity") is TILE_PROPERTIES["Salt"]
    # 'density' is itself a channel name (output var stays 'sigma0').
    assert resolve_property("density").out_name == "sigma0"
    assert set(ALIASES) == {"temperature", "salinity"}


def test_unknown_name_raises():
    with pytest.raises(KeyError, match="Unknown property"):
        resolve_property("definitely_not_a_field")


# ---------------------------------------------------------------------------
# 4. Vector rotation acceptance test (plan: tiles_fields.md)
# ---------------------------------------------------------------------------

def test_rotation_pacific_like_face():
    """CS=0 / SN=1 (90-degree rotated face): model-x flow is NORTH.

    On the rotated LLC faces the model x-axis points geographically
    north.  With a purely model-x flow the registry's U entry (true
    east) must therefore return ~0 and the V entry (true north) the
    full flow.  A passthrough would get this exactly backwards.
    """
    ds = _tile_ds(cs=0.0, sn=1.0)
    speed = 0.3
    ds["U"] = xr.full_like(ds["U"], speed)   # model-x flow
    ds["V"] = xr.zeros_like(ds["V"])         # no model-y flow
    ds_merge, grid = _build_tile_context(ds, ds)

    u = compute_tile_property(ds_merge, grid, TILE_PROPERTIES["U"])
    v = compute_tile_property(ds_merge, grid, TILE_PROPERTIES["V"])

    # Interior beyond the 1-cell staggered-interp rim.
    sel = {"j": slice(1, -1), "i": slice(1, -1)}
    np.testing.assert_allclose(
        u.isel(sel).values, 0.0, atol=1e-6,
        err_msg="model-x flow leaked into eastward U on rotated face")
    np.testing.assert_allclose(
        v.isel(sel).values, speed, rtol=1e-5,
        err_msg="model-x flow missing from northward V on rotated face")


def test_rotation_identity_face():
    """CS=1 / SN=0 (unrotated): model axes ARE geographic axes."""
    ds = _tile_ds(cs=1.0, sn=0.0)
    speed = 0.3
    ds["U"] = xr.full_like(ds["U"], speed)
    ds["V"] = xr.zeros_like(ds["V"])
    ds_merge, grid = _build_tile_context(ds, ds)

    u = compute_tile_property(ds_merge, grid, TILE_PROPERTIES["U"])
    v = compute_tile_property(ds_merge, grid, TILE_PROPERTIES["V"])

    sel = {"j": slice(1, -1), "i": slice(1, -1)}
    np.testing.assert_allclose(u.isel(sel).values, speed, rtol=1e-5)
    np.testing.assert_allclose(v.isel(sel).values, 0.0, atol=1e-6)
