"""
Tests for the generalized tile field registry
(prompts/tiles_fields.md, testing plan).

Uses the shared synthetic LLC fixtures (tests/synthetic_llc.py),
sliced to a SINGLE face to mimic a tile, with the tile context built
by the real ``tile_utils._build_tile_context`` (local xgcm grid,
``use_connections=False``).

Covers:

- every registry entry runs end-to-end through
  ``compute_tile_property`` (dims, dtype, attrs, NaN edge rim,
  finite interior beyond the rim);
- registry coverage of EVERY channel of every SURF and DEPTH subset
  (``subset_definitions`` is the ground truth);
- legacy aliases (``temperature``/``salinity``) and the KeyError for
  unknown names;
- the CS/SN rotation acceptance test: on a synthetic 90-degree-
  rotated face (CS=0, SN=1, Pacific-face-like) a purely model-x flow
  must come out as NORTHWARD (V), not eastward (U).

Generated by LH and Claude
"""

import numpy as np
import pytest
import xarray as xr

import synthetic_llc
from dbof.global_dataset_creation.subset_definitions import (
    get_subset_definition,
    valid_subsets,
)
from dbof.tiles.field_registry import (
    ALIASES,
    TILE_PROPERTIES,
    resolve_property,
)
from dbof.tiles.tile_utils import (
    _build_tile_context,
    compute_tile_property,
)


# ``_build_tile_context`` builds xgcm from its SECOND argument alone (only the
# grid coords carry the comodo ``axis`` attrs), so the synthetic tile dataset
# is passed as both tracers and grid: it holds the metrics (dxC/dyC/CS/SN) AND
# the annotated i/i_g/j/j_g coords.  Passing ``xr.Dataset()`` there -- as this
# module did before ``_build_tile_context`` was rewritten -- leaves xgcm with
# no axes and every stencil field raises.
def _tile_ds(cs=1.0, sn=0.0):
    """Single-face, depth-style synthetic tile dataset.

    Inputs: cs, sn (float) — uniform rotation coefficients.
    Outputs: xr.Dataset with a size-1 ``face`` dim (as a real tile
    slice has) and the extra 2D passthrough vars the shared fixture
    lacks (``oceQnet``, ``SIarea``).
    Generated by LH and Claude
    """
    ds = synthetic_llc.build_ds3d(cs=cs, sn=sn).isel(face=[0])
    # 2D tracer-point passthrough variables (values arbitrary).
    ds["oceQnet"] = xr.full_like(ds["Eta"], 50.0)
    ds["SIarea"] = xr.full_like(ds["Eta"], 0.5)
    return ds


@pytest.fixture(scope="module")
def tile_ctx():
    """(ds_merge, grid) tile context on the standard CS=1/SN=0 face."""
    return _build_tile_context(_tile_ds(), _tile_ds())


# ---------------------------------------------------------------------------
# 1. Every registry entry runs end-to-end
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("name", sorted(TILE_PROPERTIES))
def test_registry_entry_runs(name, tile_ctx):
    ds_merge, grid = tile_ctx
    prop = TILE_PROPERTIES[name]

    # Every declared input variable must exist on the tile dataset.
    missing = [v for v in prop.vars_needed if v not in ds_merge]
    assert not missing, f"{name}: fixture lacks {missing}"

    field = compute_tile_property(ds_merge, grid, prop)

    # face squeezed; only (k, j, i) or (j, i) remain.
    assert "face" not in field.dims
    assert set(field.dims) <= {"k", "j", "i"}
    assert {"j", "i"} <= set(field.dims)

    # dtype / naming / attrs contract.
    assert field.dtype == np.float32
    assert field.name == prop.out_name
    assert field.attrs["units"] == prop.units
    assert field.attrs["edge_margin"] == prop.edge_margin

    # NaN rim: with edge_margin > 0 the boundary cells are unusable.
    m = prop.edge_margin
    if m > 0:
        for dim in ("j", "i"):
            edge = field.isel({dim: 0})
            assert np.isnan(edge).all(), f"{name}: {dim}=0 rim not NaN"
            edge = field.isel({dim: -1})
            assert np.isnan(edge).all(), f"{name}: {dim}=-1 rim not NaN"

    # Interior beyond the rim is fully finite.  Vertical stencils may
    # be boundary-affected at the top/bottom level, so k (if present)
    # is restricted to interior levels.
    sel = {
        "j": slice(m, field.sizes["j"] - m),
        "i": slice(m, field.sizes["i"] - m),
    }
    if "k" in field.dims:
        sel["k"] = slice(1, field.sizes["k"] - 1)
    interior = field.isel(sel)
    assert interior.size > 0
    assert np.isfinite(interior).all(), f"{name}: NaNs inside the rim"


def test_2d_fields_have_no_k(tile_ctx):
    """Inherently-2D outputs keep 2D even on a 3D tile dataset."""
    ds_merge, grid = tile_ctx
    for name in ("Eta", "mixed_layer_depth", "oceTAUX", "gradeta2",
                 "SIarea"):
        field = compute_tile_property(
            ds_merge, grid, TILE_PROPERTIES[name])
        assert "k" not in field.dims, f"{name} should be 2D"


# ---------------------------------------------------------------------------
# 2. Registry covers every SURF and DEPTH subset channel
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("pipeline", ["SURF", "DEPTH"])
def test_registry_covers_all_subset_channels(pipeline):
    for subset in valid_subsets(pipeline):
        defn = get_subset_definition(pipeline, subset)
        channels = (list(defn["model_data_feature_channels"])
                    + list(defn["compute_features_channels"]))
        for ch in channels:
            # Raises KeyError if a channel has no registry entry.
            prop = resolve_property(ch)
            assert prop.name == ch


