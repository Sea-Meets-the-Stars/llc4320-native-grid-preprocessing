"""The transfer writer must record the COMODO attributes it is given.

``c_grid_axis_shift`` travels on the *coordinate*, not on the data
variables, so it is written by ``ensure_coord_written`` and nowhere else.
Until 2026-09-01 that function wrote the coordinate values and no attrs
at all, which is why the LLC_DEPTH store came back declaring ``{}`` and
every reader had to reconstruct where U and V sit by hand -- and two of
them reconstructed it differently.  See docs/Grid.md.

These tests write a small store to a temp directory: no S3, no network,
no credentials.

Generated by LH and Claude
"""

import numpy as np
import pytest
import xarray as xr

from dbof.llc4320_ingestion.grid import COMODO_COORD_META
import dbof.transfer.zarr_io as zarr_io

NFACE, N = 2, 4


def make_source(coord_attrs=None):
    """A minimal (face, j, i_g) source dataset, as the transfer sees it.

    Parameters
    ----------
    coord_attrs : dict, optional
        ``{dim: attrs}`` to stamp on the coordinates, mimicking a source
        that came through xmitgcm.  Default: bare coordinates, as raw
        MITgcm output gives.

    Returns
    -------
    xarray.Dataset
        One ``U``-like variable on the u-point.

    Generated by LH and Claude
    """
    coords = {
        "face": np.arange(NFACE),
        "j": np.arange(N),
        "i_g": np.arange(N),
    }
    ds = xr.Dataset(
        {"U": (("face", "j", "i_g"),
               np.arange(NFACE * N * N, dtype="float32").reshape(
                   NFACE, N, N))},
        coords=coords,
    )
    for dim, attrs in (coord_attrs or {}).items():
        ds[dim].attrs.update(attrs)
    return ds


def write_and_reopen(tmp_path, ds):
    """Run the real writer into a local zarr store and read it back.

    Parameters
    ----------
    tmp_path : pathlib.Path
        pytest temp directory.
    ds : xarray.Dataset
        Source dataset from :func:`make_source`.

    Returns
    -------
    xarray.Dataset
        The store as a reader would see it.

    Generated by LH and Claude
    """
    zarr = pytest.importorskip("zarr")
    path = str(tmp_path / "grid.zarr")
    root = zarr.group(store=path, overwrite=True)
    zarr_io.write_2d_horizontal(root, ds, ds["U"], time_idx=0,
                                tile_j=N, tile_i=N)
    return xr.open_zarr(path, consolidated=False)


def test_writer_supplies_comodo_attrs_when_the_source_has_none(tmp_path):
    """Raw MITgcm output carries no attributes; the store must not either."""
    out = write_and_reopen(tmp_path, make_source())

    assert out["i_g"].attrs.get("c_grid_axis_shift") == -0.5, (
        "the u-point coordinate reached the store without its "
        "registration; every reader would have to guess it")
    assert out["i_g"].attrs.get("axis") == "X"
    # Cell centres are not shifted, and must not claim to be.
    assert out["j"].attrs.get("axis") == "Y"
    assert "c_grid_axis_shift" not in out["j"].attrs


def test_writer_preserves_the_sources_own_attrs(tmp_path):
    """A source that came through xmitgcm already declares this."""
    ds = make_source(coord_attrs={
        "i_g": {"axis": "X", "c_grid_axis_shift": -0.5,
                "standard_name": "x_grid_index_at_u_location"},
    })
    out = write_and_reopen(tmp_path, ds)

    assert out["i_g"].attrs.get("c_grid_axis_shift") == -0.5
    assert out["i_g"].attrs.get("standard_name") == (
        "x_grid_index_at_u_location"), (
        "source attributes should pass through, not be replaced by the "
        "fallback")


def test_writer_does_not_invent_attrs_for_other_coords(tmp_path):
    """``face`` is not a COMODO axis and must be left bare."""
    out = write_and_reopen(tmp_path, make_source())
    assert "axis" not in out["face"].attrs
    assert "c_grid_axis_shift" not in out["face"].attrs


def test_fallback_matches_the_shared_constant(tmp_path):
    """What the writer falls back to is the one definition, not a copy."""
    out = write_and_reopen(tmp_path, make_source())
    for key, value in COMODO_COORD_META["i_g"].items():
        assert out["i_g"].attrs.get(key) == value
