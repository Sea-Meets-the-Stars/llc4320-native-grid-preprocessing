@pytest.mark.parametrize(
    "name,fn", LAZY_FNS, ids=[n for n, _ in LAZY_FNS])
def test_lazy_depth_module_function(name, fn, ds3d, grid3d):
    """Depth-module (canonical) functions build graphs without computing."""
    with no_compute_allowed():
        fn(ds3d, grid3d)


