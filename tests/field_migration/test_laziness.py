"""
Laziness tests: canonical field functions must build graphs, not compute.

MIGRATION SCAFFOLDING — see ``prompts/field_migration.md`` (Phase 0).
Every function destined for ``calculate_fields.py`` /
``calculate_fields_at_depth.py`` must be fully lazy: calling it builds a
dask task graph and triggers ZERO task execution (no ``.compute()`` or
``.persist()`` inside field functions — materialisation belongs to the
application layer).

Mechanism: dask's scheduler is temporarily replaced with a callable that
raises on any task execution.  Graph construction never invokes the
scheduler, so a truly lazy function passes; any hidden compute/persist
raises immediately.

Also DOCUMENTS the legacy eager behaviour: the superseded
``physical_calculations.density_of_field`` / ``buoyancy_of_field`` call
``.persist()`` internally and remain eager (they are kept, unused, for
reference).  Phase 1 note: ``caf.grad_rho2`` / ``caf.grad_b2`` moved off
the legacy route onto the lazy ``potential_density`` /
``buoyancy_of_field`` and now live in the lazy list below.

Running (local machine — synthetic data only, no network)::

    conda activate llcngp
    python -m pytest tests/field_migration/test_laziness.py -v

Generated by LH and Claude
"""

import contextlib

import dask
import pytest

import dbof.preprocessing.calculate_fields as caf
import dbof.preprocessing.calculate_fields_at_depth as cfad
import dbof.utils.physical_calculations as pc


class ComputeTriggered(Exception):
    """Raised when any dask task executes inside a 'lazy' call."""


def _forbid_compute(dsk, keys, **kwargs):
    raise ComputeTriggered(
        "dask task execution was triggered during graph construction")


@contextlib.contextmanager
def no_compute_allowed():
    """Context in which any dask compute/persist raises ComputeTriggered."""
    with dask.config.set(scheduler=_forbid_compute):
        yield


