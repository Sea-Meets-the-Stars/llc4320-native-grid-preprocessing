def assert_k0_equal(surface_result, result_3d, rtol=1e-10, atol=0.0,
                    name=""):
    """Assert a surface-module result equals the k=0 slice of a 3D result.

    Both inputs may be xr.DataArray, dask or numpy backed.  Comparison is
    on values (coords/attrs intentionally ignored — those differences are
    resolved by the migration itself). NaNs must match in position.
    """
    a = np.asarray(getattr(surface_result, "values", surface_result))
    b3 = result_3d
    if hasattr(b3, "isel") and "k" in getattr(b3, "dims", ()):
        b3 = b3.isel(k=0)
    b = np.asarray(getattr(b3, "values", b3))
    assert a.shape == b.shape, (
        f"{name}: shape mismatch {a.shape} vs {b.shape}")
    np.testing.assert_allclose(
        a, b, rtol=rtol, atol=atol, equal_nan=True,
        err_msg=f"{name}: surface result != 3D result at k=0")
