def test_grad_b2_equivalence(ds2d, grid2d, ds3d, grid3d):
    """Surface (buoyancy_of_field*1e3) vs depth (buoyancy_field_3d) agree.

    Both legacy scaled-buoyancy routes reduce to b = 9.8*rho/1025, so
    |grad b|^2 must match exactly.  (The migration replaces both with
    b = 9.81*rho/1000; the golden-regression test pins that rescaling.)
    """
    assert_k0_equal(
        caf.grad_b2(ds2d, grid2d),
        cfad.grad_b2_3d(ds3d, grid3d),
        name="grad_b2")


def test_log_grad_b_equivalence(ds2d, grid2d, ds3d, grid3d):
    """log_grad_b (surface-only home) == log10 of the 3D grad_b2 at k=0."""
    log2d = caf.log_grad_b(ds2d, grid2d)
    log3d = np.log10(cfad.grad_b2_3d(ds3d, grid3d))
    assert_k0_equal(log2d, log3d, name="log_grad_b")


def test_grad_squared_single_implementation(ds2d, grid2d):
    """ONE grad_squared: ng owns it; pc re-exports it; fields use it.

    Phase 1 note: ``_grad_squared_3d`` was deleted and
    ``physical_calculations.grad_squared`` became a re-export of
    ``native_gradient.grad_squared``.  This certifies the wiring and that
    the canonical two-step workflow reproduces a grad_*2 field.
    """
    assert pc.grad_squared is ng.grad_squared, (
        "physical_calculations.grad_squared must re-export "
        "native_gradient.grad_squared")
    gx, gy = ng.calculate_native_gradient_tracer(
        ds2d.Theta, ds2d, grid=grid2d)
    manual = ng.grad_squared(gx, gy)
    assert_k0_equal(manual, caf.grad_theta2(ds2d, grid2d),
                    name="two-step workflow vs grad_theta2")


def test_native_gradient_tracer_dimension_agnostic(ds2d, grid2d, ds3d,
                                                   grid3d):
    """ng.calculate_native_gradient_tracer with vs without k (both comps).

    The core dimension-agnosticism check for the tracer-gradient machinery
    every grad_* field is built on.
    """
    gx2, gy2 = ng.calculate_native_gradient_tracer(
        ds2d.Theta, ds2d, grid=grid2d)
    gx3, gy3 = ng.calculate_native_gradient_tracer(
        ds3d.Theta, ds3d, grid=grid3d)
    assert_k0_equal(gx2, gx3, name="native_gradient zonal")
    assert_k0_equal(gy2, gy3, name="native_gradient merid")
