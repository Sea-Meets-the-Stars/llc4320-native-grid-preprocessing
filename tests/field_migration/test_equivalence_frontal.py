def test_frontogenesis_injection_consistent(ds2d, grid2d):
    """Shared jacobian/buoyancy-gradient kwargs must not change values."""
    jac = caf.compute_velocity_jacobian(ds2d, grid2d)
    bg = caf.compute_buoyancy_gradients(ds2d, grid2d)
    assert_k0_equal(
        caf.frontogenesis_tendency(ds2d, grid2d,
                                   jacobian=jac, buoyancy_gradients=bg),
        caf.frontogenesis_tendency(ds2d, grid2d),
        name="frontogenesis_tendency injection")


def test_phys_helpers_deleted(ds2d, grid2d, ds3d, grid3d):
    """Phase 3: the private phys-gradient helpers are gone.

    Phase 1 proved the phys and standard buoyancy routes identical;
    Phase 3 deleted ``_buoyancy_gradient_phys_3d`` /
    ``_buoyancy_gradient_squared_phys_3d`` (and every other duplicate).
    The single ``compute_buoyancy_gradients`` serves R_ib, W*, grad_b2
    and frontogenesis on both 2D and 3D inputs.
    """
    for name in ("_buoyancy_gradient_phys_3d",
                 "_buoyancy_gradient_squared_phys_3d",
                 "compute_buoyancy_gradients_3d",
                 "_density_lazy", "buoyancy_field_3d"):
        assert not hasattr(cfad, name), f"{name} should be deleted"
    bg2 = caf.compute_buoyancy_gradients(ds2d, grid2d)
    bg3 = caf.compute_buoyancy_gradients(ds3d, grid3d)
    assert_k0_equal(bg2.zonal, bg3.zonal, name="bg.zonal 2D-vs-3D")
    assert_k0_equal(bg2.merid, bg3.merid, name="bg.merid 2D-vs-3D")
