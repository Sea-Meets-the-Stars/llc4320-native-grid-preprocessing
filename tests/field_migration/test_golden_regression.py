"""
Golden regression: pin field values on synthetic data across the migration.

MIGRATION SCAFFOLDING — see ``prompts/field_migration.md`` (Phase 0).
Computes a curated set of fields from BOTH modules on the deterministic
synthetic fixtures and compares every value against a committed baseline
(``tests/field_migration/golden/field_baselines.npz``).  Re-run after
every migration phase: any unintended numerical change fails loudly.

Baseline workflow
-----------------
- FIRST RUN (no baseline file): the baseline is written and the test is
  skipped with a message.  Run once in the project environment, then
  commit ``tests/field_migration/golden/field_baselines.npz``.
- LATER RUNS: values are compared to the baseline at rtol=1e-9.

EXPECTED (intentional) failures during the migration: when Phase 1/2
unify buoyancy to b = 9.81*rho/1000 (from the legacy 9.8*rho/1025), every
key listed in ``BUOYANCY_SCALED_KEYS`` rescales by a constant
(~+2.57% for b-linear fields, squared for |grad b|^2-type fields) and, for
Turner angle / R_ib / W*, small value shifts from the rho_ref change.
At that point: verify the diffs match the expected constants, delete the
baseline file, re-run to regenerate, and commit the new baseline.

Running (local machine — synthetic data only, no network)::

    conda activate llcngp
    python -m pytest tests/field_migration/test_golden_regression.py -v

Generated by LH and Claude
"""

import pathlib

import numpy as np
import pytest

import dbof.preprocessing.calculate_fields as caf
import dbof.preprocessing.calculate_fields_at_depth as cfad

GOLDEN_PATH = (pathlib.Path(__file__).parent / "golden"
               / "field_baselines.npz")

# Keys whose values are EXPECTED to change when RHO0 = 1000 / g = 9.81
# land (Phase 1/2).  All other keys must never change.
BUOYANCY_SCALED_KEYS = {
    "2d_grad_b2", "2d_log_grad_b", "2d_buoyancy_gradients_zonal",
    "2d_frontogenesis_tendency", "2d_frontogenesis_geo",
    "2d_turner_angle", "2d_density_channel", "2d_buoyancy_channel",
    "3d_grad_b2", "3d_buoyancy", "3d_buoyancy_gradients_zonal",
    "3d_frontogenesis_tendency", "3d_frontogenesis_geo",
    "3d_turner_angle", "3d_R_ib", "3d_Wstar",
    "3d_uB", "3d_vB", "3d_wB",
    "3d_ertel_pv", "3d_ertel_pv_vertical", "3d_ertel_pv_tilt",
}


def _values(x):
    """Materialise an xr/dask object to a float64 numpy array."""
    v = getattr(x, "values", x)
    return np.asarray(v, dtype=np.float64)


def compute_all_fields(ds2d, grid2d, ds3d, grid3d):
    """Compute the pinned field set.  Returns {key: ndarray}."""
    out = {}

    # ---- Surface module on ds2d ------------------------------------------
    jac = caf.compute_velocity_jacobian(ds2d, grid2d)
    out["2d_relative_vorticity"] = _values(
        caf.relative_vorticity(ds2d, grid2d, jacobian=jac))
    sm, sn, ss = caf.strain(ds2d, grid2d, jacobian=jac)
    out["2d_strain_mag"] = _values(sm)
    out["2d_strain_n"] = _values(sn)
    out["2d_strain_s"] = _values(ss)
    out["2d_divergence"] = _values(caf.divergence(ds2d, grid2d, jacobian=jac))
    out["2d_okubo_weiss"] = _values(
        caf.okubo_weiss_parameter(ds2d, grid2d, jacobian=jac))
    out["2d_rossby_number"] = _values(
        caf.rossby_number(ds2d, grid2d, jacobian=jac))
    out["2d_coriolis_f"] = _values(caf.coriolis_parameter(ds2d, grid2d))

    out["2d_grad_theta2"] = _values(caf.grad_theta2(ds2d, grid2d))
    out["2d_grad_salt2"] = _values(caf.grad_salt2(ds2d, grid2d))
    out["2d_grad_eta2"] = _values(caf.grad_eta2(ds2d, grid2d))
    out["2d_grad_rho2"] = _values(caf.grad_rho2(ds2d, grid2d))
    out["2d_grad_b2"] = _values(caf.grad_b2(ds2d, grid2d))
    out["2d_log_grad_b"] = _values(caf.log_grad_b(ds2d, grid2d))
    out["2d_turner_angle"] = _values(caf.turner_angle(ds2d, grid2d))

    bg = caf.compute_buoyancy_gradients(ds2d, grid2d)
    out["2d_buoyancy_gradients_zonal"] = _values(bg.zonal)
    out["2d_frontogenesis_tendency"] = _values(
        caf.frontogenesis_tendency(ds2d, grid2d))
    out["2d_frontogenesis_geo"] = _values(
        caf.frontogenesis_geo(ds2d, grid2d))
    ug, vg = caf.geostrophic_velocity(ds2d, grid2d)
    out["2d_ug"] = _values(ug)
    out["2d_vg"] = _values(vg)

    ue, vn = caf.geographic_velocity(ds2d, grid2d)
    out["2d_u_east"] = _values(ue)
    out["2d_v_north"] = _values(vn)
    te, tn = caf.geographic_wind_stress(ds2d, grid2d)
    out["2d_tau_east"] = _values(te)
    out["2d_tau_north"] = _values(tn)

    # SURF output channels for density/buoyancy (legacy eager route).
    out["2d_density_channel"] = _values(
        caf.potential_density_anomaly(ds2d))
    out["2d_buoyancy_channel"] = _values(caf.buoyancy_of_field(ds2d))

    # ---- Depth module on ds3d ---------------------------------------------
    out["3d_sigma0"] = _values(caf.potential_density_anomaly(ds3d))
    out["3d_buoyancy"] = _values(caf.buoyancy_of_field(ds3d))
    out["3d_N2"] = _values(cfad.buoyancy_frequency_squared(ds3d))
    out["3d_MLD"] = _values(cfad.mixed_layer_depth(ds3d))
    out["3d_MLD_DI"] = _values(cfad.mixed_layer_depth_DI(ds3d))
    out["3d_ml_heat_content"] = _values(
        cfad.mixed_layer_heat_content(ds3d))

    out["3d_vertical_shear"] = _values(
        cfad.vertical_shear_magnitude(ds3d, grid3d))
    out["3d_Ri"] = _values(cfad.richardson_number(ds3d, grid3d))
    out["3d_Fr"] = _values(cfad.froude_number(ds3d, grid3d))
    out["3d_Ro"] = _values(caf.rossby_number(ds3d, grid3d))
    out["3d_Bu"] = _values(cfad.burger_number(ds3d, grid3d))
    out["3d_R_ib"] = _values(
        cfad.balanced_richardson_number(ds3d, grid3d))

    out["3d_wind_stress_curl"] = _values(
        caf.wind_stress_curl(ds3d, grid3d))
    out["3d_ekman_pumping"] = _values(caf.ekman_pumping(ds3d, grid3d))
    ek = caf.ekman_transport(ds3d, grid3d)
    out["3d_u_ekman"] = _values(ek["u_ekman"])
    out["3d_v_ekman"] = _values(ek["v_ekman"])

    uB, vB, wB = cfad.advective_buoyancy_fluxes(ds3d, grid3d)
    out["3d_uB"] = _values(uB)
    out["3d_vB"] = _values(vB)
    out["3d_wB"] = _values(wB)

    pv = cfad.ertel_pv_terms(ds3d, grid3d)
    out["3d_ertel_pv"] = _values(pv["ertel_pv"])
    out["3d_ertel_pv_vertical"] = _values(pv["ertel_pv_vertical"])
    out["3d_ertel_pv_tilt"] = _values(pv["ertel_pv_tilt"])

    out["3d_grad_b2"] = _values(caf.grad_b2(ds3d, grid3d))
    out["3d_turner_angle"] = _values(caf.turner_angle(ds3d, grid3d))
    out["3d_relative_vorticity"] = _values(
        caf.relative_vorticity(ds3d, grid3d))
    out["3d_okubo_weiss"] = _values(caf.okubo_weiss_parameter(ds3d, grid3d))
    out["3d_Wstar"] = _values(caf.modified_okubo_weiss(ds3d, grid3d))
    bg3 = caf.compute_buoyancy_gradients(ds3d, grid3d)
    out["3d_buoyancy_gradients_zonal"] = _values(bg3.zonal)
    out["3d_frontogenesis_tendency"] = _values(
        caf.frontogenesis_tendency(ds3d, grid3d))
    out["3d_frontogenesis_geo"] = _values(
        caf.frontogenesis_geo(ds3d, grid3d))

    return out


def test_golden_regression(ds2d, grid2d, ds3d, grid3d):
    """Every pinned field matches the committed baseline (rtol=1e-9)."""
    current = compute_all_fields(ds2d, grid2d, ds3d, grid3d)

    if not GOLDEN_PATH.exists():
        GOLDEN_PATH.parent.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(GOLDEN_PATH, **current)
        pytest.skip(
            f"Baseline created at {GOLDEN_PATH} — commit it, then re-run.")

    baseline = np.load(GOLDEN_PATH)

    missing = set(current) - set(baseline.files)
    extra = set(baseline.files) - set(current)
    assert not missing, f"keys missing from baseline: {sorted(missing)}"
    assert not extra, f"stale keys in baseline: {sorted(extra)}"

    failures = []
    for key in sorted(current):
        try:
            np.testing.assert_allclose(
                current[key], baseline[key], rtol=1e-9, equal_nan=True)
        except AssertionError:
            tag = (" [EXPECTED to change at Phase 1/2 — see docstring]"
                   if key in BUOYANCY_SCALED_KEYS else "")
            failures.append(key + tag)
    assert not failures, (
        "fields diverged from golden baseline:\n  " + "\n  ".join(failures))
