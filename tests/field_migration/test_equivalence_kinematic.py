def test_rossby_number_equivalence(ds2d, grid2d, ds3d, grid3d):
    """Ro = zeta / f matches at k=0.

    The surface version shares a Jacobian; the 3D version recomputes zeta
    internally — the migration keeps the 3D (self-contained) behaviour
    with an optional ``jacobian=`` kwarg, so both routes must agree.
    """
    assert_k0_equal(
        caf.rossby_number(ds2d, grid2d),
        cfad.rossby_number_3d(ds3d, grid3d),
        name="rossby_number")


def test_jacobian_injection_is_consistent(ds2d, grid2d):
    """Passing a precomputed Jacobian equals standalone recomputation.

    Certifies the ``jacobian=`` injection kwarg (kept by the migration,
    incl. on ``rossby_number``) is inert: supplying the Jacobian must not
    change any value.
    """
    jac = caf.compute_velocity_jacobian(ds2d, grid2d)
    for fn in (caf.relative_vorticity, caf.divergence,
               caf.okubo_weiss_parameter, caf.rossby_number):
        assert_k0_equal(
            fn(ds2d, grid2d, jacobian=jac),
            fn(ds2d, grid2d),
            name=f"{fn.__name__} jacobian-injection")


def test_coriolis_parameter_dimension_agnostic(ds2d, grid2d, ds3d, grid3d):
    """coriolis_parameter (already single-instance) works on both inputs."""
    assert_k0_equal(
        caf.coriolis_parameter(ds2d, grid2d),
        caf.coriolis_parameter(ds3d, grid3d),
        name="coriolis_parameter")
