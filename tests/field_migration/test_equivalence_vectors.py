"""
Equivalence tests: geographic vector rotations (all duplicate copies).

MIGRATION SCAFFOLDING — see ``prompts/field_migration.md`` (Phase 0).
``geographic_velocity`` and ``geographic_wind_stress`` exist in BOTH
modules (and wind stress a third time as the private
``_wind_stress_geographic``).  All copies must agree so they can collapse
to one public function each in ``calculate_fields.py``.

These tests also certify ``ng.rotate_vector_to_geographic`` is
dimension-agnostic (with vs without a ``k`` dimension).

Running (local machine — synthetic data only, no network)::

    conda activate llcngp
    python -m pytest tests/field_migration/test_equivalence_vectors.py -v

Generated by LH and Claude
"""

import dbof.preprocessing.calculate_fields as caf
import dbof.preprocessing.calculated_fields_at_depth as cfad

from conftest import assert_k0_equal


def test_geographic_velocity_equivalence(ds2d, grid2d, ds3d, grid3d):
    """u_east / v_north match at k=0 (rotation is dimension-agnostic)."""
    u2, v2 = caf.geographic_velocity(ds2d, grid2d)
    u3, v3 = cfad.geographic_velocity_3d(ds3d, grid3d)
    assert_k0_equal(u2, u3, name="u_east")
    assert_k0_equal(v2, v3, name="v_north")


def test_geographic_wind_stress_single_copy(ds2d, grid2d, ds3d, grid3d):
    """Phase 2: the wind-stress duplicates are gone; ONE public function.

    The verbatim copy in the depth module and the private
    ``_wind_stress_geographic`` were deleted; ``calculate_fields``
    owns the single implementation, which must behave identically on
    surface-style and depth-style datasets (tau is inherently 2D).
    """
    assert not hasattr(cfad, "geographic_wind_stress")
    assert not hasattr(cfad, "_wind_stress_geographic")
    t2e, t2n = caf.geographic_wind_stress(ds2d, grid2d)
    t3e, t3n = caf.geographic_wind_stress(ds3d, grid3d)
    assert_k0_equal(t2e, t3e, name="tau_east")
    assert_k0_equal(t2n, t3n, name="tau_north")
