def make_synthetic_vertical(nk=10, dz=10.0, nspace=4, drf=None):
    """Build a small synthetic dataset mimicking the LLC vertical grid.

    The depth coordinate ``Z`` is stored MITgcm-style (negative-upward).
    Tracer-cell centres sit at the middle of each layer; ``drF`` is the
    layer thickness.  A dummy ``Theta`` is included so helpers that infer
    the vertical dimension from ``ds.Theta`` work.

    Parameters
    ----------
    nk : int
        Number of tracer levels.
    dz : float
        Uniform layer thickness (m) when *drf* is None.
    nspace : int
        Size of each (square) horizontal dimension of the dummy field.
    drf : array_like or None
        Optional per-level thicknesses (m); overrides the uniform *dz* and
        produces a non-uniform grid.

    Returns
    -------
    ds : xarray.Dataset
        Dataset with ``Z`` (k, negative-upward), ``Zl`` (k_l), ``drF`` (k)
        and a zero ``Theta`` (k, j, i).
    z_pos : numpy.ndarray
        The positive-downward centre depths (m), for building test fields.

    Generated by JXP and Claude
    """
    thick = np.full(nk, dz, float) if drf is None else np.asarray(drf, float)
    # Interfaces (positive-down): 0, thick0, thick0+thick1, ...
    iface = np.concatenate([[0.0], np.cumsum(thick)])     # length nk+1
    z_pos = 0.5 * (iface[:-1] + iface[1:])                # centre depths
    ds = xr.Dataset({
        # MITgcm convention: negative-upward.
        "Z": xr.DataArray(-z_pos, dims=("k",)),
        "Zl": xr.DataArray(-iface[:-1], dims=("k_l",)),
        "drF": xr.DataArray(thick, dims=("k",)),
        "Theta": xr.DataArray(np.zeros((nk, nspace, nspace)),
                              dims=("k", "j", "i")),
    })
    return ds, z_pos


def vertical_field(values_1d, nspace=4):
    """Broadcast a 1-D vertical profile to a ``(k, j, i)`` field.

    Parameters
    ----------
    values_1d : array_like
        Per-level values defining the profile along ``k``.
    nspace : int
        Size of each horizontal dimension.

    Returns
    -------
    xarray.DataArray
        Field on ``(k, j, i)`` constant across the horizontal.

    Generated by JXP and Claude
    """
    v = np.asarray(values_1d, float)
    arr = v[:, None, None] * np.ones((1, nspace, nspace))
    return xr.DataArray(arr, dims=("k", "j", "i"))


