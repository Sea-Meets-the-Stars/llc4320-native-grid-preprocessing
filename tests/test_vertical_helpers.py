def load_real_llc_vertical(cache_path=REAL_VERTICAL_CACHE):
    """Load the real LLC4320 1-D vertical coordinates, caching locally.

    Fetches ``Z``, ``Zl``, ``Zu``, ``Zp1`` and ``drF`` from the LLC4320
    grid store via :func:`get_raw_data.get_llc_depth_gridfile` (these are
    tiny 1-D arrays, ~51 elements) and caches them to NetCDF.

    Parameters
    ----------
    cache_path : str
        Local NetCDF cache path (overridable via ``LLC_TEST_VERTICAL_CACHE``).

    Returns
    -------
    xarray.Dataset
        Dataset of the real vertical coordinates (MITgcm negative-upward).

    Generated by JXP and Claude
    """
    if os.path.exists(cache_path):
        return xr.open_dataset(cache_path)

    from dbof.llc4320_ingestion import get_raw_data
    co = get_raw_data.get_llc_depth_gridfile(
        REAL_GRID_S3["s3_endpoint"], REAL_GRID_S3["bucket"],
        REAL_GRID_S3["folder"])

    out = {}
    for name in _REAL_VERTICAL_VARS:
        if name in co:
            out[name] = co[name].compute()
        elif name in co.coords:
            out[name] = co.coords[name].compute()
    ds = xr.Dataset(out)
    try:
        ds.to_netcdf(cache_path)
    except OSError:
        pass
    return ds


@pytest.mark.slow
@pytest.mark.network
@pytest.mark.skipif(not RUN_NETWORK,
                    reason="needs network/S3; set RUN_LLC_NETWORK_TESTS=1")
def test_real_depth_coord_sign_and_monotonic():
    """Real ``Z`` (negative-upward) converts to monotonic positive depth.

    The genuine LLC4320 ``Z`` runs from ~-0.5 m to ~-945 m.  The helper must
    return a strictly increasing positive-downward depth starting near the
    surface, equal to ``-Z``.

    Generated by JXP and Claude
    """
    ds = load_real_llc_vertical()
    assert np.nanmean(ds["Z"].values) < 0           # really negative-upward

    depth = vh._get_depth_coord(ds, zdim="k")
    assert depth.dims == ("k",)
    assert np.all(depth.values >= 0)
    assert np.all(np.diff(depth.values) > 0)         # strictly increasing
    assert depth.values[0] < 2.0                     # surface near 0
    assert depth.values[-1] > 500.0                  # deepest level deep
    np.testing.assert_allclose(depth.values, -ds["Z"].values)


@pytest.mark.slow
@pytest.mark.network
@pytest.mark.skipif(not RUN_NETWORK,
                    reason="needs network/S3; set RUN_LLC_NETWORK_TESTS=1")
def test_real_vertical_spacing_drF_consistent():
    """Real ``drF`` is positive and spans the full depth range.

    The tracer-level thicknesses must be positive, increase with depth
    (LLC4320 refines toward the surface), and sum to the total depth range
    spanned by the cell interfaces ``Zp1``.

    Generated by JXP and Claude
    """
    ds = load_real_llc_vertical()
    dz = vh._get_vertical_spacing(ds, zdim="k")

    assert dz.dims == ("k",)
    assert np.all(dz.values > 0)
    assert dz.values[0] < dz.values[-1]              # refines near surface
    if "Zp1" in ds:
        span = float(np.abs(ds["Zp1"].values[-1] - ds["Zp1"].values[0]))
        np.testing.assert_allclose(dz.values.sum(), span, rtol=1e-4)


@pytest.mark.slow
@pytest.mark.network
@pytest.mark.skipif(not RUN_NETWORK,
                    reason="needs network/S3; set RUN_LLC_NETWORK_TESTS=1")
def test_real_vertical_derivative_linear_exact():
    """d/dz of a linear profile is exact on the *real* non-uniform levels.

    Centered/forward/backward differences are exact for a linear field even
    on the genuine non-uniform LLC4320 ``Z`` spacing, so a profile
    ``f = slope * depth`` recovers ``slope`` at every level.

    Generated by JXP and Claude
    """
    ds = load_real_llc_vertical()
    depth = vh._get_depth_coord(ds, zdim="k").values
    slope = 0.123
    field = vertical_field(slope * depth)
    deriv = vh._vertical_derivative(field, ds)
    np.testing.assert_allclose(deriv.values, slope, rtol=1e-6, atol=1e-9)
