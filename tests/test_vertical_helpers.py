"""Unit tests for ``dbof.preprocessing.vertical_helpers``.

These helpers manage the *vertical* axis of LLC4320 depth diagnostics:
identifying the vertical dimension, converting the MITgcm
negative-upward ``Z`` to a positive-downward depth, choosing the right
layer-thickness variable, and the depth reductions built on top of those
(vertical derivative, select-at-depth, extract-at-MLD, W->tracer
interpolation, mixed-layer mean).

Two things are easy to get wrong and are tested explicitly:

* **Sign convention.** MITgcm stores ``Z`` negative-upward (``Z < 0`` below
  the surface).  ``_get_depth_coord`` must return a *positive-downward*
  depth (0 at surface, increasing downward).  A missed flip would silently
  invert every depth comparison (MLD masks, nearest-k, derivative spacing).
* **Vertical spacing.** Tracer levels (``k``) use ``drF``; W levels
  (``k_l``) use ``drC`` (falling back to a finite difference of the depth
  coordinate).  Using the wrong thickness mis-weights every mixed-layer
  mean.

The tests are a mix of **offline** synthetic fixtures (uniform/known
spacing, answers exact) and **online** checks against the *real* LLC4320
vertical coordinates (the genuine non-uniform 51-level ``Z``/``Zl``/``drF``,
fetched once from S3 and cached).  The online tests reuse the network gate
from ``test_jacobian`` and are skipped by default.

Generated by JXP and Claude
"""

import os
import tempfile
import warnings

import numpy as np
import xarray as xr
import pytest

import dbof.preprocessing.vertical_helpers as vh

# Reuse the real-grid S3 config + network gate from the Jacobian tests.
