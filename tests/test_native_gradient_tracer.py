def test_tracer_real_grid_constant_field_zero_gradient():
    """Constant tracer -> exactly zero gradient on the real grid.

    Because ``calculate_native_gradient_tracer`` differences the tracer
    *before* rotating the gradient, a constant tracer yields an exactly zero
    gradient everywhere -- even at grid singularities where ``CS``/``SN``
    vary rapidly (no ``grad(CS)`` term can appear, unlike the velocity
    Jacobian).  Asserted to machine precision over the ocean interior.

    Returns
    -------
    None
        Passes by assertion.

    Generated by JXP and Claude
    """
    ds = load_real_llc_grid()
    grid = set_xgcm_grid(ds.drop_vars("hFacC"), use_connections=True)

    # A spatially constant tracer on tracer centres.
    s = xr.full_like(ds["CS"], 10.0)

    grad_lambda, grad_phi = ng.calculate_native_gradient_tracer(s, ds, grid)

    ocean = interior(ds["hFacC"]).values > 0
    assert ocean.any()
    for out in (grad_lambda, grad_phi):
        vals = interior(out).values[ocean]
        vals = vals[np.isfinite(vals)]
        assert np.max(np.abs(vals)) < 1e-12


# Sphere radius used by the analytic lon/lat targets.  MITgcm/ECCO treat
# the Earth as a sphere of ~6370-6371 km; the two conventions differ by
# 0.02%, far inside the test tolerances, so the exact choice is immaterial.
R_SPHERE = 6.371e6


def analytic_geographic_gradient(kind, lon_deg, lat_deg):
    """Closed-form geographic gradient of an analytic lon/lat tracer.

    Two globally smooth tracers with known gradients (lambda = longitude,
    phi = latitude, R = sphere radius):

    * ``'sin_lat'``: ``s = sin(phi)``.  Zonal gradient 0; meridional
      gradient ``cos(phi) / R``.
    * ``'sin_lon_cos_lat'``: ``s = sin(lambda) cos(phi)`` (the Cartesian
      y-coordinate of the unit sphere, so it is smooth across the
      dateline and the poles).  Zonal gradient ``cos(lambda) / R``;
      meridional gradient ``-sin(lambda) sin(phi) / R``.

    Parameters
    ----------
    kind : str
        ``'sin_lat'`` or ``'sin_lon_cos_lat'``.
    lon_deg, lat_deg : numpy.ndarray
        Longitude / latitude in degrees (any matching shape).

    Returns
    -------
    s : numpy.ndarray
        The tracer values.
    g_zonal, g_merid : numpy.ndarray
        Analytic zonal and meridional gradient components (1/m).

    Generated by JXP and Claude
    """
    lon = np.deg2rad(lon_deg.astype("float64"))
    lat = np.deg2rad(lat_deg.astype("float64"))
    if kind == "sin_lat":
        s = np.sin(lat)
        g_zonal = np.zeros_like(s)
        g_merid = np.cos(lat) / R_SPHERE
    elif kind == "sin_lon_cos_lat":
        s = np.sin(lon) * np.cos(lat)
        g_zonal = np.cos(lon) / R_SPHERE
        g_merid = -np.sin(lon) * np.sin(lat) / R_SPHERE
    else:
        raise ValueError(f"unknown analytic tracer kind: {kind}")
    return s, g_zonal, g_merid


@pytest.mark.slow
@pytest.mark.network
@pytest.mark.skipif(not RUN_NETWORK,
                    reason="needs network/S3; set RUN_LLC_NETWORK_TESTS=1")
@pytest.mark.parametrize("kind", ["sin_lat", "sin_lon_cos_lat"])
def test_tracer_real_grid_face_consistency_analytic_field(kind):
    """Every face reproduces the analytic gradient of a lon/lat tracer.

    Builds a globally smooth tracer directly from the real grid's cell-
    centre longitude/latitude (``XC``/``YC``) whose geographic gradient is
    known in closed form, then asserts the computed (zonal, meridional)
    components match the analytic ones **on every face separately**.

    This is the reviewer-requested check that "the faces are doing what
    they should": a staggering mistake (e.g. ending on the U point on some
    faces and the V point on others), a per-face sign flip, or a swapped
    component would show up as an O(1) relative error on the affected
    face, while the discretisation error of the smooth field is orders of
    magnitude smaller.  Because the tracer is consistent across face
    boundaries, this also exercises the ``face_connections`` halo with a
    field whose truth is known (unlike the synthetic per-face linear
    fields, which are deliberately inconsistent at the seams).

    The comparison is restricted to **ocean** points (``hFacC > 0``):
    over land the grid stores fill values ``CS = SN = 0``, so the rotated
    gradient is identically zero there and the analytic target cannot be
    reproduced -- a property of the grid files, not of the code under
    test.  Errors are normalised by the gradient scale ``1/R`` so the
    thresholds are dimensionless: per-face median < 1e-3 and 95th
    percentile < 5e-3 (observed: medians ~1e-4, p95 ~5e-4).  The floor is set by float32 ``XC``/``YC``
    quantisation (~0.4 m position noise over ~1-2 km cells), not by the
    numerics under test.

    Parameters
    ----------
    kind : str
        Analytic tracer kind (pytest-parametrized; see
        :func:`analytic_geographic_gradient`).

    Returns
    -------
    None
        Passes by assertion.

    Generated by JXP and Claude
    """
    ds = load_real_llc_grid()
    grid = set_xgcm_grid(ds.drop_vars("hFacC"), use_connections=True)

    s_np, gz_np, gm_np = analytic_geographic_gradient(
        kind, ds["XC"].values, ds["YC"].values)
    s = xr.DataArray(s_np, dims=("face", "j", "i"),
                     coords={c: ds.coords[c] for c in ("face", "j", "i")},
                     name="S")

    grad_lambda, grad_phi = ng.calculate_native_gradient_tracer(s, ds, grid)

    # Dimensionless error: (computed - analytic) / (1/R).
    err_z = (interior(grad_lambda).values
             - interior(xr.DataArray(gz_np, dims=("face", "j", "i"))).values
             ) * R_SPHERE
    err_m = (interior(grad_phi).values
             - interior(xr.DataArray(gm_np, dims=("face", "j", "i"))).values
             ) * R_SPHERE

    # Ocean only: over land CS = SN = 0 (fill), so the rotation zeroes the
    # gradient by construction and no comparison is meaningful there.
    ocean = interior(ds["hFacC"]).values > 0

    for face in range(N_FACES):
        mask = ocean[face]
        pooled = np.concatenate(
            [np.abs(err_z[face][mask]).ravel(),
             np.abs(err_m[face][mask]).ravel()])
        pooled = pooled[np.isfinite(pooled)]
        assert pooled.size > 0
        med = np.median(pooled)
        p95 = np.percentile(pooled, 95.0)
        assert med < 1e-3, f"face {face} ({kind}): median {med:.2e}"
        assert p95 < 5e-3, f"face {face} ({kind}): 95th pct {p95:.2e}"


@pytest.mark.slow
@pytest.mark.network
@pytest.mark.skipif(not RUN_NETWORK,
                    reason="needs network/S3; set RUN_LLC_NETWORK_TESTS=1")
def test_tracer_real_grid_gradient_magnitude_invariance():
    """Gradient magnitude is rotation-invariant on the real grid.

    The rotation acts on the already-computed gradient vector, so
    ``|grad_geographic| = |grad_model|`` exactly (``CS^2 + SN^2 = 1``),
    independent of how ``CS``/``SN`` vary.  Feeds a real surface tracer
    (Theta) and compares the geographic-frame gradient magnitude to the
    model-frame magnitude (identity rotation) computed from the same tracer.

    Asserts robust statistics: the signal is genuinely non-zero (not a
    trivial 0 == 0), the median difference is ~0, and the relative RMS
    difference is at machine precision (empirically ~3e-8 in float32).

    Returns
    -------
    None
        Passes by assertion.

    Generated by JXP and Claude
    """
    ds = load_real_llc_grid()
    grid = set_xgcm_grid(ds.drop_vars("hFacC"), use_connections=True)

    tracer = load_real_llc_surface_tracer()
    tracer = tracer.assign_coords(
        {c: ds.coords[c] for c in tracer.dims if c in ds.coords})

    gx_geo, gy_geo = ng.calculate_native_gradient_tracer(tracer, ds, grid)
    gx_mod, gy_mod = model_frame_gradient(tracer, ds, grid)

    mag_geo = np.sqrt(gx_geo ** 2 + gy_geo ** 2)
    mag_mod = np.sqrt(gx_mod ** 2 + gy_mod ** 2)

    ocean = interior(ds["hFacC"]).values > 0
    g = interior(mag_geo).values[ocean]
    m = interior(mag_mod).values[ocean]
    finite = np.isfinite(g) & np.isfinite(m)
    g, m = g[finite], m[finite]

    signal_rms = np.sqrt(np.mean(m ** 2))
    diff = np.abs(g - m)
    diff_rms = np.sqrt(np.mean(diff ** 2))

    assert signal_rms > 1e-6                 # real, non-trivial signal
    assert np.median(diff) < 1e-12           # bit-identical for most points
    assert diff_rms / signal_rms < 1e-5      # machine precision (~3e-8)
    assert np.percentile(diff, 99.0) < 1e-9
