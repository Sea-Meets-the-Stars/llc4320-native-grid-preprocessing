def test_tracer_no_rotation_recovers_model_gradient():
    """No rotation (CS=1, SN=0): gradient equals the model slopes (p, q).

    With the identity rotation the geographic axes coincide with the model
    axes, so for ``s = p*x + q*y`` the two returned components must equal
    the constant slopes ``p`` and ``q`` over every face interior, validating
    the derivative values and the ``/dxC``, ``/dyC`` scaling.

    Returns
    -------
    None
        Passes by assertion.

    Generated by JXP and Claude
    """
    d = 2500.0
    p, q = 1.0e-4, -3.0e-4
    ds, grid = make_synthetic_grid(n=16, d=d, cs=1.0, sn=0.0)
    s = add_linear_tracer(ds, d, p, q)

    grad_lambda, grad_phi = ng.calculate_native_gradient_tracer(s, ds, grid)

    tol = dict(rtol=1e-9, atol=0.0)
    np.testing.assert_allclose(interior(grad_lambda).values, p, **tol)
    np.testing.assert_allclose(interior(grad_phi).values, q, **tol)

    for out in (grad_lambda, grad_phi):
        assert "i_g" not in out.dims and "j_g" not in out.dims
        assert set(("face", "j", "i")).issubset(out.dims)


def test_tracer_90deg_rotation_sign_conventions():
    """90-degree rotation (CS=0, SN=1): gradient becomes ``(-q, p)``.

    ``R(90) . (p, q) = (-q, p)``.  The flipped signs and swapped roles
    exercise the sign conventions of the gradient-vector rotation -- the
    part most prone to error.

    Returns
    -------
    None
        Passes by assertion.

    Generated by JXP and Claude
    """
    d = 2500.0
    p, q = 1.0e-4, -3.0e-4
    ds, grid = make_synthetic_grid(n=16, d=d, cs=0.0, sn=1.0)
    s = add_linear_tracer(ds, d, p, q)

    grad_lambda, grad_phi = ng.calculate_native_gradient_tracer(s, ds, grid)

    t_lambda, t_phi = analytic_rotated_gradient(p, q, cs=0.0, sn=1.0)
    tol = dict(rtol=1e-7, atol=1e-12)
    np.testing.assert_allclose(interior(grad_lambda).values, t_lambda, **tol)
    np.testing.assert_allclose(interior(grad_phi).values, t_phi, **tol)


def test_tracer_constant_field_zero_gradient():
    """A constant tracer has zero gradient under any rotation.

    The gradient of a constant is identically zero; the rotation of the
    zero vector is zero.  With a non-trivial 45-degree rotation, every
    interior component must be zero to machine precision -- confirming the
    machinery introduces no spurious gradient.

    Returns
    -------
    None
        Passes by assertion.

    Generated by JXP and Claude
    """
    d = 2500.0
    alpha = np.radians(45.0)
    ds, grid = make_synthetic_grid(n=16, d=d,
                                   cs=np.cos(alpha), sn=np.sin(alpha))
    # Constant tracer: zero slopes plus an arbitrary offset.
    s = add_linear_tracer(ds, d, 0.0, 0.0) + 7.0

    grad_lambda, grad_phi = ng.calculate_native_gradient_tracer(s, ds, grid)

    for out in (grad_lambda, grad_phi):
        np.testing.assert_allclose(interior(out).values, 0.0, atol=1e-15)


