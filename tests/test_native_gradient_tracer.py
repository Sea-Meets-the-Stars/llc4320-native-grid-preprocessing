def test_tracer_output_coordinate_contract():
    """Outputs live on tracer points with the input shape.

    Independent of rotation, both gradient components must be on tracer
    centres (dims ``face, j, i``), carry no staggered ``i_g``/``j_g`` axes,
    and preserve the per-face ``(n, n)`` shape.

    Returns
    -------
    None
        Passes by assertion.

    Generated by JXP and Claude
    """
    d = 2500.0
    n = 16
    alpha = np.radians(33.0)
    ds, grid = make_synthetic_grid(n=n, d=d,
                                   cs=np.cos(alpha), sn=np.sin(alpha))
    s = add_linear_tracer(ds, d, 1.0e-4, -3.0e-4)

    outputs = ng.calculate_native_gradient_tracer(s, ds, grid)
    for out in outputs:
        assert "i_g" not in out.dims and "j_g" not in out.dims
        assert set(("face", "j", "i")).issubset(out.dims)
        assert out.sizes["face"] == N_FACES
        assert out.sizes["i"] == n
        assert out.sizes["j"] == n


