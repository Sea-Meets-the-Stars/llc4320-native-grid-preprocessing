def load_real_llc_surface_tracer(var=REAL_TRACER_VAR,
                                 cache_path=REAL_TRACER_CACHE):
    """Load a real LLC4320 surface tracer, caching locally.

    Reads the surface (k=0) tracer from the LLC_SURF OSN kerchunk store via
    :func:`get_raw_data.get_remote_llc_data` (a true surface-only read) and
    caches it to a local NetCDF.

    Parameters
    ----------
    var : str
        Tracer variable name (default ``'Theta'``, sea-surface temperature).
    cache_path : str
        Local NetCDF cache path (overridable via ``LLC_TEST_TRACER_CACHE``).

    Returns
    -------
    xarray.DataArray
        Tracer on centre points ``(face, j, i)``.

    Generated by JXP and Claude
    """
    if os.path.exists(cache_path):
        return xr.open_dataset(cache_path)[var]

    from dbof.llc4320_ingestion import get_raw_data
    from dbof.global_dataset_creation.data_sources import OSN_ENDPOINT
    from dbof.global_dataset_creation.iterations import osn_date_to_iteration

    it = osn_date_to_iteration(REAL_UV_DATE)
    ds = get_raw_data.get_remote_llc_data(OSN_ENDPOINT, it, range(N_FACES))
    tracer = ds[var].astype("float32").compute()
    try:
        xr.Dataset({var: tracer}).to_netcdf(cache_path)
    except OSError:
        pass
    return tracer


