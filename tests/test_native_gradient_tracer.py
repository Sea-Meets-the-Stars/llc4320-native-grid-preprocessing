"""Unit tests for ``dbof.utils.native_gradient.calculate_native_gradient_tracer``.

This is the scalar-tracer companion to ``test_jacobian.py``.  Where the
Jacobian rotates a velocity *tensor*, ``calculate_native_gradient_tracer``
computes the gradient *vector* of a scalar tracer ``s`` on the native LLC
grid: it takes model-x / model-y finite differences (``grid.diff / dxC``,
``grid.diff / dyC``), interpolates them to tracer centres, then rotates the
gradient vector into geographic (zonal/meridional) axes with
``R = [[CS, -SN], [SN, CS]]``:

    grad_lambda = gx*CS - gy*SN,   grad_phi = gx*SN + gy*CS

where ``gx = ds/dx`` and ``gy = ds/dy`` are the model-basis gradients.

Two facts drive the tests:

* For a **linear** tracer ``s = slope_x*x + slope_y*y`` on a uniform grid
  the model gradients are exactly ``(slope_x, slope_y)``, so the rotated
  result is the closed form ``(slope_x*CS - slope_y*SN,
  slope_x*SN + slope_y*CS)`` -- an analytic target.  (``slope_x`` /
  ``slope_y`` are prescribed tracer slopes, in tracer units per metre --
  nothing to do with pressure.)
* The rotation is applied to the **already-differenced** gradient, so
  (unlike the velocity Jacobian) a **constant tracer gives an exactly zero
  gradient even on the real curvilinear grid**, and the **gradient
  magnitude is exactly rotation-invariant** (``|R g| = |g|`` pointwise,
  since ``CS^2 + SN^2 = 1``).  Both hold to machine precision regardless of
  how ``CS``/``SN`` vary.

Synthetic fixtures (13-face topology, uniform metrics, constant rotation)
and the real-grid loader are reused from ``test_jacobian`` so the two test
modules stay consistent.

Generated by JXP and Claude
"""

