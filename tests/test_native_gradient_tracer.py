def add_linear_tracer(ds, d, p, q):
    """Add a linear tracer ``s = p*x + q*y`` on tracer centres.

    Linear fields are differenced and interpolated exactly on a uniform
    grid, so the model-basis gradient is exactly ``(p, q)`` and the rotated
    result is analytic.  Only the slopes ``p``/``q`` matter, so any constant
    offset is irrelevant.

    Parameters
    ----------
    ds : xarray.Dataset
        Synthetic grid from :func:`make_synthetic_grid`; provides the
        ``face``/``j``/``i`` centre coordinates.
    d : float
        Uniform grid spacing in metres (matches the grid metrics).
    p, q : float
        Tracer slopes ds/dx and ds/dy (model basis).

    Returns
    -------
    xarray.DataArray
        Tracer on centre points ``(face, j, i)``.

    Generated by JXP and Claude
    """
    n = ds.sizes["i"]
    pos = np.arange(n) * d
    s2d = p * pos[None, :] + q * pos[:, None]            # (j, i)
    s3d = np.broadcast_to(s2d, (N_FACES, n, n)).copy()
    return xr.DataArray(s3d, dims=("face", "j", "i"),
                        coords={c: ds.coords[c]
                                for c in ("face", "j", "i")},
                        name="S")


def analytic_rotated_gradient(p, q, cs, sn):
    """Return the analytic geographic gradient ``R . (p, q)``.

    Parameters
    ----------
    p, q : float
        Model-basis tracer gradients ds/dx and ds/dy.
    cs, sn : float
        Rotation coefficients ``CS = cos(alpha)`` and ``SN = sin(alpha)``.

    Returns
    -------
    grad_lambda, grad_phi : float
        Zonal and meridional gradient components, in the order returned by
        ``calculate_native_gradient_tracer``.

    Generated by JXP and Claude
    """
    return p * cs - q * sn, p * sn + q * cs


def model_frame_gradient(s, ds, grid):
    """Return the tracer gradient with the rotation forced to the identity.

    Re-runs ``calculate_native_gradient_tracer`` on a copy of ``ds`` whose
    rotation coefficients are ``CS=1, SN=0``, giving the *model-frame*
    gradient components ``(ds/dx, ds/dy)`` at centres -- the reference for
    the magnitude-invariance check.

    Parameters
    ----------
    s : xarray.DataArray
        Tracer on centre points.
    ds : xarray.Dataset
        Grid dataset (its ``CS``/``SN`` are overridden; ``dxC``/``dyC`` kept).
    grid : xgcm.Grid
        Grid object with the LLC ``face_connections``.

    Returns
    -------
    tuple of xarray.DataArray
        ``(ds/dx, ds/dy)`` in the model frame.

    Generated by JXP and Claude
    """
    ds_id = ds.copy()
    ds_id["CS"] = xr.ones_like(ds["CS"])
    ds_id["SN"] = xr.zeros_like(ds["SN"])
    return ng.calculate_native_gradient_tracer(s, ds_id, grid)


