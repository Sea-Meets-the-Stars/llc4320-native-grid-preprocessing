"""
Tests for the surface-only tile series path (``tile_utils.run_series``).

The question these answer: can the tile machinery -- written for 3D DEPTH
data -- produce ``gradb2`` from a *surface-only* input, hour after hour, for
one tile?  Three things have to hold:

- the field functions are dimension-agnostic, so a ``(face, j, i)`` input
  yields a clean ``(j, i)`` output with no ``k`` dim and no ``Z`` coord;
- the tile geometry, the tile grid and the xgcm grid are resolved ONCE for the
  whole series -- a 504-step run cannot afford to rebuild the 12960x17280
  rect lookup (deliberately uncached, see ``tile_mapping``) 504 times;
- ``gradb2`` NaNs its ``edge_margin=3`` rim, because a single-face tile has no
  face connections and the stencil is invalid there.

All S3/OSN access is monkeypatched; this module is fully offline.

Generated by LH and Claude
"""

import numpy as np
import pytest
import xarray as xr

import dbof.tiles.tile_mapping as tm
import dbof.tiles.tile_utils as tu

TIMESTAMPS = [
    "2012-06-29 00:00:00",
    "2012-06-29 01:00:00",
    "2012-06-29 02:00:00",
]


def _patch_lookup(monkeypatch):
    """Every rect pixel -> face 0, face-local coords = rect coords mod 4320."""
    face_id = np.zeros((tm.RECT_H, tm.RECT_W), dtype=np.int8)
    jj = np.arange(tm.RECT_H, dtype=np.int16) % tm.FACE_SIZE
    ii = np.arange(tm.RECT_W, dtype=np.int16) % tm.FACE_SIZE
    j_map = np.broadcast_to(jj[:, None], (tm.RECT_H, tm.RECT_W)).copy()
    i_map = np.broadcast_to(ii[None, :], (tm.RECT_H, tm.RECT_W)).copy()
    monkeypatch.setattr(tm, "_build_lookup_arrays",
                        lambda: (face_id, j_map, i_map))


def _surface_grid_face() -> xr.Dataset:
    """A 2D tile grid: no Z, no drF -- what the OSN kerchunk grid gives.

    Carries exactly what ``grad_b2`` needs (``dxC``, ``dyC``) plus ``XC``/
    ``YC`` for the output coords and ``hFacC`` for the land mask.
    """
    n = tm.TILE_SIZE
    d = 2500.0
    XC = np.broadcast_to(np.linspace(-128.0, -113.0, n)[None, :], (n, n))
    YC = np.broadcast_to(np.linspace(26.5, 38.0, n)[:, None], (n, n))
    return xr.Dataset(
        data_vars={
            "XC":    (("face", "j", "i"),   XC[None].astype(np.float32)),
            "YC":    (("face", "j", "i"),   YC[None].astype(np.float32)),
            "dxC":   (("face", "j", "i_g"), np.full((1, n, n), d)),
            "dyC":   (("face", "j_g", "i"), np.full((1, n, n), d)),
            "hFacC": (("face", "j", "i"),   np.ones((1, n, n), np.float32)),
        },
        coords={
            "face": np.array([0]),
            "j":   ("j",   np.arange(n), {"axis": "Y"}),
            "i":   ("i",   np.arange(n), {"axis": "X"}),
            "j_g": ("j_g", np.arange(n), {"axis": "Y",
                                          "c_grid_axis_shift": 0.5}),
            "i_g": ("i_g", np.arange(n), {"axis": "X",
                                          "c_grid_axis_shift": 0.5}),
        },
    )


def _surface_tracers_face(scale: float) -> xr.Dataset:
    """2D Theta/Salt with a real horizontal structure, so gradb2 > 0.

    *scale* varies the amplitude per timestamp, so the snapshots differ and a
    stale-file bug cannot pass unnoticed.
    """
    n = tm.TILE_SIZE
    x = np.arange(n)[None, :] / n
    y = np.arange(n)[:, None] / n
    theta = 12.0 + scale * (2.0 * np.sin(2 * np.pi * x)
                            + 1.5 * np.cos(2 * np.pi * y))
    salt = 33.5 + scale * 0.4 * np.cos(2 * np.pi * x)
    ds = xr.Dataset(
        data_vars={
            "Theta": (("face", "j", "i"),
                      np.broadcast_to(theta, (n, n))[None].astype(np.float32)),
            "Salt":  (("face", "j", "i"),
                      np.broadcast_to(salt, (n, n))[None].astype(np.float32)),
        },
        coords={"face": np.array([0])},
    )
    return ds.chunk({"j": 360, "i": 360})


@pytest.fixture
def stubbed(monkeypatch):
    """Patch every network seam and count the once-per-run loads."""
    _patch_lookup(monkeypatch)
    monkeypatch.setattr(tu, "_git_commit_hash", lambda: "deadbeef")
    monkeypatch.setattr(
        tu, "_resolve_s3_source",
        lambda _, pipeline=None: {"kind": "OSN", "s3_endpoint": "stub"},
    )

    calls = {"grid": 0, "tracers": []}
    grid_face = _surface_grid_face()

    def fake_grid(s3_cfg, tile):
        calls["grid"] += 1
        return grid_face.isel(face=[0], j=tile.j_face_slice,
                              i=tile.i_face_slice).compute()

    def fake_tracers(s3_cfg, date_str, tile, vars_needed):
        calls["tracers"].append(date_str)
        # Keyed on the timestamp, not on the call count, so the same hour
        # always yields the same field however many times it is read.
        scale = 1.0 + 0.5 * TIMESTAMPS.index(date_str)
        return _surface_tracers_face(scale)[list(vars_needed)].isel(
            face=[0], j=tile.j_face_slice, i=tile.i_face_slice)

    monkeypatch.setattr(tu, "_load_grid_for_tile", fake_grid)
    monkeypatch.setattr(tu, "_load_tracers_for_tile", fake_tracers)
    return calls


def test_series_surface_only_gradb2(stubbed, tmp_path):
    """504-step shape, in miniature: 2D output, one grid load, NaN rim."""
    out = tu.run_series(
        TIMESTAMPS, i_rect=100, j_rect=10, property="gradb2",
        pipeline="OSN", config_path=None, output_dir=str(tmp_path),
    )

    # One file per timestamp -- the shape the front finder consumes.
    assert len(out) == len(TIMESTAMPS)
    assert [p.name for p in out] == [
        "gradb2_tile000_20120629T00.nc",
        "gradb2_tile000_20120629T01.nc",
        "gradb2_tile000_20120629T02.nc",
    ]
    assert all(p.exists() for p in out)

    # The expensive, timestamp-independent work happened exactly once.
    assert stubbed["grid"] == 1
    assert stubbed["tracers"] == TIMESTAMPS

    ds = xr.open_dataset(out[0], engine="h5netcdf")
    try:
        # Surface-only in, surface-only out: no vertical axis anywhere.
        assert dict(ds.sizes) == {"j": tm.TILE_SIZE, "i": tm.TILE_SIZE}
        assert "Z" not in ds.coords
        assert "gradb2" in ds
        assert ds["gradb2"].dtype == np.float32
        assert ds.attrs["property"] == "gradb2"
        assert ds.attrs["edge_margin"] == 3
        # OSN provenance: the shifted iteration numbering, as generate_global
        # records for the SURF pipeline.
        from dbof.global_dataset_creation.iterations import (
            osn_date_to_iteration,
        )
        assert ds.attrs["iteration"] == osn_date_to_iteration(TIMESTAMPS[0])

        arr = ds["gradb2"].values
        # The 3-cell rim is invalid on a single-face tile and must be NaN.
        assert np.isnan(arr[:3, :]).all() and np.isnan(arr[-3:, :]).all()
        assert np.isnan(arr[:, :3]).all() and np.isnan(arr[:, -3:]).all()
        # ...and everything inside it must be finite and physical.
        interior = arr[3:-3, 3:-3]
        assert np.isfinite(interior).all()
        assert (interior >= 0).all() and interior.max() > 0
    finally:
        ds.close()

    # Snapshots must actually differ (no stale-file / cached-graph bug).
    # gradb2 is ~1e-16 s^-4 here, far under allclose's default atol, so the
    # comparison has to be relative.
    a = xr.open_dataset(out[0], engine="h5netcdf")["gradb2"].values[3:-3, 3:-3]
    b = xr.open_dataset(out[1], engine="h5netcdf")["gradb2"].values[3:-3, 3:-3]
    assert np.nanmax(np.abs(a - b) / np.abs(b)) > 0.1


def test_series_matches_single_run(stubbed, tmp_path):
    """run_series and run must agree cell for cell on the same snapshot."""
    series = tu.run_series(
        TIMESTAMPS[:1], i_rect=100, j_rect=10, property="gradb2",
        pipeline="OSN", config_path=None, output_dir=str(tmp_path / "series"),
    )
    single = tu.run(
        i_rect=100, j_rect=10, timestamp=TIMESTAMPS[0], property="gradb2",
        pipeline="OSN", config_path=None, output=str(tmp_path / "single"),
    )
    a = xr.open_dataset(series[0], engine="h5netcdf")["gradb2"].values
    b = xr.open_dataset(single, engine="h5netcdf")["gradb2"].values
    np.testing.assert_array_equal(np.isnan(a), np.isnan(b))
    np.testing.assert_allclose(a[3:-3, 3:-3], b[3:-3, 3:-3], rtol=1e-6)


def test_series_explicit_output_paths(stubbed, tmp_path):
    """A consumer can dictate the filenames (the fronts driver does)."""
    wanted = [tmp_path / f"LLC4320_{i}_gradb2_v1.nc"
              for i in range(len(TIMESTAMPS))]
    out = tu.run_series(
        TIMESTAMPS, i_rect=100, j_rect=10, property="gradb2",
        pipeline="OSN", config_path=None,
        output_paths=[str(w) for w in wanted],
    )
    assert [p.name for p in out] == [w.name for w in wanted]


def test_series_skips_existing_without_clobber(stubbed, tmp_path):
    """Re-running is cheap: present files are not recomputed."""
    tu.run_series(TIMESTAMPS[:1], i_rect=100, j_rect=10, property="gradb2",
                  pipeline="OSN", config_path=None, output_dir=str(tmp_path))
    n_after_first = len(stubbed["tracers"])
    out = tu.run_series(TIMESTAMPS[:1], i_rect=100, j_rect=10,
                        property="gradb2", pipeline="OSN", config_path=None,
                        output_dir=str(tmp_path))
    assert len(stubbed["tracers"]) == n_after_first   # no second read
    assert len(out) == 1 and out[0].exists()


def test_series_continue_on_error(stubbed, tmp_path, monkeypatch):
    """One bad hour must not throw away the other 503."""
    real = tu._load_tracers_for_tile

    def flaky(s3_cfg, date_str, tile, vars_needed):
        if date_str == TIMESTAMPS[1]:
            raise OSError("simulated OSN read failure")
        return real(s3_cfg, date_str, tile, vars_needed)

    monkeypatch.setattr(tu, "_load_tracers_for_tile", flaky)

    with pytest.raises(OSError):
        tu.run_series(TIMESTAMPS, i_rect=100, j_rect=10, property="gradb2",
                      pipeline="OSN", config_path=None,
                      output_dir=str(tmp_path / "strict"))

    out = tu.run_series(TIMESTAMPS, i_rect=100, j_rect=10, property="gradb2",
                        pipeline="OSN", config_path=None,
                        output_dir=str(tmp_path / "lenient"),
                        continue_on_error=True)
    assert len(out) == 2
    assert all("20120629T01" not in p.name for p in out)


def test_series_rejects_bad_arguments(stubbed, tmp_path):
    with pytest.raises(ValueError, match="timestamps is empty"):
        tu.run_series([], i_rect=100, j_rect=10, pipeline="OSN")
    with pytest.raises(ValueError, match="exactly one"):
        tu.run_series(TIMESTAMPS, pipeline="OSN")
    with pytest.raises(ValueError, match="output_paths has"):
        tu.run_series(TIMESTAMPS, i_rect=100, j_rect=10, pipeline="OSN",
                      output_paths=["only-one.nc"])
