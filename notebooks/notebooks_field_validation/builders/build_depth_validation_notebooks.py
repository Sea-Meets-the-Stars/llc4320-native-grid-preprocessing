def build(subset, spec):
    """Write ``depth_fields/{subset}.ipynb`` from its spec.

    Inputs
    ------
    subset : str
        DEPTH subset name / notebook stem.
    spec : dict
        One entry of :data:`SPECS`.

    Outputs
    -------
    None (writes the .ipynb and prints the path).

    Generated by LH and Claude.
    """
    cells = []

    md(cells, f"""\
# Field validation — `{subset}` (DEPTH pipeline)

| | |
|---|---|
| Subset | `{subset}` |
| Pipeline | DEPTH |
| Timestep | 2012-11-09 12:00:00 |
| Domain | one 720 × 720 × 51 tile (≈1400 × 1400 km), set in Section 1 |
| Depth levels | `sfc`, `z25m`, `mld`, `mld_mean` |
| Data | computed on the fly from `s3://dbof/LLC4320_RAW/DEPTH/` |
| Plan | `prompts/field_validation_depth.md` |
| Field reference | `docs/Fields.md` |

Rows of every figure are **depth levels**, not regions — that is the one
structural difference from the surface notebooks.{spec['header_extra']}""")

    md(cells, SETUP_MD)
    code(cells, SETUP_CELL.format(subset=subset,
                                  raw_vars=spec["raw_vars"]))

    md(cells, LOAD_MD)
    code(cells, LOAD_CELL)

    md(cells, COMPUTE_MD)
    code(cells, spec["live_cell"])
    code(cells, PACK_CELL)

    md(cells, spec["section3_md"])
    md(cells, spec["dep_table"])

    md(cells, HELPERS_MD)
    chains_lines = [
        f'    "{k}": {json.dumps(v)},' for k, v in spec["chains"].items()
    ]
    chains_src = "{\n" + "\n".join(chains_lines) + "\n}"
    log_src = ("set()" if not spec["log_fields"]
               else "{" + ", ".join(f'"{x}"'
                                    for x in sorted(spec["log_fields"]))
               + "}")
    code(cells, HELPERS_CELL.format(chains=chains_src, log_fields=log_src))

    for field, title, desc in spec["fields"]:
        md(cells, f"### {title}\n\n{desc}")
        code(cells, f'figure1_maps("{field}")')
        code(cells, f'figure2_pdfs("{field}")')

    md(cells, LIT_MD)

    md(cells, SUMMARY_MD)
    code(cells, SUMMARY_CELL)
    code(cells, CHECKS_HEAD + spec["checks"] + CHECKS_TAIL)

    md(cells, spec["crossref"])

    nb = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3",
                           "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    path = OUT_DIR + f"{subset}.ipynb"
    Path(OUT_DIR).mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)
    print(f"wrote {path} ({len(cells)} cells)")


if __name__ == "__main__":
    import sys

    only = set(sys.argv[1:])
    for name, s in SPECS.items():
        if not only or name in only:
            build(name, s)
