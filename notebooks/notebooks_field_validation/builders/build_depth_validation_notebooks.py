def build_pointer(subset, channels):
    """Write a short pointer notebook for a surface-only DEPTH subset.

    Inputs
    ------
    subset : str
        Subset name / notebook stem.
    channels : str
        Human-readable channel list.

    Outputs
    -------
    None (writes the .ipynb).

    Generated by LH and Claude.
    """
    cells = []
    md(cells, f"""\
# Field validation — `{subset}` (DEPTH pipeline)

**This subset is `surface_only`.  It is validated in
[`../surface_fields/{subset}.ipynb`](../surface_fields/{subset}.ipynb),
not here.**

| | |
|---|---|
| Subset | `{subset}` |
| `surface_only` | `True` in `subset_definitions.DEPTH_SUBSETS` |
| Channels | {channels} |
| Validated in | `surface_fields/{subset}.ipynb` |

`get_subset_definition("DEPTH", "{subset}")` returns the same channel
list as the SURF definition, and the DEPTH pipeline runs the same
compute function on the same k=0 data — it only differs in which S3
store the raw data is read from.  There are no depth suffixes, no
vertical structure, and nothing the surface notebook does not already
cover, so duplicating it here would mean two copies of one validation
drifting apart.

This file exists so the subset → notebook mapping stays 1:1.  If the
DEPTH variant of this subset ever stops being `surface_only`, replace
this pointer with a real notebook built from
`builders/build_depth_validation_notebooks.py`.
""")
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3",
                                      "language": "python",
                                      "name": "python3"},
                       "language_info": {"name": "python",
                                         "version": "3"}},
          "nbformat": 4, "nbformat_minor": 5}
    path = OUT_DIR + f"{subset}.ipynb"
    Path(OUT_DIR).mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)
    print(f"wrote {path} (pointer)")


