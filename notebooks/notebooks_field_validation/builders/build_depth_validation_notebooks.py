"""
Generator for the DEPTH field-validation notebooks.

Writes ``notebooks/notebooks_field_validation/depth_fields/{subset}.ipynb``.
Runnable from any working directory; OVERWRITES the notebook, so re-run
the notebook itself afterwards.

    python builders/build_depth_validation_notebooks.py             # all
    python builders/build_depth_validation_notebooks.py stratification

Same shape as ``build_field_validation_notebooks.py`` (the surface
generator): shared cell templates + one ``SPECS`` entry per subset + a
generic ``build()``.  The difference is what the figures do -- the
surface notebooks put a REGION on each row, these put a DEPTH LEVEL --
and where the data comes from: one 720x720x51 tile of the raw DEPTH
store, computed on the fly, rather than a ``generate-global`` run.
Plan: ``prompts/field_validation_depth.md``.

Generated by LH and Claude.
"""

import json
import uuid
from pathlib import Path


def _repo_root():
    """Repo root: the nearest ancestor holding pyproject.toml.

    Outputs
    -------
    Path

    Generated by LH and Claude.
    """
    here = Path(__file__).resolve()
    for cand in (here, *here.parents):
        if (cand / "pyproject.toml").exists():
            return cand
    raise FileNotFoundError(f"no pyproject.toml above {here}")


OUT_DIR = str(_repo_root() / "notebooks"
              / "notebooks_field_validation"
              / "depth_fields") + "/"


def md(cells, src):
    """Append a markdown cell.  Generated by LH and Claude."""
    cells.append({"cell_type": "markdown", "id": uuid.uuid4().hex[:8],
                  "metadata": {}, "source": src})


def code(cells, src):
    """Append a code cell.  Generated by LH and Claude."""
    cells.append({"cell_type": "code", "id": uuid.uuid4().hex[:8],
                  "metadata": {}, "execution_count": None,
                  "outputs": [], "source": src})


