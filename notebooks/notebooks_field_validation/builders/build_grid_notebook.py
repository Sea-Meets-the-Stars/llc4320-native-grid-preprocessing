print(f"blanked {int(np.isnan(gdepth).sum()) - _nseam:,} seam cells "
      f"of {gdepth.size:,}")
print(f"global Depth, {regions.GLOBAL_DOWNSAMPLE}x downsampled: "
      f"{gdepth.shape}")

