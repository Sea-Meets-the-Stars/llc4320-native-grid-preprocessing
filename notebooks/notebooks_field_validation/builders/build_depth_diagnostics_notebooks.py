def _repo_root():
    """Repo root: the nearest ancestor holding pyproject.toml.

    Outputs
    -------
    Path

    Generated by LH and Claude.
    """
    here = Path(__file__).resolve()
    for cand in (here, *here.parents):
        if (cand / "pyproject.toml").exists():
            return cand
    raise FileNotFoundError(f"no pyproject.toml above {here}")


OUT_DIR = str(_repo_root() / "notebooks"
              / "notebooks_field_validation") + "/"


def md(cells, src):
    """Append a markdown cell.  Generated by LH and Claude."""
    cells.append({"cell_type": "markdown", "id": uuid.uuid4().hex[:8],
                  "metadata": {}, "source": src})


def code(cells, src):
    """Append a code cell.  Generated by LH and Claude."""
    src = src.rstrip().rstrip("\\").rstrip()
    cells.append({"cell_type": "code", "id": uuid.uuid4().hex[:8],
                  "metadata": {}, "execution_count": None,
                  "outputs": [], "source": src})


def write(subset, cells):
    """Serialise the cells to ``{subset}.ipynb``.

    Generated by LH and Claude.
    """
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3",
                                      "language": "python",
                                      "name": "python3"},
                       "language_info": {"name": "python",
                                         "version": "3"}},
          "nbformat": 4, "nbformat_minor": 5}
    path = OUT_DIR + f"{subset}.ipynb"
    Path(OUT_DIR).mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)
    print(f"wrote {path} ({len(cells)} cells)")


