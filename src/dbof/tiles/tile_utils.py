def run(
    i_rect: int | None = None,
    j_rect: int | None = None,
    timestamp: str = None,
    property: str = "density",
    output: str | None = None,
    config_path: Path | None = DEFAULT_CONFIG,
    clobber: bool = False,
    gen_qa_plot: bool = False,
    lon: float | None = None,
    lat: float | None = None,
    mask_land: bool = True,
) -> Path:
    """End-to-end pipeline: resolve tile -> load -> compute -> save NetCDF + PNG.

    The target tile is selected either by rect-grid pixel (``i_rect``,
    ``j_rect``) or by geographic coordinate (``lon``, ``lat``); supply exactly
    one of the two pairs.  A geographic request is resolved to the nearest rect
    pixel via :func:`latlon_to_rect_ij` before the usual tile lookup.

    Parameters
    ----------
    i_rect, j_rect : int, optional
        Rect-grid pixel coordinates; any pixel inside the desired tile is OK.
        Mutually exclusive with (``lon``, ``lat``).
    timestamp : str
        Snapshot timestamp in ``DATE_FMT``.
    property : str, default ``'density'``
        Channel name from :mod:`dbof.tiles.field_registry` (e.g.
        ``'N2'``, ``'relative_vorticity'``) or a legacy alias
        (``'temperature'``, ``'salinity'``); selects which field to
        extract.
    output : str or None
        Output path -- see :func:`_build_output_path`.
    config_path : Path or None
        Optional legacy YAML override with an ``s3_source`` block.  When
        ``None`` (default) the canonical LLC_DEPTH source is used (see
        :func:`_resolve_s3_source`).
    clobber : bool, default False
        If True, overwrite an existing output file; otherwise skip and return.
    gen_qa_plot : bool, default False
        If True, also write a surface QA plot (PNG) next to the NetCDF.
    lon, lat : float, optional
        Geographic longitude/latitude of the desired tile.  Mutually exclusive
        with (``i_rect``, ``j_rect``); resolved to the nearest rect pixel via
        :func:`latlon_to_rect_ij`.
    mask_land : bool, default True
        NaN land cells via ``hFacC == 0`` (see
        :func:`compute_tile_property`).

    Returns
    -------
    Path
        Absolute path of the written NetCDF.  If the output file already
        existed and ``clobber`` was False the run is skipped, but the existing
        path is still returned (the function always promises a ``Path``).

    Raises
    ------
    KeyError
        If ``property`` is not a registered key in :data:`TILE_PROPERTIES`.
    ValueError
        If neither or both of the (i_rect, j_rect) / (lon, lat) pairs are given,
        or if ``timestamp`` is missing.
    """
    # Channel-name lookup with legacy aliases (temperature, salinity).
    prop = resolve_property(property)

    if timestamp is None:
        raise ValueError("timestamp is required")

    # Validate that exactly one location convention was supplied.
    have_ij = i_rect is not None and j_rect is not None
    have_lonlat = lon is not None and lat is not None
    if have_ij == have_lonlat:
        raise ValueError(
            "Supply exactly one of (i_rect, j_rect) or (lon, lat) -- "
            f"got i_rect={i_rect}, j_rect={j_rect}, lon={lon}, lat={lat}."
        )

    # Resolve the S3 source up front (needed now for a geographic lookup, and
    # reused for the grid/tracer loads below).  Canonical DEPTH source unless a
    # legacy YAML override is passed.
    s3_cfg = _resolve_s3_source(config_path)

    # A geographic request is turned into a rect pixel via the grid file.
    if have_lonlat:
        i_rect, j_rect = latlon_to_rect_ij(lon, lat, s3_cfg)

    # 1-2: resolve tile geometry and iteration number.
    tile = rect_ij_to_tile(i_rect, j_rect)
    iteration = mit_date_to_iteration(timestamp)
    logging.info(
        f"Resolved tile: idx={tile.tile_idx} "
        f"(tile_j_rect={tile.tile_j_rect}, tile_i_rect={tile.tile_i_rect})  "
        f"face={tile.face_idx}  "
        f"face j={tile.j_face_slice}, i={tile.i_face_slice}  "
        f"property={prop.name}"
    )

    # Create out_path
    out_path = _build_output_path(
        output, tile.tile_idx, timestamp, filename_prefix=prop.filename_prefix,
    )
    if out_path.exists() and not clobber:
        logging.info(f"Output file {out_path} already exists. Skipping.")
        return out_path

    # 3: load grid for the tile (output coords, metrics, hFacC mask).
    ds_grid_tile = _load_grid_for_tile(s3_cfg, tile)

    # 4-5: lazy-open tracers (only the vars this property needs) and
    # slice.  Properties with no tracer inputs (e.g. coriolis_f) still
    # get a valid (empty) dataset merged with the grid below.
    ds_tracers_tile = _load_tracers_for_tile(
        s3_cfg, timestamp, tile, vars_needed=list(prop.vars_needed),
    ) if prop.vars_needed else xr.Dataset()

    # 5b: merged tile dataset + LOCAL xgcm grid (no face connections).
    ds_merge, xgrid = _build_tile_context(ds_tracers_tile, ds_grid_tile)

    # 6: compute property (edge rim NaN per registry; hFacC land mask
    # unless mask_land=False).
    field = compute_tile_property(ds_merge, xgrid, prop,
                                  mask_land=mask_land)

    # 7: assemble output dataset with coords + provenance.
    ds_out = _build_output_dataset(
        field=field,
        ds_grid_tile=ds_grid_tile,
        tile=tile,
        prop=prop,
        date_str=timestamp,
        iteration=iteration,
        rect_i_user=i_rect,
        rect_j_user=j_rect,
    )

    # 8: resolve filename and save.

    out_path.parent.mkdir(parents=True, exist_ok=True)
    logging.info(f"Saving NetCDF: {out_path}")
    ds_out.to_netcdf(
        out_path,
        engine="h5netcdf",
        encoding={
            prop.out_name: {"zlib": True, "complevel": 4, "dtype": "float32"},
        },
    )

    # 9: surface QA plot next to the NetCDF.
    if gen_qa_plot:
        png_path = out_path.with_suffix(".png")
        logging.info(f"Saving QA plot: {png_path}")
        _qa_plot(ds_out, prop, png_path)

    return out_path
