def _qa_plot(
    ds_out: xr.Dataset,
    prop: TileProperty,
    png_path: Path,
) -> None:
    """Save a single surface pcolormesh of the property next to the NetCDF.

    Parameters
    ----------
    ds_out : xr.Dataset
        The output dataset produced by :func:`_build_output_dataset`.
    prop : TileProperty
        Used to look up the variable name and units for the plot.
    png_path : Path
        Where to write the PNG (typically ``out_path.with_suffix('.png')``).
    """
    fig, ax = plt.subplots(figsize=(8, 7))
    da = ds_out[prop.out_name]
    # 3D fields: plot the surface level; 2D fields: plot as-is.
    surf = da.isel(k=0) if "k" in da.dims else da
    pcm = ax.pcolormesh(
        ds_out["XC"].values,
        ds_out["YC"].values,
        surf.values,
        shading="auto",
    )
    ax.set_xlabel("longitude")
    ax.set_ylabel("latitude")
    level = "(k=0)" if "k" in da.dims else "(2D)"
    ax.set_title(
        f"{prop.out_name} {level}  tile={int(ds_out['tile_index'])}  "
        f"{ds_out.attrs['timestamp']}"
    )
    fig.colorbar(pcm, ax=ax, label=f"{prop.out_name} [{prop.units}]")
    fig.tight_layout()
    fig.savefig(png_path, dpi=120)
    plt.close(fig)


