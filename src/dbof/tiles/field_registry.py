@dataclass(frozen=True)
class TileProperty:
    """Specification for a single field extractable as a tile.

    Attributes
    ----------
    name : str
        Public name at the CLI — the subset channel name.
    vars_needed : tuple of str
        S3 store variables required.
    out_name : str
        Variable name written to the output NetCDF.
    units : str
        ``units`` attribute for the output variable.
    long_name : str
        ``long_name`` attribute for the output variable.
    filename_prefix : str
        Prefix used in the default output filename.
    compute : Callable
        ``(ds_merge, grid) -> xr.DataArray`` (lazy), where ``ds_merge``
        is the merged tile dataset and ``grid`` the local xgcm grid.
    edge_margin : int
        Invalid-rim width (cells) at the tile boundary; NaN'd by
        ``compute_tile_property`` and recorded as an output attr.
    """
    name:            str
    vars_needed:     tuple[str, ...]
    out_name:        str
    units:           str
    long_name:       str
    filename_prefix: str
    compute:         Callable[[xr.Dataset, object], xr.DataArray]
    edge_margin:     int = 0


# ---------------------------------------------------------------------------
# Small adapter factories (plumbing only — no physics)
# ---------------------------------------------------------------------------

def _passthrough(var):
    """Adapter: return a stored (tracer-point, scalar) variable as-is.

    Valid only for scalars already on tracer points (``Theta``,
    ``Eta``, ``oceQnet``, ...).  Never use it for a vector component:
    ``U``/``V``/``oceTAUX``/``oceTAUY`` are on staggered C-grid faces
    and follow the MODEL x/y axes, so they need the canonical CS/SN
    rotation instead (docs/Tiles.md §Vector rotation).

    Inputs: var (str) — variable name in the tile dataset.
    Outputs: callable ``(ds_merge, grid) -> xr.DataArray``.
    Generated by LH and Claude
    """
    def _compute(ds_merge, grid):
        return ds_merge[var]
    return _compute


def _no_grid(fn):
    """Adapter for canonical functions with signature ``fn(ds_merge)``.

    Inputs: fn (callable).
    Outputs: callable ``(ds_merge, grid) -> xr.DataArray``.
    Generated by LH and Claude
    """
    def _compute(ds_merge, grid):
        return fn(ds_merge)
    return _compute


def _pick(fn, index):
    """Adapter extracting one component from a multi-output function.

    Inputs: fn (callable ``(ds_merge, grid) -> tuple | dict``); index
    (int or str) — position or key of the wanted component.
    Outputs: callable ``(ds_merge, grid) -> xr.DataArray``.
    Generated by LH and Claude
    """
    def _compute(ds_merge, grid):
        return fn(ds_merge, grid)[index]
    return _compute


def _w_centred(ds_merge, grid):
    """W interpolated from k_l interfaces to tracer levels.

    Inputs: ds_merge (tile dataset with ``W``); grid (unused).
    Outputs: xr.DataArray, W on tracer levels [m s-1].
    Generated by LH and Claude
    """
    return _interp_w_to_tracer_levels(ds_merge)


def _frontogenesis_ageo(ds_merge, grid):
    """Ageostrophic frontogenesis F(u,v) − F(ug,vg).

    Mirrors the dispatcher-inline definition in
    ``surface_subsets.compute_frontogenesis`` (no canonical CF
    function exists for the residual).
    Inputs: ds_merge (tile dataset); grid (local xgcm grid).
    Outputs: xr.DataArray [s-5], lazy.
    Generated by LH and Claude
    """
    tendency = CF.frontogenesis_tendency(ds_merge, grid)
    geo = CF.frontogenesis_geo(ds_merge, grid)
    return tendency - geo


