#: Legacy CLI names (pre-generalization) -> channel names.
ALIASES: dict[str, str] = {
    "temperature": "Theta",
    "salinity": "Salt",
    # "density" is itself a channel name and needs no alias.
}


def resolve_property(name: str) -> TileProperty:
    """Look up a tile property by channel name or legacy alias.

    Inputs
    ------
    name : str
        Channel name (e.g. ``'N2'``) or legacy alias
        (``'temperature'``, ``'salinity'``).

    Outputs
    -------
    TileProperty
        The registry entry.

    Raises
    ------
    KeyError
        With the sorted list of valid names if ``name`` is unknown.

    Generated by LH and Claude
    """
    key = ALIASES.get(name, name)
    if key not in TILE_PROPERTIES:
        raise KeyError(
            f"Unknown property '{name}'.  Available: "
            f"{sorted(TILE_PROPERTIES) + sorted(ALIASES)}"
        )
    return TILE_PROPERTIES[key]
