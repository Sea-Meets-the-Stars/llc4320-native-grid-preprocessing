"""
field_registry.py
-----------------
Registry of every field that can be extracted as an LLC4320 tile.

One :class:`TileProperty` per OUTPUT FIELD, named exactly like the
subset channels in ``global_dataset_creation.subset_definitions``
(``N2``, ``mixed_layer_depth``, ``relative_vorticity``, ...), plus
legacy aliases (``temperature`` -> ``Theta``, ``salinity`` ->
``Salt``; ``density`` is itself a channel name).

Design rules and rationale: docs/Tiles.md (§How the registry works,
§Edge margin, §Vector rotation).  Per-channel definitions, units and
equations: docs/Fields.md.
"""

from __future__ import annotations

from dataclasses import dataclass
