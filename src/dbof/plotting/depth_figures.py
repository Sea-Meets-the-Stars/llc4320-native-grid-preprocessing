"""
depth_figures.py
----------------
Figures for the DEPTH field-validation notebooks, plus the small amount
of data shaping they need.

A note on the word "grid", because this repo uses it for two unrelated
things.  In THIS module a *grid* is the rows x columns array of panels
in a figure -- matplotlib's sense, and the same sense as the surface
module ``pipeline_grids.py``.  The model's Arakawa C-grid (tracer
centres, staggered faces, corners) is a different thing entirely and
lives in ``docs/Grid.md``, ``docs/Gradients.md`` and
``utils/native_gradient.py``.  Nothing here touches it.

Layout
------
The surface notebooks put a REGION on each row.  The depth notebooks
fix one tile and put a DEPTH LEVEL on each row instead.  Columns are
unchanged: the dependency chain, raw -> intermediate -> final.

:func:`depth_map_grid` is eight rows: the four levels over the whole
tile, then the same four zoomed to a 200 x 200 km box, whose position
is the crimson square on the whole-tile rows.

:func:`depth_pdf_grid` is four rows -- the whole tile at each level.
The zoom boxes are too small to make an honest histogram, so they are
deliberately absent.  Bins are shared down a COLUMN, so reading a
column top to bottom shows how the distribution changes with depth.

Data shaping
------------
:func:`compute_levels` reduces lazy 3D fields to the four levels, and
:func:`pack_tile_levels` turns computed channels into the
``{base: {level: (x, y, arr)}}`` mapping both figure functions consume
-- NaN'ing the tile's edge rim and masking land on the way.  Same job
``live_fields.py`` does for the surface notebooks.

Colour conventions (cmaps, labels, log scales, diverging centring, land
grey) come from the same registry and the same helpers the surface
figures use.  Nothing is hard-coded here.

Generated by LH and Claude.
"""

