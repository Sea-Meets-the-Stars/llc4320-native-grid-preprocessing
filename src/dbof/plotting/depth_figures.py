def region_anchor(region):
    """Return the ``(lon, lat)`` a region's tile and zoom are centred on.

    A tile SAMPLES a region, it does not cover it, so a depth notebook
    needs a point rather than a box.  We reuse the ``zoom`` anchors
    already pinned in ``regions.py`` -- the same points the surface
    notebooks zoom into -- so surface and depth look at the same water.

    Inputs
    ------
    region : str
        Key in ``regions.REGIONS`` carrying a ``zoom`` anchor.

    Outputs
    -------
    (lon, lat) : tuple[float, float]

    Raises
    ------
    ValueError
        If the region has no anchor (``global``, ``kerguelen``).

    Generated by LH and Claude.
    """
    anchor = regions_mod.REGIONS.get(region, {}).get("zoom")
    if anchor is None:
        have = sorted(k for k, v in regions_mod.REGIONS.items()
                      if v.get("zoom"))
        raise ValueError(
            f"region '{region}' has no 'zoom' anchor in regions.py, so "
            f"there is no point to centre a tile on.  Regions with one: "
            f"{have}"
        )
    return float(anchor[0]), float(anchor[1])


def edge_margin_for(bases):
    """Widest invalid rim among these fields, from the tile registry.

    A tile's xgcm grid has no face connections, so fields with a
    horizontal stencil are wrong near the boundary.  ``field_registry``
    already records how many cells that is per field (0 vertical-only,
    1 staggered interpolation, 3 gradient / Jacobian chains); this just
    takes the worst case over the chain so one rim covers the figure.

    Names the registry does not know (live intermediates such as
    ``rho_theta``) are skipped -- pass an explicit margin if one of them
    is the widest thing in your chain.

    Inputs
    ------
    bases : iterable of str
        Field base names.

    Outputs
    -------
    int
        Rim width in cells; 0 if none of the names is in the registry.

    Generated by LH and Claude.
    """
    known = [TILE_PROPERTIES[b].edge_margin for b in bases
             if b in TILE_PROPERTIES]
    return max(known) if known else 0


