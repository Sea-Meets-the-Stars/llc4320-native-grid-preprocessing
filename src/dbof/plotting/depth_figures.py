def depth_map_grid(chain, level_arrays, cmap_cfg, *, region,
                   levels=DEPTH_LEVELS,
                   diverging_cmaps=frozenset(),
                   log_scale_channels=frozenset(),
                   percentiles=(1, 99),
                   zoom_rows=True,
                   zoom_half_km=ZOOM_HALF_KM,
                   suptitle=None):
    """Figure 1: dependency chain across columns, depth levels down rows.

    Rows 1..N are the levels over the whole tile; rows N+1..2N repeat
    them zoomed to a ``2 * zoom_half_km`` square, whose position is
    drawn as a crimson box on the whole-tile rows.

    One colour scale per COLUMN, built from the pooled whole-tile values
    of every level and reused by that column's zoom rows -- so both the
    depth rows and the zoom rows are directly comparable.

    Inputs
    ------
    chain : list[str]
        Field base names in dependency order (the columns).  Every entry
        must be a key of ``level_arrays``.
    level_arrays : dict[str, dict[str, tuple]]
        ``level_arrays[base][level] = (x, y, arr)`` -- from
        :func:`pack_tile_levels`.
    cmap_cfg : dict[str, tuple[str, str]]
        ``field_cmaps.load_field_cmaps()`` registry: name -> (cmap, label).
    region : str
        Region key, used for the zoom anchor.
    levels : tuple[str]
        Depth levels, in row order.
    diverging_cmaps : set[str]
        Colormap NAMES to centre at zero.
    log_scale_channels : set[str]
        Field names drawn on a log colour scale.
    percentiles : tuple[float, float]
        Colour-limit percentiles.
    zoom_rows : bool
        Add the zoomed rows.  Turn off for a quick 4-row look.
    zoom_half_km : float
        Half-width of the zoom square, in km.
    suptitle : str or None
        Figure title.

    Outputs
    -------
    (fig, axes) : tuple
        ``axes`` has shape ``(n_rows, len(chain))``.

    Generated by LH and Claude.
    """
    n_lev = len(levels)
    n_rows = n_lev * 2 if zoom_rows else n_lev
    n_cols = len(chain)

    bounds = zoom_bounds(region, half_km=zoom_half_km) if zoom_rows else None

    fig, axes = plt.subplots(
        n_rows, n_cols, squeeze=False,
        figsize=(n_cols * PANEL_W, n_rows * PANEL_H),
    )

    for j, field in enumerate(chain):
        by_level = level_arrays[field]
        cmap_name, _ = cmap_cfg.get(field, ("viridis", field))

        # ONE norm per column, pooled over the whole-tile rows.  The zoom
        # rows reuse it so a feature does not change colour when you zoom.
        pooled = np.concatenate(
            [by_level[lev][2].ravel() for lev in levels])
        norm = make_field_norm(
            pooled, cmap_name,
            log=field in log_scale_channels,
            diverging_cmaps=diverging_cmaps,
            percentiles=percentiles,
        )

        im_last, label = None, field
        for i in range(n_rows):
            lev = levels[i % n_lev]
            zoomed = zoom_rows and i >= n_lev
            x, y, arr = by_level[lev]
            if zoomed:
                x, y, arr = crop_lonlat_box(x, y, arr, *bounds)

            ax = axes[i, j]
            ax.set_facecolor(LAND_COLOR)   # NaNs are not drawn -> grey land
            im, label = plot_global_field(
                ax, x, y, arr, field, cmap_cfg,
                diverging_cmaps=diverging_cmaps,
                transform=None, add_coastline=False, norm=norm,
            )
            if im is not None:
                im_last = im
            if not zoomed and zoom_rows:
                _draw_box(ax, bounds)

            ax.set_xticks([])
            ax.set_yticks([])
            if i == 0:
                ax.set_title(field, fontsize=9)
            if j == 0:
                title = LEVEL_TITLES.get(lev, lev)
                if zoomed:
                    title = f"{title}\n{2 * zoom_half_km:.0f} km zoom"
                ax.set_ylabel(title, fontsize=9)

        if im_last is not None:
            fig.colorbar(im_last, ax=axes[:, j].tolist(),
                         orientation="horizontal", fraction=0.03,
                         pad=0.02, label=label)

    if suptitle:
        fig.suptitle(suptitle, fontsize=12, y=1.005)
    return fig, axes


