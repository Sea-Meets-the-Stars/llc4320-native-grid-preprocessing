def tile_coords(ds_grid):
    """Return the tile's 2D ``(XC, YC)`` as plain numpy arrays.

    Inputs
    ------
    ds_grid : xr.Dataset
        Tile grid from ``tile_utils._load_grid_for_tile``.

    Outputs
    -------
    (XC, YC) : tuple[np.ndarray, np.ndarray]
        Longitude / latitude on dims ``(j, i)``, face squeezed out.

    Generated by LH and Claude.
    """
    return (ds_grid["XC"].isel(face=0).values,
            ds_grid["YC"].isel(face=0).values)


def tile_land_mask(ds_grid):
    """Boolean land mask (True = land) from the tile's surface ``hFacC``.

    The DEPTH grid store's ``hFacC`` is already collapsed to ``k=0``, and
    the production depth pipeline masks with that same surface mask, so
    this matches what the global stores contain.

    Inputs
    ------
    ds_grid : xr.Dataset
        Tile grid from ``tile_utils._load_grid_for_tile``.

    Outputs
    -------
    np.ndarray
        Boolean ``(j, i)`` array, True where the cell is land.

    Generated by LH and Claude.
    """
    hfac = ds_grid["hFacC"]
    if "k" in hfac.dims:
        hfac = hfac.isel(k=0)
    return (hfac.isel(face=0).values == 0)


#: Horizontal dimension names that must be chunked identically before a
#: field and the MLD are indexed together.
_HORIZONTAL_DIMS = ("j", "i", "j_g", "i_g")


def align_chunks(*arrays):
    """Force one common horizontal chunking across several arrays.

    ``_extract_at_mld`` (and anything else that feeds a 3D field and a
    2D MLD into a single ``apply_ufunc``) indexes the two together
    inside one block, so their horizontal chunks must match exactly.
    They often do not: xgcm's ``diff`` / ``interp`` can fuse or split
    blocks, so a field derived through a gradient chain can come out
    chunked 360x360 while the MLD it will be sampled at is still
    180x180.  xarray does not always unify these, and the failure is an
    ``IndexError`` deep inside the ufunc rather than anything readable.

    Production never hits this because ``_ensure_depth_chunking`` uses a
    single 720x720 horizontal block; it only appears once you rechunk
    the horizontal to bound memory.

    Inputs
    ------
    *arrays : xr.DataArray
        Any mix of 2D and 3D arrays.  Non-dask arrays pass through.

    Outputs
    -------
    tuple[xr.DataArray] or xr.DataArray
        The inputs rechunked to the SMALLEST block size present for
        each horizontal dimension.  A single input is returned bare.

    Generated by LH and Claude.
    """
    target = {}
    for a in arrays:
        sizes = getattr(a, "chunksizes", None) or {}
        for d in _HORIZONTAL_DIMS:
            if d in sizes and len(sizes[d]):
                target[d] = min(target.get(d, min(sizes[d])),
                                min(sizes[d]))
    if not target:
        return arrays if len(arrays) > 1 else arrays[0]

    out = tuple(
        a.chunk({d: n for d, n in target.items() if d in a.dims})
        for a in arrays
    )
    return out if len(out) > 1 else out[0]


def reduce_to_levels(field3d, base, ds_merge, mld, levels=DEPTH_LEVELS):
    """Reduce one lazy 3D field to the requested depth levels (still lazy).

    Fields with no vertical dimension (Eta, coriolis_f, MLD itself) pass
    straight through under ``{base}_2d``; :func:`pack_tile_levels`
    broadcasts those down the rows later.

    Inputs
    ------
    field3d : xr.DataArray
        Lazy field on the tile.
    base : str
        Channel base name, e.g. ``"rho_theta"``.
    ds_merge : xr.Dataset
        Merged tile dataset.
    mld : xr.DataArray or None
        Lazy MLD; required for the ``mld`` / ``mld_mean`` levels.
    levels : tuple[str]
        Subset of :data:`DEPTH_LEVELS`.

    Outputs
    -------
    dict[str, xr.DataArray]
        Lazy arrays keyed ``{base}_{level}`` (or ``{base}_2d``).

    Generated by LH and Claude.
    """
    if not (set(field3d.dims) & _VERTICAL_DIMS):
        return {f"{base}_2d": field3d}

    # The mld / mld_mean strategies index the field and the MLD inside
    # one apply_ufunc, so their horizontal chunks have to match.
    if mld is not None:
        field3d, mld = align_chunks(field3d, mld)

    return apply_depth_strategies(
        field3d, base, ds_merge, mld=mld,
        requested={f"{base}_{lev}" for lev in levels},
    )


def compute_levels(lazy_3d, ds_merge, *, mld=None, levels=DEPTH_LEVELS,
                   verbose=True):
    """Reduce a dict of lazy fields to levels, in one ``dask.compute``.

    Use this for the chain's raw inputs and live intermediates (Theta,
    Salt, rho_theta, db_dx, ...) -- the things the global stores never
    keep but the dependency figures need.

    Inputs
    ------
    lazy_3d : dict[str, xr.DataArray]
        Base name -> lazy field on the tile.
    ds_merge : xr.Dataset
        Merged tile dataset.
    mld : xr.DataArray or None
        Lazy MLD.  Required if ``levels`` includes ``mld`` / ``mld_mean``.
    levels : tuple[str]
        Depth levels to produce.
    verbose : bool
        Print the channels produced.

    Outputs
    -------
    dict[str, xr.DataArray]
        Materialised, keyed ``{base}_{level}`` / ``{base}_2d``.

    Generated by LH and Claude.
    """
    lazy_out = {}
    for base, field in lazy_3d.items():
        lazy_out.update(
            reduce_to_levels(field, base, ds_merge, mld, levels=levels))

    keys = list(lazy_out)
    values = dask.compute(*[lazy_out[k] for k in keys], retries=10)
    out = dict(zip(keys, values))
    if verbose:
        print(f"live fields : {sorted(out)}")
    return out


def _as_2d(value):
    """Squeeze a computed channel to a 2D ``(j, i)`` numpy array.

    Inputs
    ------
    value : xr.DataArray or np.ndarray
        A computed channel; may still carry a size-1 ``face`` dim.

    Outputs
    -------
    np.ndarray

    Generated by LH and Claude.
    """
    return np.squeeze(np.asarray(getattr(value, "values", value)))


def channel_base(name, levels=DEPTH_LEVELS):
    """Strip a depth suffix: ``"N2_mld_mean"`` -> ``"N2"``.

    Inputs
    ------
    name : str
        Channel name, with or without a level suffix.
    levels : tuple[str]
        Level suffixes to recognise.

    Outputs
    -------
    str

    Generated by LH and Claude.
    """
    return _split_channel(name, levels)[0]


def _split_channel(name, levels):
    """Split ``"N2_mld_mean"`` into ``("N2", "mld_mean")``.

    Inputs
    ------
    name : str
        Channel name.
    levels : tuple[str]
        Level suffixes to look for.

    Outputs
    -------
    (base, level) : tuple[str, str or None]
        ``level`` is None when there is no recognised suffix.

    Generated by LH and Claude.
    """
    # Longest suffix first, so "mld_mean" wins over "mld".
    for lev in sorted(set(levels) | {"2d", "sfc"}, key=len, reverse=True):
        if name.endswith("_" + lev):
            return name[: -len(lev) - 1], lev
    return name, None


def _nan_rim(arr, margin):
    """NaN a border of *margin* cells on all four sides.

    Same convention as ``tile_utils.compute_tile_property``: the array
    keeps its full 720 x 720 shape and the unusable cells become NaN,
    rather than being trimmed away.

    Inputs
    ------
    arr : np.ndarray
        2D field (modified on a copy).
    margin : int
        Rim width in cells; 0 is a no-op.

    Outputs
    -------
    np.ndarray

    Generated by LH and Claude.
    """
    if margin <= 0:
        return arr
    out = arr.copy()
    out[:margin, :] = np.nan
    out[-margin:, :] = np.nan
    out[:, :margin] = np.nan
    out[:, -margin:] = np.nan
    return out


def pack_tile_levels(channels, XC, YC, *, edge_margin=0, land_mask=None,
                     levels=DEPTH_LEVELS, verbose=True):
    """Turn computed channels into the ``{base: {level: (x, y, arr)}}`` map.

    This is the structure both figure functions consume.  On the way it
    does the two clean-up steps every tile result needs:

    - **NaNs the edge rim**, where the local (no face connections) grid
      made horizontal stencils invalid;
    - **masks land** with the surface ``hFacC``, matching production.

    Channels with no depth suffix, and bases that only ever produce
    ``_sfc`` (Eta, gradeta2, ug, vg), are BROADCAST down the rows so the
    dependency chain still reads left-to-right at every level.  Which
    ones were broadcast is printed, and belongs in the figure caption.

    Inputs
    ------
    channels : dict[str, xr.DataArray | np.ndarray]
        Computed channels, keyed ``{base}_{level}`` / ``{base}_2d`` /
        bare (e.g. ``"mixed_layer_depth"``).
    XC, YC : np.ndarray
        Tile coordinates from :func:`tile_coords`.
    edge_margin : int
        Rim width to NaN; see :func:`edge_margin_for`.
    land_mask : np.ndarray or None
        Boolean ``(j, i)`` land mask from :func:`tile_land_mask`.
        ``None`` skips masking.
    levels : tuple[str]
        Row order.
    verbose : bool
        Print the shape and which bases were broadcast.

    Outputs
    -------
    dict[str, dict[str, tuple]]
        ``out[base][level] = (x, y, arr)``.

    Generated by LH and Claude.
    """
    def _finish(value):
        arr = _nan_rim(_as_2d(value).astype("float32"), edge_margin)
        if land_mask is not None:
            arr = np.where(land_mask, np.nan, arr)
        return (XC, YC, arr)

    grouped = {}
    for name, value in channels.items():
        base, level = _split_channel(name, levels)
        grouped.setdefault(base, {})[level or "2d"] = _finish(value)

    out, broadcast = {}, []
    for base, by_level in grouped.items():
        missing = [lev for lev in levels if lev not in by_level]
        if missing:
            # A 2D field (or a surface-only base): repeat it down the rows.
            source = by_level.get("2d") or by_level.get("sfc")
            if source is None:
                raise KeyError(
                    f"'{base}' has levels {sorted(by_level)} but none of "
                    f"{missing} and nothing to broadcast from."
                )
            broadcast.append(base)
            by_level = {lev: by_level.get(lev, source) for lev in levels}
        out[base] = {lev: by_level[lev] for lev in levels}

    if verbose:
        n_j, n_i = out[next(iter(out))][levels[0]][2].shape
        print(f"packed      : {len(out)} fields on a {n_j} x {n_i} tile, "
              f"{edge_margin}-cell rim NaN'd")
        if broadcast:
            print(f"broadcast   : {sorted(broadcast)} are 2D / surface-only "
                  "-- the same map repeats down the depth rows")
    return out


