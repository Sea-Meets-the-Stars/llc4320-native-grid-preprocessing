# Vertical-stencil A/B  (the depth analogue of the surface sparkle test)
# ---------------------------------------------------------------------------

def vertical_stencil_ab(field, ds_merge):
    """Centred vs one-sided d/dz, separating curvature from cancellation.

    The production vertical derivative uses a CENTRED stencil at
    interior levels::

        (f[k+1] - f[k-1]) / (z[k+1] - z[k-1])

    which never reads level k.  Two DIFFERENT things follow from that,
    and conflating them is misleading:

    - **Curvature.**  Where the two one-sided slopes have the SAME sign
      but different magnitudes -- a monotone kink, e.g. the base of the
      mixed layer -- the centred form returns roughly their mean.  That
      is not an error: it is a correct second-order estimate at a place
      where the derivative genuinely is not well defined.  It drives
      ``dz_asym`` up to at most ~0.5 and no further.
    - **Cancellation.**  Where the two one-sided slopes have OPPOSITE
      signs -- level k is a vertical extremum, an inversion or a spike
      -- they partly annihilate and the centred form can collapse
      toward zero while both one-sided slopes are large.  THIS is the
      vertical analogue of the horizontal "sparkle"
      (``docs/Gradients.md``), and it is what ``dz_signflip`` marks.

    On even spacing ``dz_asym > 0.5`` is reachable ONLY through a sign
    flip, so the two diagnostics agree at the boundary; they are
    reported separately because the interesting quantity is the sign
    flip, and the asymmetry alone overstates the problem badly.

    Returns
    -------
    dict[str, xr.DataArray]
        - ``dz_centred``  -- what the pipeline computes;
        - ``dz_onesided`` -- the larger-magnitude one-sided slope
          straddling level k;
        - ``dz_asym``     -- ``1 - |centred| / |onesided|``.  Bounded by
          ~0.5 for same-sign slopes; mostly a CURVATURE map;
        - ``dz_signflip`` -- 1.0 where the two one-sided slopes have
          opposite signs, else 0.0.  **This is the artifact map.**

    Everything stays lazy.  Top and bottom levels are NaN: the centred
    stencil is undefined there and the production code falls back to a
    one-sided difference, which has no cancellation to measure.

    Inputs
    ------
    field : xr.DataArray
        Lazy 3D field on tracer levels (e.g. potential density, U).
    ds_merge : xr.Dataset
        Merged tile dataset, for the depth coordinate.

    Generated by LH and Claude.
    """
    import xarray as xr

    zdim = _get_vertical_dim(field)
    z = _get_depth_coord(ds_merge, zdim=zdim)

    f_below, f_above = field.shift({zdim: -1}), field.shift({zdim: 1})
    z_below, z_above = z.shift({zdim: -1}), z.shift({zdim: 1})

    # The production stencil: spans 2 levels, never reads level k.
    dz_centred = (f_below - f_above) / (z_below - z_above)

    # The two one-sided slopes that straddle level k.
    slope_above = (field - f_above) / (z - z_above)
    slope_below = (f_below - field) / (z_below - z)

    dz_onesided = xr.where(
        np.abs(slope_above) >= np.abs(slope_below), slope_above,
        slope_below)

    denom = np.abs(dz_onesided)
    dz_asym = xr.where(denom > 0, 1.0 - np.abs(dz_centred) / denom,
                       np.nan)

    # Opposite signs => level k is a vertical extremum => cancellation.
    prod = slope_above * slope_below
    dz_signflip = xr.where(np.isfinite(prod),
                           xr.where(prod < 0, 1.0, 0.0), np.nan)

    for nm, da in (("dz_centred", dz_centred), ("dz_onesided", dz_onesided),
                   ("dz_asym", dz_asym), ("dz_signflip", dz_signflip)):
        da.name = nm
    return {"dz_centred": dz_centred, "dz_onesided": dz_onesided,
            "dz_asym": dz_asym, "dz_signflip": dz_signflip}
