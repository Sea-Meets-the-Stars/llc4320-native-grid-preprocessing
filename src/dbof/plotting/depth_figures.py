# Cropping to the zoom box
# ---------------------------------------------------------------------------

def crop_lonlat_box(x, y, arr, west, east, south, north):
    """Crop a tile to the tightest window covering a lon/lat box.

    Unlike ``regions.crop_zoom`` this makes no assumption that array
    rows are lines of constant latitude.  A tile's face-local axes can
    be rotated or mirrored relative to geographic north, so we build a
    boolean mask of cells inside the box and take its bounding box in
    ARRAY space.

    Inputs
    ------
    x, y : np.ndarray
        2D longitude / latitude of the tile.
    arr : np.ndarray
        2D field on the same mesh.
    west, east, south, north : float
        Box edges in degrees.

    Outputs
    -------
    (xz, yz, sub) : tuple[np.ndarray, np.ndarray, np.ndarray]

    Raises
    ------
    ValueError
        If no cell falls inside the box.

    Generated by LH and Claude.
    """
    # Wrap longitudes onto the box so the dateline is not a special case.
    dlon = (x - west + 180.0) % 360.0 - 180.0
    span = (east - west + 180.0) % 360.0 - 180.0
    if span <= 0:
        span += 360.0
    inside = (dlon >= 0) & (dlon <= span) & (y >= south) & (y <= north)

    if not inside.any():
        raise ValueError(
            f"no tile cells inside lon [{west}, {east}], "
            f"lat [{south}, {north}] -- is the zoom anchor on this tile?"
        )

    rows = np.where(inside.any(axis=1))[0]
    cols = np.where(inside.any(axis=0))[0]
    jsl = slice(int(rows[0]), int(rows[-1]) + 1)
    isl = slice(int(cols[0]), int(cols[-1]) + 1)
    return x[jsl, isl], y[jsl, isl], arr[jsl, isl]


def zoom_bounds(region, *, half_km=ZOOM_HALF_KM):
    """Return ``(west, east, south, north)`` of a region's zoom square.

    Thin wrapper over ``regions.zoom_box`` so this module has one place
    that knows the zoom convention.  The square is centred on the same
    anchor :func:`region_anchor` picks the tile with, so it always falls
    on the tile -- though it can sit near an edge, in which case the
    crop is clipped to whatever the tile holds.

    Inputs
    ------
    region : str
        Region key with a ``zoom`` anchor.
    half_km : float
        Half-width of the square, in km.

    Outputs
    -------
    tuple[float, float, float, float]

    Generated by LH and Claude.
    """
    (west, east), (south, north) = regions_mod.zoom_box(
        region, half_km=half_km)
    return west, east, south, north


def _draw_box(ax, bounds):
    """Draw the crimson zoom locator square on a lon/lat axis.

    Inputs
    ------
    ax : matplotlib axis
    bounds : tuple[float, float, float, float]
        ``(west, east, south, north)``.

    Outputs
    -------
    None (draws on ``ax``).

    Generated by LH and Claude.
    """
    w, e, s, n = bounds
    ax.plot([w, e, e, w, w], [s, s, n, n, s], **BOX_KW)


