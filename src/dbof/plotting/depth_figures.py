def depth_pdf_grid(chain, level_arrays, cmap_cfg, *,
                   levels=DEPTH_LEVELS,
                   log10_fields=frozenset(),
                   n_bins=N_BINS,
                   log_y=False,
                   row_labels=None,
                   suptitle=None):
    """Figure 2: PDFs, dependency chain across columns, levels down rows.

    Whole-tile values only.  Conventions are the surface ones
    (probability density; land and rim NaNs dropped; log10-x for the
    proportional-to-squared fields), with bins shared down a COLUMN so
    the change with depth is readable.

    Inputs
    ------
    chain : list[str]
        Field base names (the columns).
    level_arrays : dict[str, dict[str, tuple]]
        As for :func:`depth_map_grid`.
    cmap_cfg : dict[str, tuple[str, str]]
        Registry -- labels only here.
    levels : tuple[str]
        Depth levels, in row order.
    log10_fields : set[str]
        Fields binned in log10(x).
    n_bins : int
        Shared bin count per field.
    log_y : bool
        Logarithmic density axis.
    row_labels : sequence[str] or None
        Override the row labels; must match ``len(levels)``.
    suptitle : str or None
        Figure title.

    Outputs
    -------
    (fig, axes) : tuple

    Generated by LH and Claude.
    """
    n_rows, n_cols = len(levels), len(chain)
    fig, axes = plt.subplots(
        n_rows, n_cols, squeeze=False,
        figsize=(n_cols * PANEL_W, n_rows * 2.4),
    )

    for j, field in enumerate(chain):
        log10 = field in log10_fields
        _, label = cmap_cfg.get(field, ("viridis", field))
        if log10:
            label = f"log₁₀[{label}]"

        vals = [_clean_values(level_arrays[field][lev][2], log10=log10)
                for lev in levels]
        bins = shared_bins(vals, n_bins=n_bins)

        for i, v in enumerate(vals):
            pdf_panel(axes[i, j], v, bins,
                      label=label if i == n_rows - 1 else None,
                      log_y=log_y)
            if i == 0:
                axes[i, j].set_title(field, fontsize=9)
            if j == 0:
                lab = (row_labels[i] if row_labels is not None
                       else LEVEL_TITLES.get(levels[i], levels[i]))
                axes[i, j].set_ylabel(lab, fontsize=9)

    fig.text(0.005, 0.5, "probability density", rotation=90,
             va="center", fontsize=9)
    if suptitle:
        fig.suptitle(suptitle, fontsize=12, y=1.005)
    fig.tight_layout()
    return fig, axes


