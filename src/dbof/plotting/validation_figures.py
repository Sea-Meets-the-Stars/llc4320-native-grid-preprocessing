"""
validation_figures.py
---------------------
The three standard figures of every field-validation section
(prompts/field_validation.md), extracted from the per-notebook
helper cells so the logic exists once:

- Figure 1: dependency-chain map grid (:meth:`ValidationFigures.maps`);
- Figure 2: dependency-chain PDF grid (:meth:`ValidationFigures.pdfs`);
- Figure 3: our-data vs literature .png
  (:meth:`ValidationFigures.literature`);
- plus :func:`run_consistency_checks` for the store-vs-live cell.

The notebooks instantiate one :class:`ValidationFigures` with their
per-subset config (chains, sliced arrays, colormaps) and bind the
methods to the historical cell-level names::

    _figs = ValidationFigures(chains=CHAINS, ...)
    figure1_maps = _figs.maps
"""

from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
import cartopy.crs as ccrs

from dbof.plotting.global_maps import plot_global_field
from dbof.plotting.pipeline_grids import (
    pipeline_map_grid, mask_wrap_cells, LAND_COLOR,
)
from dbof.plotting.pdfs import pipeline_pdf_grid
from dbof.plotting.literature_comparison import side_by_side

PDF_NOTE = ("PDFs: density; land+rim NaNs removed; shared bins "
            "across domains; log10-x for ∝-squared fields")


class ValidationFigures:
    """Per-subset figure toolkit for the validation notebooks.

    Generated by LH and Claude.

    Inputs
    ------
    chains : dict[str, list[str]]
        Output field -> full dependency chain (figure columns).
    region_arrays : dict
        field -> region -> (x, y, arr) (store + live slices).
    cmap_cfg, diverging :
        From ``field_cmaps.load_field_cmaps()``.
    log_fields : set[str]
        Fields drawn/binned on log scales.
    f_norm : set[str]
        f-normalised fields (|lat|>2 deg filter on the Eq. Pacific
        PDF row — plan Clarification 8).
    lit_dir : Path
        Flat literature-figure directory.
    """

    def __init__(self, *, chains, region_arrays, cmap_cfg,
                 diverging, log_fields, f_norm,
                 lit_dir=Path("../literature_figures")):
        self.chains = chains
        self.region_arrays = region_arrays
        self.cmap_cfg = cmap_cfg
        self.diverging = diverging
        self.log_fields = log_fields
        self.f_norm = f_norm
        self.lit_dir = Path(lit_dir)

    # -- Figure 1 -----------------------------------------------------
    def maps(self, field):
        """Figure 1: dependency-chain map grid for one field.

        Inputs: field (str) — key into ``chains``.
        Outputs: displays the figure.
        Generated by LH and Claude
        """
        note = (" | f-normalised: Eq. Pacific extreme near equator "
                "(expected)" if field in self.f_norm else "")
        pipeline_map_grid(
            self.chains[field], self.region_arrays, self.cmap_cfg,
            diverging_cmaps=self.diverging,
            log_scale_channels=self.log_fields,
            suptitle=(f"Figure 1 — {field}: pipeline maps"
                      f"{note}"),
        )
        plt.show()

    # -- Figure 2 -----------------------------------------------------
    def _pdf_arrays(self, field):
        """Region arrays for the PDF grid (Eq. Pacific |lat|>2 deg
        filter on f-normalised chain members).
        Inputs: field (str).  Outputs: dict like region_arrays.
        Generated by LH and Claude
        """
        out = {}
        for f in self.chains[field]:
            d = dict(self.region_arrays[f])
            if f in self.f_norm and "eq_pacific" in d:
                x, y, a = d["eq_pacific"]
                d["eq_pacific"] = (
                    x, y, np.where(np.abs(y) > 2.0, a, np.nan))
            out[f] = d
        return out

    def pdfs(self, field):
        """Figure 2: dependency-chain PDF grid for one field.

        Inputs: field (str) — key into ``chains``.
        Outputs: displays the figure.
        Generated by LH and Claude
        """
        note = (" | Eq. Pacific: |lat|>2° filter (f-normalised)"
                if set(self.chains[field]) & self.f_norm else "")
        pipeline_pdf_grid(
            self.chains[field], self._pdf_arrays(field),
            self.cmap_cfg, log10_fields=self.log_fields,
            suptitle=(f"Figure 2 — {field}: {PDF_NOTE}{note}"),
        )
        plt.show()

    # -- Figure 3 -----------------------------------------------------
    def literature(self, field, png_name=None, caption=None,
                   global_view=False):
        """Figure 3: our data vs literature .png for one field.

        Inputs: field (str); png_name (str or None) — file in
        ``lit_dir``; caption (str or None); global_view (bool) —
        render OUR panel as a global Robinson map.
        Outputs: displays the figure.
        Generated by LH and Claude
        """
        region = "global" if global_view else "gulf_stream"

        def _render(ax):
            x, y, arr = self.region_arrays[field][region]
            if global_view:
                # Same seam/Arctic handling as the Fig-1 global row.
                arr = mask_wrap_cells(x, y, arr)
            ax.set_facecolor(LAND_COLOR)
            im, label = plot_global_field(
                ax, x, y, arr, field, self.cmap_cfg,
                log_scale_channels=self.log_fields,
                diverging_cmaps=self.diverging,
                transform=(ccrs.PlateCarree() if global_view
                           else None),
                add_coastline=global_view,
                coastline_kw={"linewidth": 0.4, "edgecolor": "k"},
            )
            if im is not None:
                plt.colorbar(im, ax=ax, orientation="horizontal",
                             fraction=0.04, pad=0.04, label=label)

        side_by_side(
            _render,
            self.lit_dir / png_name if png_name else None,
            projection=ccrs.Robinson() if global_view else None,
            caption=caption or ("Discussion: awaiting literature "
                                f"reference for {field}."),
        )
        plt.show()


def run_consistency_checks(checks, rel_tol=1e-4):
    """Store-vs-live consistency loop (pass/fail per identity).

    Each entry maps a label to ``(store_arr, recomputed_arr)``;
    the max relative error over finite pixels must beat ``rel_tol``
    (float32 store vs float64 live recompute -> expect ~1e-7).

    Generated by LH and Claude.

    Inputs: checks (dict[str, (np.ndarray, np.ndarray)]);
    rel_tol (float).  Outputs: prints per check; raises
    AssertionError on the first failure.
    """
    for name, (store_v, recomputed) in checks.items():
        m = np.isfinite(store_v) & np.isfinite(recomputed)
        scale = max(float(np.nanmax(np.abs(recomputed[m]))),
                    1e-300)
        rel = (float(np.nanmax(np.abs(store_v[m] - recomputed[m])))
               / scale)
        flag = "OK  " if rel < rel_tol else "FAIL"
        print(f"{flag} {name}  (max rel err {rel:.2e}, "
              f"n={m.sum()})")
        assert rel < rel_tol, name
    print("\nStore-vs-live consistency: all checks passed.")
