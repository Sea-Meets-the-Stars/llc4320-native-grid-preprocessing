"""
pdfs.py
-------
PDF (histogram) panels for the field-validation notebooks, following
the conventions confirmed in the plan (prompts/field_validation.md,
Clarification 8):

- y-axis is probability DENSITY (``density=True``);
- NaNs (land + gradient halo rim) are removed before binning;
- ∝-squared fields (gradb2, gradtheta2, ... — positive-definite with
  huge dynamic range) are binned in log10(x);
- bins are SHARED per field across all validation domains, so region
  rows are directly comparable (pipeline_pdf_grid computes them from
  the pooled values of all regions);
- the |lat|>2° equatorial filter for f-normalised fields is applied by
  the caller BEFORE values reach this module (and must be stated in
  the figure title).

Layout mirrors ``pipeline_grids``: rows = domains, columns =
dependency chain.
"""

import numpy as np
import matplotlib.pyplot as plt

from dbof.plotting import regions as regions_mod
from dbof.plotting.pipeline_grids import make_grid

# Default number of shared bins per field.
N_BINS = 120

# Percentile range used to clip pooled values when building shared bins
# (keeps single extreme outliers from flattening the histogram).
BIN_RANGE_PERCENTILES = (0.05, 99.95)


def _clean_values(arr, *, log10=False):
    """Flatten a field to finite (optionally log10) sample values.

    Generated by LH and Claude.

    Inputs
    ------
    arr : np.ndarray
        Field values (any shape); NaNs = land / halo rim.
    log10 : bool
        If True, keep strictly positive values and return log10(x)
        (the ∝-squared field convention).

    Outputs
    -------
    np.ndarray
        1D array of finite sample values (log10-transformed if asked).
    """
    v = np.asarray(arr).ravel()
    v = v[np.isfinite(v)]          # drop land + halo-rim NaNs
    if log10:
        v = v[v > 0]               # log needs strictly positive values
        v = np.log10(v)
    return v


def shared_bins(values_per_region, *, n_bins=N_BINS,
                percentiles=BIN_RANGE_PERCENTILES):
    """Build one bin set per field from pooled multi-region values.

    Generated by LH and Claude.

    Inputs
    ------
    values_per_region : list[np.ndarray]
        Cleaned 1D value arrays, one per region (same transform).
    n_bins : int
        Number of bins.
    percentiles : tuple[float, float]
        Pooled percentile range used as bin limits.

    Outputs
    -------
    np.ndarray
        Bin edges (length ``n_bins + 1``) shared by every region row.
    """
    pooled = np.concatenate([v for v in values_per_region if v.size])
    lo, hi = np.nanpercentile(pooled, percentiles)
    if lo == hi:                   # degenerate (constant field) guard
        lo, hi = lo - 0.5, hi + 0.5
    return np.linspace(lo, hi, n_bins + 1)


def pdf_panel(ax, values, bins, *, label=None, log_y=False):
    """Draw one probability-density histogram panel.

    Generated by LH and Claude.

    Inputs
    ------
    ax : matplotlib axis
        Target panel.
    values : np.ndarray
        Cleaned 1D sample values (see ``_clean_values``).
    bins : np.ndarray
        Shared bin edges for this field (see ``shared_bins``).
    label : str or None
        x-axis label (physical label from field_cmaps).
    log_y : bool
        Logarithmic density axis.

    Outputs
    -------
    None (draws on ``ax``).
    """
    if values.size:
        ax.hist(values, bins=bins, density=True, histtype="stepfilled",
                alpha=0.75, color="steelblue", edgecolor="none")
    else:
        ax.text(0.5, 0.5, "no data", ha="center", va="center",
                transform=ax.transAxes, fontsize=8)
    if log_y:
        ax.set_yscale("log")
    if label:
        ax.set_xlabel(label, fontsize=7)
    ax.tick_params(labelsize=7)


def pipeline_pdf_grid(chain, region_arrays, cmap_cfg, *,
                      log10_fields=frozenset(),
                      region_order=None,
                      n_bins=N_BINS,
                      log_y=False,
                      suptitle=None):
    """Figure 2 of a field's validation section: the PDF grid.

    Generated by LH and Claude.

    Inputs
    ------
    chain : list[str]
        Channel/intermediate names in dependency order (the columns).
    region_arrays : dict[str, dict[str, tuple]]
        ``region_arrays[field][region] = (x, y, arr)`` — the same
        structure consumed by ``pipeline_grids.pipeline_map_grid``.
    cmap_cfg : dict[str, tuple[str, str]]
        Registry from ``field_cmaps.load_field_cmaps()`` (labels only).
    log10_fields : set[str]
        Fields binned in log10(x) (the ∝-squared gradient fields).
    region_order : list[str] or None
        Row order; defaults to ``regions.REGION_ORDER``.
    n_bins : int
        Shared bin count per field.
    log_y : bool
        Logarithmic density axis on every panel.
    suptitle : str or None
        Overall figure title (state any physical filters here).

    Outputs
    -------
    (fig, axes) : the populated scaffold.
    """
    region_order = region_order or regions_mod.REGION_ORDER
    row_titles = [regions_mod.REGIONS[r]["short"] for r in region_order]

    fig, axes = make_grid(len(region_order), len(chain),
                          row_titles, list(chain))

    for j, field in enumerate(chain):
        log10 = field in log10_fields
        _, label = cmap_cfg.get(field, ("viridis", field))
        if log10:
            label = f"log₁₀[{label}]"

        # Clean once per region, then build ONE bin set per field.
        vals = [
            _clean_values(region_arrays[field][r][2], log10=log10)
            for r in region_order
        ]
        bins = shared_bins(vals, n_bins=n_bins)

        for i, v in enumerate(vals):
            pdf_panel(axes[i, j], v, bins,
                      label=label if i == len(region_order) - 1 else None,
                      log_y=log_y)
            if j == 0:
                axes[i, j].set_ylabel(row_titles[i], fontsize=9)

    fig.text(0.005, 0.5, "probability density", rotation=90,
             va="center", fontsize=9)
    if suptitle:
        fig.suptitle(suptitle, fontsize=12, y=1.005)
    fig.tight_layout()
    return fig, axes
