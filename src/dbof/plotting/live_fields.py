"""
live_fields.py
--------------
Shared stitch/slice plumbing for the field-validation notebooks
(prompts/field_validation.md) — extracted from the per-notebook
cells so the logic exists once.

Two entry points, both returning
``{field: {region: (x, y, arr)}}`` ready for the figure helpers in
:mod:`dbof.plotting.validation_figures`:

- :func:`stitch_and_slice` — batch-stitch LAZY live fields
  (face -> rect grid) and slice each to the validation regions
  immediately, so at most ``batch`` full-resolution arrays are in
  memory at once;
- :func:`slice_store` — slice STORE channels (already-stitched
  rect-grid snapshots from a reader) to the same regions.
"""

import numpy as np

from dbof.plotting import regions
from dbof.utils.faces_to_latlon import stitch_and_mask


def stitch_and_slice(live_map, ds_raw, ds_merge, lon, lat,
                     region_names, *, batch=4, verbose=True):
    """Batch-stitch lazy live fields and slice to the regions.

    Generated by LH and Claude.

    Inputs
    ------
    live_map : dict[str, xr.DataArray]
        Lazy native-grid fields keyed by name.
    ds_raw : xr.Dataset
        Raw snapshot dataset (template for ``assign``; same face
        layout as the fields).
    ds_merge : xr.Dataset
        Merged dataset providing ``hFacC`` for the land mask.
    lon, lat : np.ndarray
        2D rect-grid coordinates (XC, YC).
    region_names : list[str]
        Regions to slice to (keys into ``regions.REGIONS``).
    batch : int
        Fields stitched per pass — bounds peak memory.
    verbose : bool
        Print progress per batch.

    Outputs
    -------
    dict[str, dict[str, tuple]]
        field -> region -> (x, y, arr).
    """
    mask = {"_land_mask": (ds_merge.hFacC == 0)}
    names = list(live_map)
    out = {}
    for i0 in range(0, len(names), batch):
        grp = names[i0:i0 + batch]
        ds_conv = ds_raw.assign(
            {n: live_map[n] for n in grp})[grp]
        chw = stitch_and_mask(ds_conv, grp, mask)
        for k, n in enumerate(grp):
            out[n] = regions.select_all_regions(
                chw[k], lon, lat, names=region_names)
        del chw
        if verbose:
            print(f"stitched + sliced: {grp}")
    return out


def slice_store(reader, channels, lon, lat, region_names):
    """Slice store channels to the regions (one snapshot each).

    Full-resolution arrays are released immediately after slicing.

    Generated by LH and Claude.

    Inputs
    ------
    reader : GlobalZarrDatasetReader
        Store reader with ``get_channel_snapshot``.
    channels : list[str]
        Channel names to slice.
    lon, lat : np.ndarray
        2D rect-grid coordinates (XC, YC).
    region_names : list[str]
        Regions to slice to.

    Outputs
    -------
    dict[str, dict[str, tuple]]
        channel -> region -> (x, y, arr).
    """
    out = {}
    for ch in channels:
        arr = reader.get_channel_snapshot(ch)
        out[ch] = regions.select_all_regions(
            arr, lon, lat, names=region_names)
        del arr
    return out


def print_region_summary(region_arrays, region="gulf_stream"):
    """One-line shape/min/max summary per field for one region.

    Generated by LH and Claude.

    Inputs: region_arrays (dict from the functions above);
    region (str).  Outputs: prints only.
    """
    for ch in region_arrays:
        x, y, sub = region_arrays[ch][region]
        print(f"{ch:24s} {region} {sub.shape}  "
              f"min {np.nanmin(sub):.3g}  "
              f"max {np.nanmax(sub):.3g}")
