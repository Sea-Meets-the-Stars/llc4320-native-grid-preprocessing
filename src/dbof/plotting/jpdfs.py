"""
jpdfs.py
--------
Joint-PDF diagnostics in vorticity–strain space (Balwada et al. 2021
style), for the field-validation notebooks.

Two panel types:

- ``plot_jpdf_occurrence``: occurrence joint PDF of (ζ/f₀, σ/|f₀|)
  with log-spaced filled contours and the σ = |ζ| regime separatrices
  (AVD / SD / CVD annotation optional).
- ``plot_jpdf_conditional``: mean of a third field conditioned on the
  (ζ/f₀, σ/|f₀|) bin, on a symmetric-log colour scale (e.g. mean
  divergence Δ/|f₀| — Balwada et al. 2021 Fig. style).

NOTE: this is a fresh implementation written from the reference
figures; it is the PORT TARGET for
``fronts/properties/analysis/jpdf.py`` (Balwada et al. workflow) —
reconcile bin/normalisation conventions against that module when it
is available in this repo, then delete this note.
"""

import numpy as np
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors

# Default vorticity/strain axes (units of f0).
ZETA_RANGE = (-7.0, 7.0)
SIGMA_RANGE = (0.0, 7.0)
N_BINS = 175

# Log-spaced occurrence levels, as in Balwada et al. (2021).
OCC_LEVELS = 10.0 ** np.arange(-5, 2)


def _hist2d(zf, sf, *, weights=None, bins=N_BINS,
            zeta_range=ZETA_RANGE, sigma_range=SIGMA_RANGE):
    """2D histogram on the standard (ζ/f₀, σ/|f₀|) grid.

    Generated by LH and Claude.

    Inputs
    ------
    zf, sf : np.ndarray
        1D normalised vorticity / strain samples (finite).
    weights : np.ndarray or None
        Optional per-sample weights (for conditional means).
    bins, zeta_range, sigma_range :
        Binning of the (ζ/f₀, σ/|f₀|) plane.

    Outputs
    -------
    (H, xc, yc) : histogram (y rows, x cols) and bin centres.
    """
    H, xe, ye = np.histogram2d(
        zf, sf, bins=bins, range=[zeta_range, sigma_range],
        weights=weights,
    )
    xc = 0.5 * (xe[:-1] + xe[1:])
    yc = 0.5 * (ye[:-1] + ye[1:])
    return H.T, xc, yc


def _separatrices(ax, zeta_range=ZETA_RANGE):
    """Dashed σ = |ζ| regime lines.  Generated by LH and Claude."""
    x = np.linspace(zeta_range[0], zeta_range[1], 2)
    ax.plot(x, np.abs(x), "--", color="gray", linewidth=1)


def plot_jpdf_occurrence(ax, zf, sf, *, bins=N_BINS,
                         zeta_range=ZETA_RANGE,
                         sigma_range=SIGMA_RANGE,
                         levels=OCC_LEVELS,
                         annotate_regimes=True,
                         colorbar=True):
    """Occurrence joint PDF of normalised vorticity and strain.

    Generated by LH and Claude.

    Inputs
    ------
    ax : matplotlib axis
        Target panel.
    zf, sf : np.ndarray
        1D samples of ζ/f₀ and σ/|f₀| (NaNs allowed; removed).
    bins, zeta_range, sigma_range :
        Binning of the plane.
    levels : array
        Log-spaced filled-contour levels (probability density).
    annotate_regimes : bool
        Write AVD / SD / CVD labels (anticyclonic-vorticity-,
        strain-, cyclonic-vorticity-dominated).
    colorbar : bool
        Attach a colorbar to ``ax``.

    Outputs
    -------
    matplotlib.contour.QuadContourSet (the mappable).
    """
    m = np.isfinite(zf) & np.isfinite(sf)
    H, xc, yc = _hist2d(zf[m], sf[m], bins=bins,
                        zeta_range=zeta_range, sigma_range=sigma_range)
    # Probability density: normalise by N and bin area.
    area = ((zeta_range[1] - zeta_range[0]) / bins
            * (sigma_range[1] - sigma_range[0]) / bins)
    P = H / max(m.sum(), 1) / area

    cf = ax.contourf(xc, yc, np.where(P > 0, P, np.nan),
                     levels=levels,
                     norm=mcolors.LogNorm(vmin=levels[0],
                                          vmax=levels[-1]),
                     cmap="Oranges", extend="both")
    _separatrices(ax, zeta_range)
    if annotate_regimes:
        ax.text(0.15, 0.75, "SD", transform=ax.transAxes, fontsize=11)
        ax.text(0.06, 0.15, "AVD", transform=ax.transAxes, fontsize=11)
        ax.text(0.88, 0.15, "CVD", transform=ax.transAxes, fontsize=11)
    ax.set_xlabel(r"$\zeta/f_0$")
    ax.set_ylabel(r"$\sigma/|f_0|$")
    ax.grid(alpha=0.4, linewidth=0.5)
    if colorbar:
        ax.figure.colorbar(cf, ax=ax)
    return cf


def plot_jpdf_conditional(ax, zf, sf, c, *, bins=N_BINS,
                          zeta_range=ZETA_RANGE,
                          sigma_range=SIGMA_RANGE,
                          min_count=10,
                          linthresh=1e-2,
                          vlim=3.0,
                          clabel=None,
                          cmap="RdBu_r",
                          colorbar=True):
    """Conditional mean of a third field in (ζ/f₀, σ/|f₀|) bins.

    Generated by LH and Claude.

    Inputs
    ------
    ax : matplotlib axis
        Target panel.
    zf, sf : np.ndarray
        1D samples of ζ/f₀ and σ/|f₀|.
    c : np.ndarray
        1D samples of the conditioned field (e.g. Δ/|f₀|).
    bins, zeta_range, sigma_range :
        Binning of the plane.
    min_count : int
        Bins with fewer samples are masked (unstable means).
    linthresh, vlim : float
        Symmetric-log colour scale parameters.
    clabel : str or None
        Colorbar label.
    cmap : str
        Diverging colormap.
    colorbar : bool
        Attach a colorbar to ``ax``.

    Outputs
    -------
    matplotlib.collections.QuadMesh (the mappable).
    """
    m = np.isfinite(zf) & np.isfinite(sf) & np.isfinite(c)
    sums, xc, yc = _hist2d(zf[m], sf[m], weights=c[m], bins=bins,
                           zeta_range=zeta_range,
                           sigma_range=sigma_range)
    counts, _, _ = _hist2d(zf[m], sf[m], bins=bins,
                           zeta_range=zeta_range,
                           sigma_range=sigma_range)
    with np.errstate(invalid="ignore", divide="ignore"):
        mean = np.where(counts >= min_count, sums / counts, np.nan)

    pm = ax.pcolormesh(
        xc, yc, mean,
        norm=mcolors.SymLogNorm(linthresh=linthresh,
                                vmin=-vlim, vmax=vlim),
        cmap=cmap, shading="nearest",
    )
    _separatrices(ax, zeta_range)
    ax.set_xlabel(r"$\zeta/f_0$")
    ax.set_ylabel(r"$\sigma/|f_0|$")
    ax.grid(alpha=0.4, linewidth=0.5)
    if colorbar:
        ax.figure.colorbar(pm, ax=ax, label=clabel)
    return pm
