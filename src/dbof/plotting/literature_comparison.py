"""
literature_comparison.py
------------------------
Figure 3 of every field-validation section: a standard side-by-side
layout comparing (a) our generated diagnostic with (b) a figure from
the literature supplied as a .png (plan: prompts/field_validation.md,
§5 and §7).

The diagnostic panel type is deliberately unspecified: it is rendered
by a caller-supplied callback (any axes-rendering function — map, PDF,
scatter, ...), because the figure type is specified explicitly per
variable when the literature reference is chosen.
"""

from pathlib import Path

import matplotlib.pyplot as plt
import matplotlib.image as mpimg


def side_by_side(render_fn, png_path, *,
                 our_title="(a) This work",
                 lit_title="(b) Literature",
                 caption=None,
                 figsize=(13, 5),
                 projection=None):
    """Render the standard our-data vs literature comparison figure.

    Generated by LH and Claude.

    Inputs
    ------
    render_fn : callable
        ``render_fn(ax)`` draws our diagnostic on the left axis.  Any
        figure type is allowed — the callback decides.
    png_path : str or Path or None
        Path to the literature .png.  If None or missing, the right
        panel shows an 'awaiting literature reference' placeholder so
        notebooks stay runnable before references are supplied.
    our_title, lit_title : str
        Panel titles.
    caption : str or None
        Short discussion (similarities / differences / physical
        plausibility) rendered below the panels.
    figsize : tuple[float, float]
        Figure size in inches.
    projection : cartopy CRS or None
        Projection for OUR (left) axis — e.g. ``ccrs.Robinson()`` when
        the literature figure is a global map.  None = plain axis.

    Outputs
    -------
    (fig, (ax_ours, ax_lit)) : the populated figure and its two axes.
    """
    fig = plt.figure(figsize=figsize)
    if projection is not None:
        ax_ours = fig.add_subplot(1, 2, 1, projection=projection)
    else:
        ax_ours = fig.add_subplot(1, 2, 1)
    ax_lit = fig.add_subplot(1, 2, 2)

    # Left: our diagnostic, rendered by the caller.
    render_fn(ax_ours)
    ax_ours.set_title(our_title, fontsize=11)

    # Right: literature image, or a placeholder when not yet supplied.
    if png_path is not None and Path(png_path).exists():
        ax_lit.imshow(mpimg.imread(str(png_path)))
        ax_lit.set_axis_off()
    else:
        ax_lit.text(0.5, 0.5, "awaiting literature reference (.png)",
                    ha="center", va="center", fontsize=11, style="italic",
                    transform=ax_lit.transAxes)
        ax_lit.set_xticks([])
        ax_lit.set_yticks([])
    ax_lit.set_title(lit_title, fontsize=11)

    # Discussion slot below the panels.
    if caption:
        fig.text(0.02, -0.02, caption, ha="left", va="top",
                 fontsize=9, wrap=True)
    fig.tight_layout()
    return fig, (ax_ours, ax_lit)
