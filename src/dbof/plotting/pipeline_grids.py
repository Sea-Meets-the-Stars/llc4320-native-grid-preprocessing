"""
pipeline_grids.py
-----------------
Shared rows × columns figure scaffold for the field-validation
notebooks (plan: prompts/field_validation.md, §5 and §7).

Layout convention (both Figure 1 / maps and Figure 2 / PDFs):

- columns = a field's dependency chain, in raw → intermediate → final
  order (option (a): each field repeats its full chain);
- rows    = validation domains (``dbof.plotting.regions.REGION_ORDER``:
  global, Gulf Stream, SO Atlantic sector, eastern tropical Pacific).

Colormaps / labels / units resolve through ``field_cmaps.yaml`` and
norms through ``global_maps.make_field_norm`` — nothing here hard-codes
colors or labels.  The panel renderer is a callback so the same
scaffold serves maps (``map_panel``) and PDFs (``dbof.plotting.pdfs``).
"""

import numpy as np
import matplotlib.pyplot as plt

from dbof.plotting.global_maps import make_field_norm, plot_global_field
from dbof.plotting import regions as regions_mod

# Default panel size (inches); rows scale with region aspect.
PANEL_W = 3.4
PANEL_H = 2.2


def make_grid(n_rows, n_cols, row_titles, col_titles, *,
              panel_w=PANEL_W, panel_h=PANEL_H):
    """Create the shared rows × columns scaffold with titled margins.

    Generated by LH and Claude.

    Inputs
    ------
    n_rows, n_cols : int
        Grid dimensions (rows = domains, cols = dependency chain).
    row_titles, col_titles : list[str]
        Labels written on the left margin / top row of the grid.
    panel_w, panel_h : float
        Per-panel size in inches.

    Outputs
    -------
    (fig, axes) : (matplotlib.figure.Figure, np.ndarray)
        ``axes`` always has shape (n_rows, n_cols).
    """
    fig, axes = plt.subplots(
        n_rows, n_cols,
        figsize=(n_cols * panel_w, n_rows * panel_h),
        squeeze=False,
    )
    for j, title in enumerate(col_titles):
        axes[0, j].set_title(title, fontsize=9)
    for i, title in enumerate(row_titles):
        axes[i, 0].set_ylabel(title, fontsize=9)
    return fig, axes


def pipeline_map_grid(chain, region_arrays, cmap_cfg, *,
                      diverging_cmaps=frozenset(),
                      log_scale_channels=frozenset(),
                      region_order=None,
                      percentiles=(1, 99),
                      suptitle=None):
    """Figure 1 of a field's validation section: the map grid.

    Generated by LH and Claude.

    Inputs
    ------
    chain : list[str]
        Channel/intermediate names in dependency order (the columns).
    region_arrays : dict[str, dict[str, tuple]]
        ``region_arrays[field][region] = (x, y, arr)`` as produced by
        ``regions.select_all_regions`` — every field in ``chain`` must
        have every region in ``region_order``.
    cmap_cfg : dict[str, tuple[str, str]]
        Registry from ``field_cmaps.load_field_cmaps()``.
    diverging_cmaps : set[str]
        Colormap names centred at zero (from the same registry).
    log_scale_channels : set[str]
        Channels drawn with a logarithmic colour scale.
    region_order : list[str] or None
        Row order; defaults to ``regions.REGION_ORDER``.
    percentiles : tuple[float, float]
        Colour-limit percentiles per panel.
    suptitle : str or None
        Overall figure title.

    Outputs
    -------
    (fig, axes) : the populated scaffold; ONE norm and one horizontal
        colorbar per column, shared across all rows (regions are
        directly comparable within a column), labelled with the field's
        physical label from the registry.
    """
    region_order = region_order or regions_mod.REGION_ORDER
    row_titles = [regions_mod.REGIONS[r]["short"] for r in region_order]

    fig, axes = make_grid(len(region_order), len(chain),
                          row_titles, list(chain))

    for j, field in enumerate(chain):
        cmap_name, label = cmap_cfg.get(field, ("viridis", field))

        # One norm per column: percentile limits over the pooled finite
        # values of ALL regions, so rows share a colour scale.
        pooled = np.concatenate([
            region_arrays[field][r][2].ravel() for r in region_order
        ])
        norm = make_field_norm(pooled, cmap_name,
                               log=field in log_scale_channels,
                               diverging_cmaps=diverging_cmaps,
                               percentiles=percentiles)

        im_last = None
        for i, region in enumerate(region_order):
            x, y, arr = region_arrays[field][region]
            im, label = plot_global_field(
                axes[i, j], x, y, arr, field, cmap_cfg,
                diverging_cmaps=diverging_cmaps,
                add_coastline=False,   # plain axes; land is NaN-masked
                norm=norm,
            )
            axes[i, j].set_xticks([])
            axes[i, j].set_yticks([])
            # Keep the row title set by make_grid on the first column.
            if j == 0:
                axes[i, j].set_ylabel(row_titles[i], fontsize=9)
            if im is not None:
                im_last = im
        if im_last is not None:
            # One shared colorbar per column, labelled with units.
            fig.colorbar(im_last, ax=axes[:, j].tolist(),
                         orientation="horizontal", fraction=0.03,
                         pad=0.02, label=label)
    if suptitle:
        fig.suptitle(suptitle, fontsize=12, y=1.005)
    return fig, axes
