def draw_vertical_schematic(axes=None, interfaces=(0.0, 50.0, 120.0)):
    """Draw an annotated MITgcm vertical-grid schematic.

    Names every coordinate and spacing variable at the depth it belongs
    to.  Drawn in **dbof's positive-downward depth** (0 at the surface,
    increasing downward), matching everything downstream of
    ``vertical_helpers._get_depth_coord``.  MITgcm/ECCO themselves use
    a **positive-upward** ``Z``, so their values are negative below the
    surface; each label carries that native value in parentheses.

    On the ``Zl`` / ``Zu`` naming: the ``l`` and ``u`` refer to the
    *index* position, not to depth.  ``Zl[k]`` is the interface on the
    low-index (SHALLOWER) side of cell ``k``; ``Zu[k]`` is the one on
    the high-index (DEEPER) side.  Flipping the sign convention does
    not change that -- it is a statement about array indexing, not
    about geometry, and it is the most common source of off-by-one
    errors when reading MITgcm vertical output.

    Parameters
    ----------
    axes : pair of matplotlib Axes, or None
        ``(column axes, naming-table axes)``.  None creates a figure.
    interfaces : sequence of float
        Interface depths in metres, **positive downward**, shallowest
        first.  The default is two illustrative cells with round
        numbers -- the point of the figure is the topology, not the
        real LLC4320 levels (for those see the depth table in
        ``notebooks/notebooks_field_validation/Grid.ipynb``).

    Returns
    -------
    (ax_col, ax_key) : the two axes drawn into.

    Generated by JXP, LH and Claude
    """
    if axes is None:
        _, axes = plt.subplots(
            1, 2, figsize=(16.5, 7.4),
            gridspec_kw={"width_ratios": [2.15, 1.0]})
    ax, ax_key = axes

    ifc = list(interfaces)
    nk = len(ifc) - 1
    ctr = [0.5 * (ifc[k] + ifc[k + 1]) for k in range(nk)]

    x0, x1 = 0.0, 1.0          # horizontal extent of interface lines
    xcol = 0.12                # the column itself

    # ---- interfaces --------------------------------------------------
    for kp1, z in enumerate(ifc):
        ax.plot([x0, x1], [z, z], ls="--", color=C_UPOINT, lw=1.2,
                zorder=1)
        ax.plot(xcol, z, "o", color=C_UPOINT, ms=11, zorder=3)

        names = [f"Zp1[k_p1={kp1}]"]
        if kp1 < nk:
            names.append(f"Zl[k_l={kp1}]")
        if kp1 > 0:
            names.append(f"Zu[k_u={kp1 - 1}]")
        ax.text(x1 + 0.04, z,
                f"depth {z:g} m  =  " + " = ".join(names) +
                f"      (native Z = {-z if z else 0:g})",
                va="center", fontsize=9.5, color=C_UPOINT)

    # ---- cell centres ------------------------------------------------
    for k, z in enumerate(ctr):
        ax.plot([x0, x1], [z, z], ls=":", color=C_TRACER, lw=1.0,
                zorder=1)
        ax.plot(xcol, z, "X", color=C_TRACER, ms=13, zorder=3)
        ax.text(x1 + 0.04, z,
                f"depth {z:g} m  =  Z[k={k}]   "
                f"(Theta, Salt, U, V)",
                va="center", fontsize=9.5, color=C_TRACER)

    # ---- W lives on the interfaces -----------------------------------
    for z in ifc[:-1]:
        ax.plot(xcol + 0.30, z, "v", color=C_UPOINT, ms=9, zorder=3,
                mfc="none")
    span = ifc[-1] - ifc[0]
    ax.annotate("W  (k_l, j, i)", xy=(xcol + 0.30, ifc[0]),
                xytext=(xcol + 0.40, ifc[0] + 0.10 * span),
                fontsize=9.5, color=C_UPOINT,
                arrowprops=dict(arrowstyle="->", color=C_UPOINT,
                                lw=1.0))

    # ---- drF: thickness of cell 0 (interface to interface) -----------
    xd = xcol - 0.075
    ax.annotate("", xy=(xd, ifc[1]), xytext=(xd, ifc[0]),
                arrowprops=dict(arrowstyle="<->", color=C_SPACE,
                                lw=1.8))
    ax.text(xd - 0.03, 0.5 * (ifc[0] + ifc[1]), "drF[k=0]",
            rotation=90, va="center", ha="right", fontsize=10,
            color=C_SPACE)

    # ---- drC: centre-to-centre spacing -------------------------------
    if nk >= 2:
        xc = xcol + 0.16
        ax.annotate("", xy=(xc, ctr[1]), xytext=(xc, ctr[0]),
                    arrowprops=dict(arrowstyle="<->", color=C_SPACE,
                                    lw=1.8))
        ax.text(xc + 0.03, 0.5 * (ctr[0] + ctr[1]),
                "drC\n(centre to centre)",
                va="center", ha="left", fontsize=10, color=C_SPACE)

    pad = 0.06 * span
    ax.set_ylim(ifc[0] - pad, ifc[-1] + pad)
    ax.invert_yaxis()                      # depth increases downward
    ax.set_xlim(-0.16, 2.35)
    ax.set_xticks([])
    ax.set_ylabel("depth (m, POSITIVE downward)  --  dbof convention")
    ax.set_title("LLC4320 vertical grid", fontsize=11)
    ax.spines[["top", "right", "bottom"]].set_visible(False)

    # ---- naming key --------------------------------------------------
    ax_key.axis("off")
    ax_key.set_title("What each name means", fontsize=11, loc="left")
    rows = [
        ("Z, k", C_TRACER,
         "tracer-cell CENTRE depth. Theta and Salt live\n"
         "here, and so does every dbof depth reduction."),
        ("Zl, k_l", C_UPOINT,
         "interface on the LOW-INDEX side of cell k --\n"
         "i.e. the SHALLOWER one. W lives here."),
        ("Zu, k_u", C_UPOINT,
         "interface on the HIGH-INDEX side of cell k --\n"
         "i.e. the DEEPER one."),
        ("Zp1, k_p1", C_UPOINT,
         "all nk+1 interfaces in one array\n"
         "(Zl and Zu are overlapping subsets of it)."),
        ("drF", C_SPACE,
         "THICKNESS of cell k = |Zu[k] - Zl[k]|.\n"
         "The weight in thickness-weighted vertical means."),
        ("drC", C_SPACE,
         "distance between adjacent cell CENTRES.\n"
         "Used for k_l-level spacing, not for drF weights."),
    ]
    y = 0.985
    for name, colour, desc in rows:
        ax_key.text(0.0, y, name, fontsize=11, fontweight="bold",
                    color=colour, va="top")
        ax_key.text(0.30, y, desc, fontsize=9.5, va="top",
                    color="0.15")
        y -= 0.125

    ax_key.text(0.0, y + 0.02,
                "l and u refer to INDEX POSITION, not depth.\n"
                "Zl is the shallower interface; Zu is the deeper "
                "one --\nthis is true in either sign convention.",
                fontsize=9.5, va="top", color=C_UPOINT, style="italic")
    ax_key.text(0.0, y - 0.10,
                "3D at cell centres (k):  Theta, Salt   |   3D on the "
                "C-grid\nfaces at the same k:  U, V   |   3D on "
                "interfaces (k_l):  W\n2D surface fields:  Eta, "
                "oceQnet, oceTAUX, oceTAUY",
                fontsize=9, va="top", color="0.15")
    ax_key.text(0.0, y - 0.20,
                "SIGN CONVENTION: drawn as dbof depth, axis POSITIVE "
                "DOWNWARD,\nso values are positive below the surface. "
                "MITgcm/ECCO use a\nPOSITIVE-UPWARD Z, so their values "
                "are NEGATIVE below the\nsurface (given in parentheses "
                "on the left); depth = -Z.\n\n"
                "MITgcm vertical grid documentation:\n"
                + MITGCM_VERT_DOC,
                fontsize=8, va="top", color="0.15",
                bbox=dict(boxstyle="round,pad=0.5", fc="#fff3cd",
                          ec="#c9a227"))
    return ax, ax_key


# ---------------------------------------------------------------------
# The sparkle artifact, in 1-D arithmetic
# ---------------------------------------------------------------------

def draw_sparkle_schematic(fig=None, s=(10.0, 12.0, 10.0), dx=1.0):
    """Draw the 1-D arithmetic that produces the 'sparkle' artifact.

    Walks a grid-scale extremum through both recipes, in the X
    direction only (Y is identical and adds nothing):

    * **interp-then-square** (the legacy ECCO recipe): difference onto
      the U faces, average the two SIGNED differences back to the
      centre -- they are equal and opposite, so they cancel -- then
      square.  The centred ``|grad|^2`` collapses to ~0 at a point
      where the one-sided gradients are large: an isolated white pixel
      on a log-scaled map.
    * **square-then-interp** (production,
      ``native_gradient.calculate_grad_squared_tracer``): square each
      difference ON its own face, then average the non-negative
      squares.  A mean of non-negative numbers cannot cancel.

    The default ``s`` is a symmetric one-cell spike, which makes the
    cancellation exact.  Real fields are never exactly symmetric, so
    the true artifact is a near-cancellation -- orders of magnitude
    below the neighbouring values rather than identically zero, which
    is why it shows up as WHITE rather than as a hole.

    Parameters
    ----------
    fig : matplotlib.figure.Figure or None
        Figure to draw into.  None (default) creates one.
    s : sequence of float
        Three tracer values at cell centres ``i-1, i, i+1``.  The
        middle one should be a local extremum for the point to land.
    dx : float
        Cell spacing ``dxC`` in metres (kept at 1 so the arithmetic on
        the figure stays readable).

    Returns
    -------
    matplotlib.figure.Figure
        The figure containing the schematic.

    Generated by LH and Claude
    """
    if fig is None:
        fig = plt.figure(figsize=(11.5, 8.2))
    gs = fig.add_gridspec(3, 3, height_ratios=[1.05, 1.0, 1.0],
                          hspace=0.62, wspace=0.30)

    s = np.asarray(s, dtype=float)
    xc = np.array([-1.0, 0.0, 1.0])        # tracer centres
    xf = np.array([-0.5, 0.5])             # U faces between them
    d = np.diff(s) / dx                    # differences ON the faces
    ecco_centre = float(np.mean(d))        # 2-point mean, then...
    ecco_final = ecco_centre ** 2          # ...square
    sqf_final = float(np.mean(d ** 2))     # square, then 2-point mean

    def _stage(ax, x, vals, colour, marker, title, fmt="{:.3g}"):
        ax.axhline(0.0, color="0.85", lw=1.0, zorder=0)
        cont = ax.stem(x, vals, linefmt="-", markerfmt=marker,
                       basefmt=" ")
        cont.stemlines.set_color(colour)
        cont.markerline.set_color(colour)
        cont.markerline.set_markersize(11)
        for xi, vi in zip(x, vals):
            ax.annotate(fmt.format(vi), (xi, vi),
                        textcoords="offset points",
                        xytext=(0, 9 if vi >= 0 else -16),
                        ha="center", fontsize=10, color=colour,
                        fontweight="bold")
        ax.set_title(title, fontsize=10)
        ax.set_xlim(-1.45, 1.45)
        ax.set_xticks(list(xc))
        ax.set_xticklabels(["i-1", "i", "i+1"], fontsize=9)
        ax.tick_params(labelsize=8)
        ax.spines[["top", "right"]].set_visible(False)
        pad = 0.35 * (max(abs(np.max(vals)), abs(np.min(vals))) or 1.0)
        ax.set_ylim(min(0.0, np.min(vals)) - pad,
                    max(0.0, np.max(vals)) + pad)

    # ---- row 0: the field and the two face differences ---------------
    ax0 = fig.add_subplot(gs[0, :])
    ax0.plot(xc, s, "-", color="0.75", lw=1.2, zorder=1)
    ax0.plot(xc, s, "o", color=C_TRACER, ms=13, zorder=3)
    for xi, vi in zip(xc, s):
        ax0.annotate(f"{vi:g}", (xi, vi), textcoords="offset points",
                     xytext=(0, 12), ha="center", fontsize=11,
                     color=C_TRACER, fontweight="bold")
    for xi, di in zip(xf, d):
        ax0.plot(xi, np.interp(xi, xc, s), ">", color=C_UPOINT, ms=13,
                 zorder=3)
        ax0.annotate(f"diff / dxC = {di:+g}", (xi, np.interp(xi, xc, s)),
                     textcoords="offset points", xytext=(0, -26),
                     ha="center", fontsize=10, color=C_UPOINT)
    ax0.set_xlim(-1.45, 1.45)
    rng = float(np.max(s) - np.min(s)) or 1.0
    ax0.set_ylim(np.min(s) - 0.9 * rng - 0.5, np.max(s) + 0.9 * rng)
    ax0.set_xticks(list(xc))
    ax0.set_xticklabels(["i-1", "i", "i+1"], fontsize=9)
    ax0.set_yticks([])
    ax0.spines[["top", "right", "left"]].set_visible(False)
    ax0.set_title("A grid-scale extremum at i: the two flanking "
                  "differences are EQUAL AND OPPOSITE", fontsize=11)
    ax0.legend(handles=[
        plt.Line2D([], [], marker="o", ls="", color=C_TRACER, ms=10,
                   label="tracer centre (i) -- Theta, Salt, ..."),
        plt.Line2D([], [], marker=">", ls="", color=C_UPOINT, ms=10,
                   label="U face (i_g) -- where grid.diff lands"),
    ], loc="lower center", ncol=2, fontsize=9, framealpha=0.95)

    # ---- row 1: interp-then-square (the artifact) --------------------
    _stage(fig.add_subplot(gs[1, 0]), xf, d, C_UPOINT, ">",
           "1. grid.diff(s, 'X') / dxC\n(signed, on the faces)")
    ax = fig.add_subplot(gs[1, 1])
    _stage(ax, [0.0], [ecco_centre], C_TRACER, "o",
           "2. grid.interp to the centre\n"
           f"({d[0]:+g} {d[1]:+g}) / 2  ->  CANCELS")
    ax.set_ylim(min(d) * 1.2, max(d) * 1.2)
    _stage(fig.add_subplot(gs[1, 2]), [0.0], [ecco_final], C_TRACER,
           "o", "3. square it\n-> the sparkle pixel")

    # ---- row 2: square-then-interp (production) ----------------------
    _stage(fig.add_subplot(gs[2, 0]), xf, d, C_UPOINT, ">",
           "1. grid.diff(s, 'X') / dxC\n(the same differences)")
    _stage(fig.add_subplot(gs[2, 1]), xf, d ** 2, C_UPOINT, ">",
           "2. square ON the faces\n(both non-negative)")
    _stage(fig.add_subplot(gs[2, 2]), [0.0], [sqf_final], C_TRACER,
           "o", "3. grid.interp to the centre\n"
                "-> a mean of non-negatives")

    # ---- row labels and the verdict ----------------------------------
    fig.text(0.008, 0.435, "LEGACY ECCO RECIPE\ninterp -> square",
             rotation=90, va="center", ha="center", fontsize=10,
             fontweight="bold", color=C_UPOINT)
    fig.text(0.008, 0.145, "PRODUCTION\nsquare -> interp",
             rotation=90, va="center", ha="center", fontsize=10,
             fontweight="bold", color=C_VPOINT)
    fig.text(0.5, 0.005,
             f"Same field, same differences, same point: "
             f"|grad s|^2 = {ecco_final:.3g} one way and "
             f"{sqf_final:.3g} the other.\n"
             "The 2-point mean has a null space at the grid scale; "
             "squaring first removes it, because a mean of "
             "non-negative numbers cannot cancel.",
             ha="center", va="bottom", fontsize=10,
             bbox=dict(boxstyle="round,pad=0.5", fc="#fff3cd",
                       ec="#c9a227"))
    fig.suptitle("Why 'sparkle' happens: the order of squaring and "
                 "interpolating", fontsize=13, y=0.985)
    fig.subplots_adjust(left=0.045, right=0.985, top=0.895,
                        bottom=0.135)
    return fig


