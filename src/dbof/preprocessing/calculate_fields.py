def wind_stress_curl(ds_merge, grid):
    """Lazy wind stress curl.

    Moved from ``calculate_fields_at_depth`` during the field migration —
    inherently 2D inputs, dimension-agnostic code.

    Parameters
    ----------
    ds_merge : xarray.Dataset
        Dataset containing ``oceTAUX`` and ``oceTAUY`` on staggered
        velocity points, plus grid metrics.
    grid : xgcm.Grid
        Grid object used for differencing and interpolation.

    Returns
    -------
    xarray.DataArray
        2D wind stress curl dtauy/dx - dtaux/dy [N m-3] on tracer points.
    """
    taux = ds_merge.oceTAUX
    tauy = ds_merge.oceTAUY
    _, dtaux_dphi, dtauy_dlambda, _ = ng.calculate_jacobian(
        taux, tauy, ds_merge, grid)
    curl_tau = dtauy_dlambda - dtaux_dphi
    return curl_tau


def ekman_pumping(ds_merge, grid, rho0=RHO0_REFERENCE):
    """Lazy Ekman pumping w_E = curl(tau) / (rho0 f).

    Moved from ``calculate_fields_at_depth`` during the field migration.

    Parameters
    ----------
    ds_merge : xarray.Dataset
        Dataset containing ``oceTAUX``, ``oceTAUY``, grid metrics, and
        latitude coordinate ``YC``.
    grid : xgcm.Grid
        Grid object used for differencing and interpolation.
    rho0 : float, optional
        Reference density [kg m-3] (default ``RHO0_REFERENCE``).

    Returns
    -------
    xarray.DataArray
        2D Ekman pumping velocity w_E [m s-1] on tracer points; NaN at
        the equator where f = 0.
    """
    curl_tau = wind_stress_curl(ds_merge, grid)
    f = coriolis_parameter(ds_merge, grid)
    w_e = xr.where(np.abs(f) > 0, curl_tau / (rho0 * f), np.nan)
    return w_e


def ekman_transport(ds_merge, grid, rho0=RHO0_REFERENCE):
    """Lazy Ekman transport (u_E, v_E) — depth-integrated tau / (rho0 f).

    Moved from ``calculate_fields_at_depth`` during the field migration;
    now uses the single public :func:`geographic_wind_stress` (the private
    ``_wind_stress_geographic`` duplicate was deleted).
    https://sam.ucsd.edu/ltalley/sio210/dynamics_ekman/index.html

    Parameters
    ----------
    ds_merge : xarray.Dataset
        Dataset containing ``oceTAUX``, ``oceTAUY``, rotation coefficients
        ``CS``/``SN``, and latitude coordinate ``YC``.
    grid : xgcm.Grid
        Grid object used for interpolation to tracer points.
    rho0 : float, optional
        Reference density [kg m-3] (default ``RHO0_REFERENCE``).

    Returns
    -------
    dict
        ``{"u_ekman": zonal transport, "v_ekman": meridional transport}``
        [m2 s-1] on tracer points.
    """
    f = coriolis_parameter(ds_merge, grid)
    denom = rho0 * f
    safe_denom = xr.where(np.abs(f) > 0, denom, np.nan)
    tau_east, tau_north = geographic_wind_stress(ds_merge, grid)
    return {"u_ekman": tau_north / safe_denom,
            "v_ekman": -tau_east / safe_denom}


