def modified_okubo_weiss(ds_merge, grid, *, jacobian=None,
                         okubo_weiss=None, q_squared=None):
    """Lazy modified Okubo-Weiss parameter W* (Bachman 2021).

    Like the classical Okubo-Weiss parameter, W* compares strain and
    vorticity, but it is additionally sensitive to the vertical shear
    encoded in the quasigeostrophic Q vector:

        W* = 4 sgn(l2) sqrt(l1^2 + l2^2)
        l2 = W / 4,     W = sn^2 + ss^2 - zeta^2   (Okubo-Weiss)
        l1 = l2/2 + sqrt(l2^2 + |Q|^2 / f^2) / 2

    with the QG Q vector (Hoskins, Draghici & Davies 1978)

        Q1 = -(du/dx db/dx + dv/dx db/dy)
        Q2 = -(du/dy db/dx + dv/dy db/dy),   |Q|^2 = Q1^2 + Q2^2.

    Moved (suffix-free) from ``calculate_fields_at_depth`` during the
    field migration: horizontal math only, so dimension-agnostic.  The
    buoyancy gradient now comes from the single
    :func:`compute_buoyancy_gradients` (the private phys-gradient helper
    was deleted — with one project-wide buoyancy definition the two
    routes are identical).

    Parameters
    ----------
    ds_merge : xarray.Dataset
        Dataset containing ``Theta``, ``Salt``, ``U``, ``V``, latitude
        ``YC``, grid metrics, and rotation coefficients ``CS``/``SN``.
    grid : xgcm.Grid
        Grid object used for differencing and interpolation.
    jacobian : VelocityJacobian, optional
        Pre-computed velocity Jacobian.  If ``None`` (and needed),
        computed internally.
    okubo_weiss : xarray.DataArray, optional
        Pre-computed classical Okubo-Weiss parameter W [s-2].  If
        ``None``, computed via :func:`okubo_weiss_parameter`.
    q_squared : xarray.DataArray, optional
        Pre-computed |Q|^2 [s-6].  If ``None``, computed from the
        Jacobian and the buoyancy gradients.

    Returns
    -------
    xarray.DataArray
        Modified Okubo-Weiss parameter W* [s-2] on tracer points, with
        ``name="Wstar"``; NaN at the equator where f -> 0.  Its sign
        follows the classical Okubo-Weiss parameter (positive =>
        strain-dominated).

    Generated by LH and Claude
    """
    # Classical Okubo-Weiss W (reuse caller's if given).
    if okubo_weiss is None:
        okubo_weiss = okubo_weiss_parameter(ds_merge, grid)
    # Smaller eigenvalue l2 = W / 4.
    l2 = okubo_weiss / 4.0

    # QG Q-vector magnitude squared |Q|^2 (reuse caller's if supplied).
    if q_squared is None:
        if jacobian is None:
            jacobian = compute_velocity_jacobian(ds_merge, grid)
        bg = compute_buoyancy_gradients(ds_merge, grid)
        q1 = -(jacobian.du_dx * bg.zonal + jacobian.dv_dx * bg.merid)
        q2 = -(jacobian.du_dy * bg.zonal + jacobian.dv_dy * bg.merid)
        q_squared = q1**2 + q2**2

    # f^2 normalises |Q|^2; mask the equator (f -> 0) where it diverges.
    f = coriolis_parameter(ds_merge, grid)
    f2 = xr.where(np.abs(f) > 0, f**2, np.nan)

    # Larger eigenvalue l1, then W* = 4 sgn(l2) sqrt(l1^2 + l2^2).
    l1 = 0.5 * l2 + 0.5 * np.sqrt(l2**2 + q_squared / f2)
    wstar = 4.0 * np.sign(l2) * np.sqrt(l1**2 + l2**2)
    wstar.name = "Wstar"
    wstar.attrs["long_name"] = "Modified Okubo-Weiss parameter (W*)"
    wstar.attrs["units"] = "s^-2"
    return wstar
