# Density and buoyancy (lazy, dimension-agnostic)
# ---------------------------------------------------------------------------

def potential_density(ds_merge):
    """Surface-referenced potential density via JMD95 at p = 0 (lazy).

    JMD95 computes in-situ density rho(S, Theta, p); evaluating it at
    p = 0 with (surface-referenced) potential temperature is the standard
    potential-density construction (TEOS-10, CSIRO seawater ``pden``).
    The result equals in-situ density AT the surface only; below the
    surface it is the potential density rho_theta (sigma_theta + 1000).

    Dimension-agnostic: works on 2D (face, j, i) or 3D (k, face, j, i)
    inputs.  Chunk-alignment of Theta/Salt is the caller's responsibility
    (the DEPTH pipeline rechunks once at its entry point).

    Parameters
    ----------
    ds_merge : xarray.Dataset
        Dataset containing 'Theta' (potential temperature, deg C) and
        'Salt' (salinity, PSU).

    Returns
    -------
    xarray.DataArray
        Potential density [kg m^-3] on tracer points, dask-backed.

    Generated by LH and Claude
    """
    import dbof.utils.jmd95_xgcm_implementation as jmd95

    p = xr.zeros_like(ds_merge.Theta)  # reference pressure p = 0 (surface)

    rho = xr.apply_ufunc(
        jmd95.jmd95,
        ds_merge.Salt,
        ds_merge.Theta,
        p,
        dask="parallelized",
        output_dtypes=[float],
    )
    rho.name = "potential_density"
    rho.attrs["long_name"] = (
        "potential density referenced to surface (JMD95, p=0)")
    rho.attrs["units"] = "kg m-3"
    return rho


def potential_density_anomaly(ds_merge):
    """Potential density anomaly sigma0 = potential_density - RHO0 (lazy).

    The single canonical sigma0 routine: subtracts
    :data:`physical_constants.RHO0_REFERENCE` (1000 kg m^-3) from
    :func:`potential_density`.  Any code that needs sigma0 — the
    mixed-layer-depth criterion, the tile pipeline, buoyancy — should
    call this rather than re-implementing ``rho - 1000``.

    Parameters
    ----------
    ds_merge : xarray.Dataset
        Dataset containing 'Theta' and 'Salt'.

    Returns
    -------
    xarray.DataArray
        sigma0 [kg m^-3] on tracer points, dask-backed, with
        ``name="sigma0"``.

    Generated by LH and Claude
    """
    sigma0 = potential_density(ds_merge) - RHO0_REFERENCE
    sigma0.name = "sigma0"
    sigma0.attrs["long_name"] = (
        "potential density anomaly referenced to surface (JMD95, p=0)")
    sigma0.attrs["units"] = "kg m-3"
    return sigma0


def buoyancy_of_field(ds_merge):
    """Buoyancy b = G * sigma0 / RHO0 from the potential density anomaly.

    Parameters
    ----------
    ds_merge : xarray.Dataset
        Dataset containing 'Theta' and 'Salt'.

    Returns
    -------
    xarray.DataArray
        Buoyancy [m s^-2] on tracer points, dask-backed.

    Generated by LH and Claude
    """
    b = G * potential_density_anomaly(ds_merge) / RHO0_REFERENCE
    b.name = "buoyancy"
    b.attrs["long_name"] = "buoyancy b = g sigma0 / rho0 (JMD95, p=0)"
    b.attrs["units"] = "m s-2"
    return b


