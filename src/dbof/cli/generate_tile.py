"""
CLI entry point for generating a single LLC4320 tile of a chosen property.

This is a thin wrapper around ``tile_utils.run``: it parses CLI args (which
property to extract, and where the tile is) and delegates the entire pipeline
to :func:`dbof.tiles.tile_utils.run`.

The tile location may be given either as a rect-grid pixel (``--i``/``--j``)
or as a geographic coordinate (``--lon``/``--lat``).  Supply exactly one of
the two pairs; a geographic request is resolved to the nearest rect pixel via
the grid file, so a user does not need to know rect indices.

CLI usage
---------

    # by rect-grid pixel
    generate-tile --i 8123 --j 6044 \\
        --timestamp '2012-11-09 12:00:00' --property density

    # by geographic location (resolved to i, j via grid.zarr)
    generate-tile --lon -45.0 --lat 33.0 \\
        --timestamp '2012-11-09 12:00:00' --property temperature \\
        [--output ./out_dir] [--clobber] [--qa-plot] [--s3-config over.yaml]

``--property`` accepts any key registered in
:data:`dbof.tiles.tile_utils.TILE_PROPERTIES` (currently ``density``,
``temperature``, ``salinity``).  If ``--output`` is omitted, the NetCDF is
written to ``./{prefix}_tile{tile_idx:03d}_{YYYYMMDDTHH}.nc`` where
``{prefix}`` is the property's ``filename_prefix``
(``density``, ``theta``, ``salt``, ...).

Adding a new property does **not** require any change in this file -- just add
an entry to ``TILE_PROPERTIES`` in ``dbof/tiles/tile_utils.py``.

Generated by JXP and Claude
"""

# stdlib
from __future__ import annotations
import argparse
import logging
import sys
from pathlib import Path

from dbof.tiles import tile_utils


def _parse_args(argv=None) -> argparse.Namespace:
    """Build the CLI argument parser and parse ``argv``.

    Parameters
    ----------
    argv : list of str or None
        Argument list (default: ``sys.argv[1:]``).

    Returns
    -------
    argparse.Namespace
        Parsed arguments with attributes ``i``, ``j``, ``lon``, ``lat``,
        ``timestamp``, ``property``, ``output``, ``s3_config``, ``clobber``,
        ``qa_plot``.
    """
    p = argparse.ArgumentParser(
        description=(
            "Generate a 3D tile of one property (density / temperature / "
            "salinity / ...) for one LLC4320 snapshot."
        ),
    )
    p.add_argument(
        "--i", type=int, default=None,
        help=(
            "rect-grid i coord (0..17279); any pixel inside the desired tile. "
            "Use with --j, or use --lon/--lat instead."
        ),
    )
    p.add_argument(
        "--j", type=int, default=None,
        help=(
            "rect-grid j coord (0..12959); any pixel inside the desired tile. "
            "Use with --i, or use --lon/--lat instead."
        ),
    )
    p.add_argument(
        "--lon", type=float, default=None,
        help=(
            "target longitude (deg E); resolved to the nearest rect pixel via "
            "the grid file.  Use with --lat, or use --i/--j instead."
        ),
    )
    p.add_argument(
        "--lat", type=float, default=None,
        help=(
            "target latitude (deg N); resolved to the nearest rect pixel via "
            "the grid file.  Use with --lon, or use --i/--j instead."
        ),
    )
    p.add_argument(
        "--timestamp", type=str, required=True,
        help="timestamp 'YYYY-MM-DD HH:MM:SS'",
    )
    p.add_argument(
        "--property", dest="property", type=str, default="density",
        choices=sorted(tile_utils.TILE_PROPERTIES),
        help=(
            "Which property to extract.  Add new properties by registering "
            "them in tile_utils.TILE_PROPERTIES."
        ),
    )
    p.add_argument(
        "--output", type=str, default=None,
        help=(
            "Output path; if omitted, writes "
            "./{prefix}_tile{tile_idx:03d}_{YYYYMMDDTHH}.nc"
        ),
    )
    p.add_argument(
        "--s3-config", type=Path, default=tile_utils.DEFAULT_CONFIG,
        help=(
            "Optional legacy YAML override with an s3_source block.  If "
            "omitted, the canonical LLC_DEPTH source (data_sources.py) is used."
        ),
    )
    p.add_argument(
        "--clobber", action="store_true",
        help="Overwrite an existing output file instead of skipping.",
    )
    p.add_argument(
        "--qa-plot", dest="qa_plot", action="store_true",
        help="Also write a surface QA plot (PNG) next to the NetCDF.",
    )
    args = p.parse_args(argv)

    # Enforce exactly one location convention here so the CLI gives a clean
    # argparse-style error rather than surfacing a ValueError from ``run``.
    have_ij = args.i is not None and args.j is not None
    have_lonlat = args.lon is not None and args.lat is not None
    if have_ij == have_lonlat:
        p.error(
            "supply exactly one location: either --i and --j, or --lon and "
            "--lat"
        )
    return args


def main(argv=None) -> None:
    """CLI entry point: configure logging, parse args, dispatch to ``tile_utils.run``.

    Parameters
    ----------
    argv : list of str or None
        Argument list (default: ``sys.argv[1:]``).

    Returns
    -------
    None
        Side effect: writes a NetCDF (and, with ``--qa-plot``, a PNG) to disk.
    """
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(message)s",
        stream=sys.stdout,
    )
    args = _parse_args(argv)
    tile_utils.run(
        i_rect=args.i,
        j_rect=args.j,
        lon=args.lon,
        lat=args.lat,
        timestamp=args.timestamp,
        property=args.property,
        output=args.output,
        config_path=args.s3_config,
        clobber=args.clobber,
        gen_qa_plot=args.qa_plot,
    )


if __name__ == "__main__":
    main()

