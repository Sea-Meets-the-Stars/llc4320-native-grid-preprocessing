def edges_needing_a_rotated_halo(connections=None, facedim='face'):
    """Face edges whose halo cannot simply be copied from the neighbour.

    Two kinds qualify: connections that reach the neighbour along the
    OTHER axis (so a staggered component's halo would have to come from
    the neighbour's other component), and ``None`` connections (an open
    domain edge, where there is no neighbour at all).  Same-axis
    connections are copied correctly and are not listed.

    Derived from ``face_connections`` here rather than imported, so this
    diagnostic keeps working independently of the stencil code.

    Parameters
    ----------
    connections : dict, optional
        Face-connection mapping; defaults to the LLC4320 table.
    facedim : str, default 'face'
        Key of the outer connection dictionary.

    Returns
    -------
    set[tuple[int, str, str]]
        ``(face, axis, side)`` triples, ``side`` in {'lower', 'upper'}.

    Generated by LH and Claude
    """
    conn = (face_connections if connections is None else connections)[facedim]
    edges = set()
    for face, axes in conn.items():
        for axis, (lower, upper) in axes.items():
            for side, link in (('lower', lower), ('upper', upper)):
                if link is None or link[1] != axis:
                    edges.add((face, axis, side))
    return edges


