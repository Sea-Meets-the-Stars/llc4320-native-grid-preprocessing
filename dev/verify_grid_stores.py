def coord_attrs(ds):
    """Comodo attributes on the horizontal coordinate dims.

    Parameters
    ----------
    ds : xarray.Dataset
        Any grid dataset.

    Returns
    -------
    dict
        ``{dim: {'axis': ..., 'c_grid_axis_shift': ...}}``; a dim that is
        not a coordinate maps to ``None``.

    Generated by LH and Claude
    """
    out = {}
    for dim in COORD_DIMS:
        if dim not in ds.dims:
            out[dim] = None
        elif dim not in ds.coords:
            out[dim] = "dim only (no coordinate variable, no attrs)"
        else:
            attrs = ds.coords[dim].attrs
            out[dim] = {k: attrs.get(k) for k in
                        ("axis", "c_grid_axis_shift") if k in attrs}
    return out


def shift_to_position(shift):
    """Translate a ``c_grid_axis_shift`` into xgcm's position name.

    Parameters
    ----------
    shift : float or None
        The attribute value.

    Returns
    -------
    str
        ``'left'``, ``'right'``, or a description of what is missing.

    Generated by LH and Claude
    """
    if shift is None:
        return "MISSING"
    try:
        value = float(shift)
    except (TypeError, ValueError):
        return f"UNPARSEABLE ({shift!r})"
    if value == -0.5:
        return "left  (west/south edge -- MITgcm + xmitgcm convention)"
    if value == 0.5:
        return "right (east/north edge)"
    return f"INVALID ({value})"


def stage_attrs(osn_raw, osn_proc, dep_raw, dep_proc, dep_store):
    """Report what each store declares, before and after processing.

    Parameters
    ----------
    osn_raw, osn_proc, dep_raw, dep_proc : xarray.Dataset
        Grids at the two stages of each path.
    dep_store : xarray.Dataset or None
        The DEPTH store opened without the reader's stamping.

    Returns
    -------
    bool
        True when both paths end up on the same convention.

    Generated by LH and Claude
    """
    print("\n" + "=" * 70)
    print("STAGE 1: comodo attributes")
    print("=" * 70)
    print("xgcm reads c_grid_axis_shift as a SIGNED direction "
          "(xgcm/comodo.py):")
    print("  -0.5 -> 'left'   +0.5 -> 'right'   anything else -> error")
    print("xmitgcm stamps -0.5 on i_g/j_g (xmitgcm/variables.py).\n")

    stages = [("OSN   store  (get_remote_gridfile)", osn_raw),
              ("OSN   processed", osn_proc),
              ("DEPTH store  (raw zarr, unstamped)", dep_store),
              ("DEPTH reader (get_llc_depth_gridfile)", dep_raw),
              ("DEPTH processed", dep_proc)]
    for label, ds in stages:
        if ds is None:
            print(f"{label:38s}  (unavailable)")
            continue
        print(f"{label}")
        for dim, attrs in coord_attrs(ds).items():
            if attrs is None:
                continue
            if isinstance(attrs, str):
                print(f"    {dim:4s} {attrs}")
                continue
            shift = attrs.get("c_grid_axis_shift")
            note = (f"  -> {shift_to_position(shift)}"
                    if dim.endswith("_g") else "")
            print(f"    {dim:4s} {attrs}{note}")
        print()

    def staggered_shift(ds):
        if ds is None:
            return None
        attrs = coord_attrs(ds).get("i_g")
        if not isinstance(attrs, dict):
            return None
        return attrs.get("c_grid_axis_shift")

    osn_shift = staggered_shift(osn_proc)
    dep_shift = staggered_shift(dep_proc)
    agree = (osn_shift is not None and dep_shift is not None
             and float(osn_shift) == float(dep_shift))
    print(f"RESULT: OSN i_g = {osn_shift!r}, DEPTH i_g = {dep_shift!r}"
          f"  ->  {'AGREE' if agree else 'DISAGREE'}")
    if not agree:
        print("  The two pipelines are using different C-grid registrations."
              "\n  Stage 4 decides which one the data itself supports.")
    return agree


