def main(argv=None):
    """Parse arguments, run the requested stages, and report.

    Parameters
    ----------
    argv : list of str, optional
        Command-line arguments; defaults to ``sys.argv[1:]``.

    Returns
    -------
    int
        0 when every stage passed, 1 otherwise.

    Generated by LH and Claude
    """
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--stages", nargs="+", choices=ALL_STAGES,
                        default=DEFAULT_STAGES)
    parser.add_argument("--variables", nargs="+", default=SHARED_VARS)
    parser.add_argument("--stride", type=int, default=24)
    parser.add_argument("--face", type=int, default=1,
                        help="face used for the stage-4 geometry test")
    parser.add_argument("--output-dir", type=Path,
                        default=Path("dev/output/grid_stores"))
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args(argv)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    figures = not args.no_figures

    print("Loading OSN kerchunk grid ...")
    osn_raw, osn_proc = load_osn_grid()
    print("Loading LLC_DEPTH grid store ...")
    dep_raw, dep_proc = load_depth_grid()
    dep_store = (load_depth_store_unstamped()
                 if "attrs" in args.stages else None)

    results = {}
    if "attrs" in args.stages:
        results["attrs"] = stage_attrs(
            osn_raw, osn_proc, dep_raw, dep_proc, dep_store)
    if "vars" in args.stages:
        results["vars"] = stage_vars(osn_proc, dep_proc)
    if "native" in args.stages:
        results["native"] = stage_native(
            osn_proc, dep_proc, args.variables, args.output_dir,
            figures=figures, stride=args.stride)
    if "truth" in args.stages:
        results["truth"] = stage_truth(
            osn_raw, dep_raw, osn_proc, dep_proc, face=args.face)
    if "xgcm" in args.stages:
        results["xgcm"] = stage_xgcm(osn_proc, dep_proc)
    if "stitch" in args.stages:
        results["stitch"] = stage_stitch(
            osn_proc, dep_proc, args.variables, args.output_dir,
            figures=figures, stride=args.stride)

    print("\n" + "=" * 70)
    print("SUMMARY")
    print("=" * 70)
    for stage, passed in results.items():
        print(f"  {stage:8s} {'PASS' if passed else 'FAIL'}")
    report = args.output_dir / "grid_store_comparison.json"
    report.write_text(json.dumps(results, indent=2))
    print(f"\nreport -> {report}")
    return 0 if all(results.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
