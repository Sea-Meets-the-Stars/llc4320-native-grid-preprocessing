def stage_vars(osn, dep):
    """Compare variable inventories, shapes and dtypes.

    Parameters
    ----------
    osn, dep : xarray.Dataset
        Processed grids.

    Returns
    -------
    bool
        True when the shared variables match in shape and dtype.

    Generated by LH and Claude
    """
    print("\n" + "=" * 70)
    print("STAGE 2: variable inventory")
    print("=" * 70)
    osn_vars, dep_vars = set(osn.data_vars), set(dep.data_vars)
    only_osn = sorted(osn_vars - dep_vars)
    only_dep = sorted(dep_vars - osn_vars)
    if only_osn:
        print(f"  only in OSN   : {only_osn}")
    if only_dep:
        print(f"  only in DEPTH : {only_dep}")

    ok = True
    print(f"\n  {'variable':10s} {'dims':22s} {'OSN shape':18s} "
          f"{'DEPTH shape':18s} dtype")
    for name in sorted(osn_vars & dep_vars):
        a, b = osn[name], dep[name]
        same = a.shape == b.shape and a.dims == b.dims
        ok &= same
        flag = "" if same else "   <-- MISMATCH"
        print(f"  {name:10s} {str(a.dims):22s} {str(a.shape):18s} "
              f"{str(b.shape):18s} {a.dtype}/{b.dtype}{flag}")
    print(f"\nRESULT: shapes and dims {'match' if ok else 'DIFFER'}")
    return ok


