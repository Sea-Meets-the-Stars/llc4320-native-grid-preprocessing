def load_depth_store_unstamped(source=None, grid_store_name="grid.zarr"):
    """Open the DEPTH grid zarr WITHOUT the reader's attr stamping.

    ``get_llc_depth_gridfile`` overwrites ``c_grid_axis_shift`` on its way
    out, so this is the only way to see what the store itself declares.
    Mirrors that reader's URL and storage-option construction (its private
    helpers are reused deliberately -- this is a diagnostic, and the point
    is to read exactly the same object).

    Parameters
    ----------
    source : dict, optional
        As in :func:`load_depth_grid`.
    grid_store_name : str, default 'grid.zarr'
        Grid store name inside the folder.

    Returns
    -------
    xarray.Dataset or None
        The store as-is, or ``None`` if it could not be opened (the
        reason is printed).

    Generated by LH and Claude
    """
    src = dict(LLC_DEPTH_SOURCE if source is None else source)
    folder = src.get("grid_folder", src["folder"])
    try:
        url = get_raw_data._build_s3_store_url(
            src["bucket"], folder, grid_store_name)
        opts = get_raw_data._llc_depth_storage_options(src["s3_endpoint"])
        return xr.open_zarr(url, consolidated=False, storage_options=opts)
    except Exception as exc:                       # diagnostic, stay alive
        print(f"    (could not open the unstamped DEPTH store: "
              f"{type(exc).__name__}: {exc})")
        return None


