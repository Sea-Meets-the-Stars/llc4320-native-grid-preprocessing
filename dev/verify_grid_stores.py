"""Compare the OSN kerchunk grid with the LLC_DEPTH grid store, step by step.

Motivation
----------
The two pipelines load the SAME physical LLC4320 grid from different
stores, and they disagree about one thing: the comodo
``c_grid_axis_shift`` on ``i_g`` / ``j_g``.  ``get_remote_gridfile``
(OSN) passes through whatever the store carries; the LLC_DEPTH store
carries no comodo attributes at all, so ``get_llc_depth_gridfile``
supplies them -- which makes that literal the only record of where U and
V sit in that pipeline.

That attribute is not cosmetic.  xgcm reads it as a SIGNED direction
(``xgcm/comodo.py``): ``-0.5`` -> the staggered coordinate is at the
LEFT/WEST edge of its cell, ``+0.5`` -> the RIGHT/EAST edge.  MITgcm puts
``U`` on the west face, and xmitgcm stamps ``-0.5`` accordingly
(``xmitgcm/variables.py``).

Nothing about the FACES changes -- the stored arrays are identical, as
stage 3 confirms.  What changes is which PAIR OF CELLS each stencil
combines.  Interpolating a left-staggered ``U`` to centre ``i`` averages
``i_g[i]`` and ``i_g[i+1]``, so it reaches past the last index and needs
the UPPER halo; a right-staggered one averages ``i_g[i-1]`` and
``i_g[i]``, reaching past index 0 for the LOWER halo.  So a wrong sign
shifts every velocity-derived field one cell along the model axis, and
moves the halo-damaged column from one end of each face's index range to
the other -- which, since only some connections rotate the neighbour,
also changes WHICH faces are affected.

What this script does
---------------------
Walks both grids through the production path and compares them at every
stage, rather than trusting any single attribute:

1. ``attrs``    -- what each STORE declares, before and after the loaders
                   stamp anything.
2. ``vars``     -- inventory: variables, shapes, dtypes, chunking.
3. ``native``   -- per-face numeric comparison of every shared variable
                   on the raw face grid.
4. ``truth``    -- the decisive test, from the DATA rather than the
                   metadata: MITgcm defines ``dxC(i,j)`` as the distance
                   between tracer centres ``(i-1,j)`` and ``(i,j)``, so
                   the great-circle distance between ``XC[i-1]`` and
                   ``XC[i]`` must equal ``dxC[i]`` under the LEFT
                   convention, and ``dxC[i-1]`` under RIGHT.  Uses only
                   XC/YC/dxC/dyC, which both stores carry.
5. ``xgcm``     -- what each grid's declared attrs actually make xgcm do,
                   and which face edges become seams under each.
6. ``stitch``   -- run both through the same face->latlon stitch and
                   compare the rasters.

Run it from the repo root on the server.  OSN is public; the LLC_DEPTH
store needs dbof credentials (docs/Testing.md)::

    conda activate llcngp
    export AWS_ACCESS_KEY_ID=...
    export AWS_SECRET_ACCESS_KEY=...

    # the question at hand -- seconds, metadata + geometry only
    python dev/verify_grid_stores.py --stages attrs truth --no-figures

    # full comparison of the two stores on the native face grid
    python dev/verify_grid_stores.py --stages attrs vars native truth xgcm

    # heavy: stitches both grids to the 12960 x 17280 raster
    python dev/verify_grid_stores.py --stages stitch --stride 24

If the DEPTH store is unreachable, ``--stages attrs truth`` still reports
the OSN side on its own, which is the half that decides whether the
``+0.5`` stamp is right.

Options::

    --stages       Which stages to run (default: all but ``stitch``).
    --variables    Variables to compare numerically (default: the shared
                   horizontal set).
    --stride       Subsample stride for plotting / stitching (default 24).
    --output-dir   Where figures and the report are written (default
                   ``dev/output/grid_stores``).
    --no-figures   Skip plotting; print the numeric report only.

Exit status is non-zero if any comparison fails, so it can gate a
regeneration.

Generated by LH and Claude
"""

