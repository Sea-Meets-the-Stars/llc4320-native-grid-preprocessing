def stage_native(osn, dep, variables, out_dir, figures=True, stride=24):
    """Per-face numeric comparison on the raw face grid.

    Parameters
    ----------
    osn, dep : xarray.Dataset
        Processed grids.
    variables : list of str
        Variables to compare.
    out_dir : pathlib.Path
        Where figures are written.
    figures : bool, default True
        Whether to draw the per-face montage.
    stride : int, default 24
        Subsampling stride for the figure only.

    Returns
    -------
    bool
        True when every compared variable is identical to float tolerance.

    Generated by LH and Claude
    """
    print("\n" + "=" * 70)
    print("STAGE 3: native (per-face) values")
    print("=" * 70)
    print("  Same physical grid from two stores -- these should be equal.\n")
    print(f"  {'variable':10s} {'max |diff|':>14s} {'max rel diff':>14s} "
          f"{'worst face':>11s}")

    ok = True
    for name in variables:
        if name not in osn or name not in dep:
            print(f"  {name:10s} (absent from one store -- skipped)")
            continue
        a, b = osn[name], dep[name]
        if a.dims != b.dims or a.shape != b.shape:
            print(f"  {name:10s} shape/dims mismatch -- skipped")
            ok = False
            continue
        diff = np.abs(a - b)
        scale = np.maximum(np.abs(a), 1e-30)
        max_abs = float(diff.max().compute())
        max_rel = float((diff / scale).max().compute())
        other = [d for d in diff.dims if d != "face"]
        per_face = diff.max(dim=other).compute()
        worst = int(per_face.argmax())
        good = max_rel < 1e-6
        ok &= good
        print(f"  {name:10s} {max_abs:14.6e} {max_rel:14.6e} "
              f"{worst:11d}{'' if good else '   <-- DIFFERS'}")

    if figures:
        _plot_face_montage(osn, dep, "XC", out_dir, stride)
    print(f"\nRESULT: native values {'match' if ok else 'DIFFER'}")
    return ok


def _plot_face_montage(osn, dep, name, out_dir, stride):
    """Draw OSN / DEPTH / difference for one variable, all 13 faces.

    Parameters
    ----------
    osn, dep : xarray.Dataset
        Processed grids.
    name : str
        Variable to draw.
    out_dir : pathlib.Path
        Output directory.
    stride : int
        Subsampling stride.

    Generated by LH and Claude
    """
    if name not in osn or name not in dep:
        return
    sub = dict(i=slice(None, None, stride), j=slice(None, None, stride))
    a = osn[name].isel(**{k: v for k, v in sub.items()
                          if k in osn[name].dims}).compute()
    b = dep[name].isel(**{k: v for k, v in sub.items()
                          if k in dep[name].dims}).compute()
    nface = a.sizes["face"]
    fig, axes = plt.subplots(3, nface, figsize=(2.0 * nface, 6.4),
                             constrained_layout=True)
    for f in range(nface):
        for row, (field, title) in enumerate(
                ((a, "OSN"), (b, "DEPTH"), (a - b, "OSN - DEPTH"))):
            ax = axes[row, f]
            cmap = "RdBu_r" if row == 2 else "viridis"
            ax.pcolormesh(field.isel(face=f).values, cmap=cmap)
            ax.set_xticks([])
            ax.set_yticks([])
            if row == 0:
                ax.set_title(f"face {f}", fontsize=8)
            if f == 0:
                ax.set_ylabel(title, fontsize=8)
    fig.suptitle(f"{name}: OSN vs LLC_DEPTH grid store "
                 f"(every {stride}th cell)", fontsize=11)
    path = out_dir / f"native_faces_{name}.png"
    fig.savefig(path, dpi=110)
    plt.close(fig)
    print(f"    figure -> {path}")


