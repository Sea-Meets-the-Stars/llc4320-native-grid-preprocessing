def stage_stitch(osn, dep, variables, out_dir, figures=True, stride=24):
    """Stitch both grids to lat-lon and compare the rasters.

    Parameters
    ----------
    osn, dep : xarray.Dataset
        Processed grids.
    variables : list of str
        Scalar variables to stitch (staggered fields are skipped).
    out_dir : pathlib.Path
        Output directory.
    figures : bool, default True
        Whether to draw the comparison figure.
    stride : int, default 24
        Subsampling stride applied AFTER stitching, for plotting only.

    Returns
    -------
    bool
        True when the stitched rasters match.

    Generated by LH and Claude
    """
    from dbof.utils.faces_to_latlon import stitch_and_mask

    print("\n" + "=" * 70)
    print("STAGE 6: face -> lat-lon stitch")
    print("=" * 70)

    centre_vars = [v for v in variables
                   if v in osn and v in dep
                   and set(osn[v].dims) == {"face", "j", "i"}]
    if not centre_vars:
        print("  no cell-centred variables to stitch -- skipped")
        return True
    print(f"  stitching {centre_vars}")

    ok = True
    rasters = {}
    for label, ds in (("OSN", osn), ("DEPTH", dep)):
        arr = stitch_and_mask(ds, centre_vars, mask_dict={})
        rasters[label] = np.asarray(arr)
        print(f"    {label}: {rasters[label].shape}")

    for idx, name in enumerate(centre_vars):
        a, b = rasters["OSN"][idx], rasters["DEPTH"][idx]
        both = np.isfinite(a) & np.isfinite(b)
        max_abs = float(np.abs(a[both] - b[both]).max()) if both.any() else 0.0
        nan_mismatch = int((np.isfinite(a) ^ np.isfinite(b)).sum())
        good = max_abs < 1e-6 and nan_mismatch == 0
        ok &= good
        print(f"    {name:10s} max |diff| = {max_abs:.6e} | "
              f"NaN-pattern mismatches = {nan_mismatch}"
              f"{'' if good else '   <-- DIFFERS'}")

    if figures:
        name = centre_vars[0]
        a = rasters["OSN"][0][::stride, ::stride]
        b = rasters["DEPTH"][0][::stride, ::stride]
        fig, axes = plt.subplots(3, 1, figsize=(11, 10),
                                 constrained_layout=True)
        for ax, field, title, cmap in (
                (axes[0], a, f"{name} -- OSN", "viridis"),
                (axes[1], b, f"{name} -- LLC_DEPTH", "viridis"),
                (axes[2], a - b, f"{name} -- difference", "RdBu_r")):
            im = ax.pcolormesh(field, cmap=cmap)
            ax.set_title(title, fontsize=10)
            ax.set_xticks([])
            ax.set_yticks([])
            fig.colorbar(im, ax=ax, shrink=0.85)
        path = out_dir / f"stitched_{name}.png"
        fig.savefig(path, dpi=110)
        plt.close(fig)
        print(f"    figure -> {path}")

    print(f"\nRESULT: stitched rasters {'match' if ok else 'DIFFER'}")
    return ok


