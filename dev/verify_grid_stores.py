def _haversine(lon0, lat0, lon1, lat1):
    """Great-circle distance [m] between two lon/lat arrays.

    Parameters
    ----------
    lon0, lat0, lon1, lat1 : array_like
        Degrees.

    Returns
    -------
    numpy.ndarray
        Distances in metres.

    Generated by LH and Claude
    """
    p0, p1 = np.radians(lat0), np.radians(lat1)
    dphi = p1 - p0
    dlam = np.radians(lon1 - lon0)
    h = (np.sin(dphi / 2) ** 2
         + np.cos(p0) * np.cos(p1) * np.sin(dlam / 2) ** 2)
    return 2 * EARTH_RADIUS_M * np.arcsin(np.sqrt(np.clip(h, 0, 1)))


def corner_registration(ds, face=1, sample=64):
    """Decide the registration from the CORNER coordinates, if present.

    MITgcm's ``XG``/``YG`` are the cell's south-west corner, so for cell
    ``i`` the u-point longitude ``XG[i]`` lies half a cell WEST of
    ``XC[i]``.  Testing which side ``XC[i]`` falls on is a HALF-CELL
    question (~1 km on LLC4320) and therefore immune to the sub-metre
    ambiguity that limits :func:`metric_registration`.

    Parameters
    ----------
    ds : xarray.Dataset
        Grid that still carries ``XG``/``YG`` (the raw store -- the
        ``process_llc4320_*grid`` filters drop them).
    face : int, default 1
        Face to test.
    sample : int, default 64
        Stride used when sampling rows/columns AFTER the neighbour
        differences are formed.

    Returns
    -------
    dict or None
        ``{'X': {...}, 'Y': {...}}`` with the fraction of sampled cells
        supporting each hypothesis and a verdict, or ``None`` when the
        corner coordinates are absent.

    Generated by LH and Claude
    """
    names = [(n, m) for n, m in (("XG", "XC"), ("YG", "YC"))
             if n in ds and m in ds]
    if len(names) < 1:
        return None

    out = {}
    for corner_name, centre_name, axis in (("XG", "XC", "X"),
                                           ("YG", "YC", "Y")):
        if corner_name not in ds or centre_name not in ds:
            continue
        g = np.asarray(ds[corner_name].isel(face=face))
        c = np.asarray(ds[centre_name].isel(face=face))
        # Neighbours must be taken BEFORE subsampling -- striding first
        # would compare cell i with cell i+sample.
        if axis == "X":
            g_here, g_next, centre = g[:, :-1], g[:, 1:], c[:, :-1]
        else:
            g_here, g_next, centre = g[:-1, :], g[1:, :], c[:-1, :]
        g_here = g_here[::sample, ::sample]
        g_next = g_next[::sample, ::sample]
        centre = centre[::sample, ::sample]
        # 'left'  : XG[i] <= XC[i] <= XG[i+1]  (corner i is cell i's west
        #           edge).  'right' is the mirror image.  Work with the
        #           signed offsets so a descending axis is handled too.
        step = g_next - g_here
        offset = centre - g_here
        with np.errstate(invalid="ignore", divide="ignore"):
            frac = offset / np.where(step == 0, np.nan, step)
        good = np.isfinite(frac)
        if not good.any():
            continue
        frac = frac[good]
        # frac ~ +0.5 -> centre sits between corner i and i+1 -> LEFT.
        # frac ~ -0.5 -> centre sits between corner i-1 and i -> RIGHT.
        left_votes = float(np.mean(np.abs(frac - 0.5) < 0.25))
        right_votes = float(np.mean(np.abs(frac + 0.5) < 0.25))
        out[axis] = {
            "median_fraction_of_cell": float(np.median(frac)),
            "left_support": left_votes,
            "right_support": right_votes,
            "verdict": ("left" if left_votes > right_votes else
                        "right" if right_votes > left_votes else
                        "inconclusive"),
        }
    return out or None


def metric_registration(ds, face=1):
    """Decide the registration from XC/YC and dxC/dyC.

    MITgcm defines ``dxC(i,j)`` as the distance between tracer centres
    ``(i-1,j)`` and ``(i,j)``, i.e. it sits on the WEST edge of cell
    ``(i,j)``.  Writing ``d[i] = geodesic(XC[i-1], XC[i])``:

    * LEFT  (``-0.5``): ``d[i] == dxC[i]``
    * RIGHT (``+0.5``): ``d[i] == dxC[i-1]``

    CAVEAT -- this test is only as sharp as the grid is non-uniform.
    The wrong alignment is wrong by one cell's worth of metric
    VARIATION, which on LLC4320 is well under a metre out of ~2 km, and
    our haversine is not MITgcm's own metric.  A constant bias between
    the two is therefore expected and is removed before comparing; what
    discriminates is the SCATTER.  When the two hypotheses are not
    clearly separated the verdict is ``'inconclusive'`` and
    :func:`corner_registration` should be used instead.

    Parameters
    ----------
    ds : xarray.Dataset
        Grid with ``XC``, ``YC``, ``dxC``, ``dyC``.
    face : int, default 1
        Face to test.

    Returns
    -------
    dict
        Per-axis scatter for each hypothesis, their separation ratio,
        and a verdict.

    Generated by LH and Claude
    """
    xc = np.asarray(ds["XC"].isel(face=face))
    yc = np.asarray(ds["YC"].isel(face=face))
    dxc = np.asarray(ds["dxC"].isel(face=face))
    dyc = np.asarray(ds["dyC"].isel(face=face))

    dx_between = _haversine(xc[:, :-1], yc[:, :-1], xc[:, 1:], yc[:, 1:])
    dy_between = _haversine(xc[:-1, :], yc[:-1, :], xc[1:, :], yc[1:, :])

    out = {}
    for axis, between, metric in (("X", dx_between, dxc),
                                  ("Y", dy_between, dyc)):
        if axis == "X":
            cand = {"left": metric[:, 1:], "right": metric[:, :-1]}
        else:
            cand = {"left": metric[1:, :], "right": metric[:-1, :]}
        cell = float(np.median(between))
        scatter = {}
        for name, arr in cand.items():
            residual = between - arr
            # Remove the constant haversine-vs-MITgcm bias; the
            # misalignment shows up as scatter, not offset.
            scatter[name] = float(np.std(residual - np.median(residual)))
        lo, hi = sorted(scatter.values())
        separation = (hi / lo) if lo > 0 else np.inf
        verdict = (min(scatter, key=scatter.get) if separation >= 3.0
                   else "inconclusive")
        out[axis] = {
            "cell_size_m": cell,
            "left_scatter_m": scatter["left"],
            "right_scatter_m": scatter["right"],
            "separation_ratio": separation,
            "verdict": verdict,
        }
    return out


def same_underlying_grid(a, b, face=1, names=("XC", "YC", "dxC", "dyC")):
    """Whether two stores hold numerically identical grid arrays.

    The corner test needs ``XG``/``YG``, which not every store carries.
    When the two stores demonstrably hold the SAME arrays, a verdict
    established on one transfers to the other -- the registration is a
    property of the grid, not of the store it was copied into.

    Parameters
    ----------
    a, b : xarray.Dataset
        Grids to compare.
    face : int, default 1
        Face to compare on.
    names : tuple of str
        Variables that must match.

    Returns
    -------
    (bool, dict)
        Whether every listed variable matches to float tolerance, and
        the per-variable max absolute difference.

    Generated by LH and Claude
    """
    diffs = {}
    for name in names:
        if name not in a or name not in b:
            diffs[name] = None
            continue
        va = a[name].isel(face=face)
        vb = b[name].isel(face=face)
        if va.shape != vb.shape:
            diffs[name] = np.inf
            continue
        diffs[name] = float(np.abs(np.asarray(va) - np.asarray(vb)).max())
    values = [d for d in diffs.values() if d is not None]
    return (bool(values) and all(d < 1e-6 for d in values)), diffs


def stage_truth(osn_raw, dep_raw, osn_proc, dep_proc, face=1):
    """Decide each grid's registration from the data, not the metadata.

    Runs the corner test first (sharp, half-cell scale) and falls back to
    the metric test (sub-metre, often inconclusive on a near-uniform
    grid).  A store with no corner coordinates inherits the other
    store's verdict when the two demonstrably hold the same arrays --
    otherwise a store that simply omitted ``XG``/``YG`` would escape the
    check entirely.

    Parameters
    ----------
    osn_raw, dep_raw : xarray.Dataset
        Grids as loaded, before the variable filters drop ``XG``/``YG``.
    osn_proc, dep_proc : xarray.Dataset
        The processed grids, used for the declared attributes.
    face : int, default 1
        Face to test.

    Returns
    -------
    bool
        True when every store's declared attribute matches the
        registration the data supports.

    Generated by LH and Claude
    """
    print("\n" + "=" * 70)
    print("STAGE 4: registration from the DATA (ignores all attributes)")
    print("=" * 70)

    stores = {"OSN": (osn_raw, osn_proc), "DEPTH": (dep_raw, dep_proc)}
    verdict_from_corners = {}

    # Pass 1: what can each store establish on its own?
    for label, (raw, proc) in stores.items():
        print(f"  {label} (face {face}):")
        corner = corner_registration(raw, face=face)
        if corner is None:
            print("    corner test: XG/YG absent from this store -- skipped")
        else:
            votes = []
            for axis, r in corner.items():
                print(f"    corner {axis}: centre sits "
                      f"{r['median_fraction_of_cell']:+.3f} of a cell from "
                      f"corner[i] | support left={r['left_support']:.2f} "
                      f"right={r['right_support']:.2f} "
                      f"-> {r['verdict'].upper()}")
                if r["verdict"] != "inconclusive":
                    votes.append(r["verdict"])
            if votes:
                verdict_from_corners[label] = max(set(votes), key=votes.count)

        if all(v in raw for v in ("XC", "YC", "dxC", "dyC")):
            for axis, r in metric_registration(raw, face=face).items():
                print(f"    metric {axis}: cell ~{r['cell_size_m']:.1f} m | "
                      f"scatter left={r['left_scatter_m']:.4f} m "
                      f"right={r['right_scatter_m']:.4f} m | "
                      f"separation x{r['separation_ratio']:.1f} "
                      f"-> {r['verdict'].upper()}")
        else:
            print("    metric test: XC/YC/dxC/dyC incomplete -- skipped")
        print()

    # Pass 2: transfer a verdict to any store that could not reach one,
    # provided the two stores hold the same arrays.
    identical, diffs = same_underlying_grid(osn_raw, dep_raw, face=face)
    inherited = {}
    for label in stores:
        if label in verdict_from_corners:
            continue
        donors = [d for d in verdict_from_corners if d != label]
        if identical and donors:
            donor = donors[0]
            inherited[label] = (verdict_from_corners[donor], donor)
    if inherited:
        shown = {k: (f"{v:.3e}" if isinstance(v, float) else v)
                 for k, v in diffs.items()}
        print(f"  The two stores hold identical arrays "
              f"(max |diff| {shown}),")
        print("  so a registration established on one applies to the "
              "other:")
        for label, (verdict, donor) in inherited.items():
            print(f"    {label} inherits '{verdict}' from {donor}")
        print()
    elif not identical:
        print(f"  Stores do NOT hold identical arrays (max |diff| "
              f"{diffs}); no verdict is transferred.\n")

    # Pass 3: compare each store's declared attribute with the verdict.
    ok = True
    for label, (_, proc) in stores.items():
        declared = coord_attrs(proc).get("i_g")
        declared = (declared.get("c_grid_axis_shift")
                    if isinstance(declared, dict) else None)
        expected = {-0.5: "left", 0.5: "right"}.get(
            float(declared) if declared is not None else None)
        if label in verdict_from_corners:
            data_says, how = verdict_from_corners[label], "own geometry"
        elif label in inherited:
            data_says, how = inherited[label][0], (
                f"inherited from {inherited[label][1]}")
        else:
            print(f"  {label}: declared {declared!r} -> {expected}; "
                  "data -> INCONCLUSIVE (no test could separate them)")
            continue
        agree = (expected == data_says)
        ok &= agree
        print(f"  {label}: declared {declared!r} -> {expected}; "
              f"data -> {data_says} ({how})  ==> "
              f"{'CONSISTENT' if agree else 'INCONSISTENT'}")
    print()
    print(f"RESULT: declared attributes {'match' if ok else 'CONTRADICT'} "
          "the data")
    return ok


