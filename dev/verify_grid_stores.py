def stage_xgcm(osn, dep):
    """Show the stencil consequences of each grid's declared attrs.

    Parameters
    ----------
    osn, dep : xarray.Dataset
        Processed grids.

    Returns
    -------
    bool
        True when both grids give xgcm the same axis positions.

    Generated by LH and Claude
    """
    print("\n" + "=" * 70)
    print("STAGE 5: what xgcm does with each grid")
    print("=" * 70)

    positions = {}
    for label, ds in (("OSN", osn), ("DEPTH", dep)):
        try:
            grid = set_xgcm_grid(ds, use_connections=True)
        except Exception as exc:
            print(f"  {label}: could not build xgcm Grid -- "
                  f"{type(exc).__name__}: {exc}")
            positions[label] = None
            continue
        coords = {ax: dict(grid.axes[ax].coords) for ax in ("X", "Y")
                  if ax in grid.axes}
        positions[label] = coords
        print(f"  {label}: {coords}")

        # Which halo does an interpolation to centres read, and therefore
        # which face edge becomes the seam?
        for axis in ("X", "Y"):
            entry = coords.get(axis, {})
            staggered = [p for p in entry if p != "center"]
            if not staggered:
                continue
            side = "upper" if staggered[0] == "left" else "lower"
            faces = sorted({f for f, ax, sd in edges_needing_a_rotated_halo()
                            if ax == axis and sd == side})
            print(f"      {axis}: staggered position '{staggered[0]}' -> "
                  f"reads the {side} halo -> seams on faces {faces}")

    agree = (positions.get("OSN") is not None
             and positions["OSN"] == positions.get("DEPTH"))
    print(f"\nRESULT: xgcm axis positions "
          f"{'AGREE' if agree else 'DISAGREE'} between the two pipelines")
    if not agree:
        print("  -> The faces themselves are identical (stage 3); what")
        print("     differs is which pair of cells each stencil combines.")
        print("     'left' reaches past the last index (upper halo), so the")
        print("     damaged column is a face's LAST; 'right' reaches past")
        print("     index 0 (lower halo), so it is the FIRST.  Every")
        print("     velocity-derived field is therefore shifted one cell")
        print("     along the model axis, and a different set of face edges")
        print("     is affected -- not because any face is flipped, but")
        print("     because only some connections rotate the neighbour.")
    return agree


